#!/bin/bash
# Оснастка визуальных проб — при каждом запуске сессии.
#
# Повод. Контейнер забирают во время пауз и собирают заново, а поставленное
# на его диск не возвращается: репозиторий приходит из GitHub, `playwright`
# — нет. Первая проба каждой новой сессии начиналась с установки, и однажды
# хранилище пакетов не ответило вовсе. Этот скрипт лежит в репозитории,
# значит переживает пересоздание вместе с ним.
#
# Хук не валит сессию. Не встало — говорим об этом словами и выходим с нулём:
# без проб работать хуже, чем с пробами, но лучше, чем никак.
set -uo pipefail

# На машине Константина ставить нечего — там всё своё.
if [ "${CLAUDE_CODE_REMOTE:-}" != "true" ]; then
  exit 0
fi

ставим() {           # ставим <модуль> <пакет>
  if python3 -c "import $1" 2>/dev/null; then
    echo "· $2 уже на месте"
    return 0
  fi
  echo "· ставим $2…"
  if pip install --quiet --disable-pip-version-check "$2" 2>&1 | tail -3; then
    python3 -c "import $1" 2>/dev/null \
      && echo "· $2 готов" \
      || echo "‼ $2 поставился, но не подключается"
  else
    echo "‼ $2 поставить не вышло — визуальные пробы работать не будут"
  fi
}

ставим playwright playwright
ставим PIL pillow

# Сам браузер лежит в образе, но с номером сборки в пути: он меняется при
# обновлении образа, и вписанный в пробу номер однажды перестал бы совпадать.
# Находим и передаём переменной — пробы читают её, а не выдумывают путь.
# Имя латиницей: имена переменных оболочки кириллицу не принимают.
BROWSERS_ROOT="${BM_BROWSERS:-/opt/pw-browsers}"   # подменяется в пробе
BROWSER=$(ls -d "$BROWSERS_ROOT"/chromium-*/chrome-linux/chrome 2>/dev/null | sort | tail -1)
if [ -n "${BROWSER}" ]; then
  echo "· браузер: ${BROWSER}"
  if [ -n "${CLAUDE_ENV_FILE:-}" ]; then
    echo "export BM_CHROMIUM=\"${BROWSER}\"" >> "$CLAUDE_ENV_FILE"
  fi
else
  echo "‼ Chromium в /opt/pw-browsers не найден — пробам нечем открывать страницу"
fi

exit 0
