#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Страж проб: правка боевого файла не заканчивается без прогона.

Срабатывает в конце хода (Stop). Если в ходе правился index.html или 404.html,
а ни одна проба check_*.py не запускалась, ход не завершается: в переписку
возвращается напоминание.

Повод. Правило «прогонять визуальную пробу на каждой видимой правке» записано
в CLAUDE.md, и дважды его оказалось недостаточно: правка уходила на тестовый
домен непроверенной, а обнаруживалось это уже по снимку экрана от Константина.
Причина не в забывчивости как таковой, а в том, что внимание к правилам падает
к концу длинной сессии, — а хук срабатывает одинаково и на первом ходе, и на
сотом.

Что считается прогоном: любая команда Bash, в которой встречается запуск файла
вида check_*.py. Этого достаточно: имена всех проб в проекте начинаются так,
и подделать признак случайно невозможно.

Чего страж намеренно не проверяет: какие именно пробы прогнаны и что они
показали. Решение, какая проба относится к правке, требует суждения, а страж
судить не умеет — он ловит только полное отсутствие проверки.
"""
import json
import os
import re
import subprocess
import sys

# Файлы, правка которых уезжает на домен и обязана быть проверена.
БОЕВЫЕ = ("index.html", "404.html")
# Опознаются они не по имени, а по репозиторию: «index.html» встречается где
# угодно, и страж, срабатывающий на чужом файле, хуже отсутствующего. Признак
# берётся из адреса origin — он один и тот же на любой машине и при любом
# пути внутри контейнера.
ПРИЗНАК_РЕПОЗИТОРИЯ = "calculator"
ПРОБА = re.compile(r"check_[\w\-]*\.py")


def прочитать_ввод():
    try:
        return json.loads(sys.stdin.read() or "{}")
    except json.JSONDecodeError:
        return {}


def записи_хода(путь):
    """Записи стенограммы после последнего обращения Константина.

    Ход — это то, что произошло с его последней реплики: правка, сделанная
    два хода назад и уже проверенная, снова стражем не считается.
    """
    try:
        строки = open(путь, encoding="utf-8").read().splitlines()
    except OSError:
        return []
    записи = []
    for строка in строки:
        строка = строка.strip()
        if not строка:
            continue
        try:
            запись = json.loads(строка)
        except json.JSONDecodeError:
            continue
        записи.append(запись)
    начало = 0
    for номер, запись in enumerate(записи):
        if запись.get("type") == "user" and not служебная(запись):
            начало = номер
    return записи[начало:]


def служебная(запись):
    """Ответ инструмента приходит ролью user — это не реплика человека."""
    содержимое = (запись.get("message") or {}).get("content")
    if isinstance(содержимое, list):
        return any(ч.get("type") == "tool_result" for ч in содержимое if isinstance(ч, dict))
    return False


def боевой(путь):
    """Правда ли этот файл принадлежит репозиторию калькулятора.

    Если репозиторий определить не удалось, страж молчит. Для блокирующей
    проверки ложная тишина дешевле ложной остановки: пропущенный прогон
    заметен на следующем же ходе, а остановка верной работы бьёт сразу.
    """
    if os.path.basename(путь) not in БОЕВЫЕ:
        return False
    каталог = os.path.dirname(os.path.abspath(путь)) or "."
    try:
        итог = subprocess.run(["git", "-C", каталог, "remote", "get-url", "origin"],
                              capture_output=True, text=True, timeout=30)
    except (FileNotFoundError, subprocess.TimeoutExpired):
        return False
    if итог.returncode != 0:
        return False
    return ПРИЗНАК_РЕПОЗИТОРИЯ in итог.stdout.lower()


def вызовы(записи):
    """Все обращения к инструментам в этих записях: имя и входные данные."""
    для_каждого = []
    for запись in записи:
        содержимое = (запись.get("message") or {}).get("content")
        if not isinstance(содержимое, list):
            continue
        for часть in содержимое:
            if isinstance(часть, dict) and часть.get("type") == "tool_use":
                для_каждого.append((часть.get("name") or "", часть.get("input") or {}))
    return для_каждого


def главная():
    ввод = прочитать_ввод()
    if ввод.get("stop_hook_active"):
        sys.exit(0)  # защита от зацикливания: страж уже держит этот ход
    путь = ввод.get("transcript_path") or ""
    if not путь:
        sys.exit(0)

    правленые, пробы = set(), False
    for имя, данные in вызовы(записи_хода(путь)):
        if имя in ("Edit", "Write", "NotebookEdit"):
            путь = str(данные.get("file_path") or "")
            if боевой(путь):
                правленые.add(os.path.basename(путь))
        elif имя == "Bash":
            if ПРОБА.search(str(данные.get("command") or "")):
                пробы = True

    if правленые and not пробы:
        перечень = " и ".join(sorted(правленые))
        print(
            f"В этом ходе правился {перечень}, но ни одна проба не запускалась.\n"
            "Прогони относящиеся к правке check_*.py и покажи итог — правка уезжает\n"
            "на тестовый домен, и непроверенной ей там делать нечего.",
            file=sys.stderr)
        sys.exit(2)
    sys.exit(0)


if __name__ == "__main__":
    главная()
