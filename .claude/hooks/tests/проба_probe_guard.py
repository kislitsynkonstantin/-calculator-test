# -*- coding: utf-8 -*-
"""Проба стража проб на собранных стенограммах.

Проверяется и то, что он ловит правку без прогона, и то, что он молчит во всех
случаях, когда прогон был или правки боевых файлов не было вовсе.
"""
import json, os, shutil, subprocess, tempfile

import pathlib as _путь
# Страж берётся тот, рядом с которым лежит проба: файлы скопированы в два
# репозитория, и жёсткий путь проверял бы всегда одну копию.
СТРАЖ = str(_путь.Path(__file__).resolve().parent.parent / 'probe-guard.py')
зам, отч = [], []
def факт(у, т): (отч if у else зам).append(("    ок  " if у else "") + т)

def реплика(текст):
    return {"type": "user", "message": {"role": "user", "content": текст}}
def ответ_инструмента():
    return {"type": "user", "message": {"role": "user",
            "content": [{"type": "tool_result", "content": "ок"}]}}
def вызов(имя, данные):
    return {"type": "assistant", "message": {"role": "assistant",
            "content": [{"type": "tool_use", "name": имя, "input": данные}]}}

def позвать(записи, держит=False):
    с = tempfile.NamedTemporaryFile('w', suffix='.jsonl', delete=False, encoding='utf-8')
    for з in записи: с.write(json.dumps(з, ensure_ascii=False) + "\n")
    с.close()
    ввод = json.dumps({"transcript_path": с.name, "stop_hook_active": держит})
    и = subprocess.run(['python3', СТРАЖ], input=ввод, capture_output=True, text=True, timeout=60)
    os.unlink(с.name)
    return и.returncode, (и.stderr or '').strip()

# Боевые файлы живут в репозитории калькулятора; для пробы он собирается
# на месте, чтобы страж опознавал их по origin, а не по имени.
import subprocess as _пр
КАЛЬК = tempfile.mkdtemp(prefix='calculator-test-')
_пр.run(['git', 'init', '-q', КАЛЬК], check=True)
_пр.run(['git', '-C', КАЛЬК, 'remote', 'add', 'origin',
         'https://github.com/kislitsynkonstantin/-calculator-test'], check=True)
for _и in ('index.html', '404.html'):
    open(os.path.join(КАЛЬК, _и), 'w').write('<html></html>')

ЧУЖОЙ = tempfile.mkdtemp(prefix='workspace-')
_пр.run(['git', 'init', '-q', ЧУЖОЙ], check=True)
_пр.run(['git', '-C', ЧУЖОЙ, 'remote', 'add', 'origin',
         'https://github.com/kislitsynkonstantin/vscode-workspace'], check=True)
open(os.path.join(ЧУЖОЙ, 'index.html'), 'w').write('<html></html>')

ПРАВКА = вызов("Edit", {"file_path": os.path.join(КАЛЬК, "index.html")})
ПРОБА  = вызов("Bash", {"command": "cd /tmp/s && timeout 600 python3 check_client_page.py"})

# ── ловит ─────────────────────────────────────────────────────────────────
код, текст = позвать([реплика("сделай"), ПРАВКА, ответ_инструмента()])
факт(код == 2 and "index.html" in текст, f"правка без прогона ловится: {текст[:70]!r}")
код, _ = позвать([реплика("сделай"),
                  вызов("Write", {"file_path": os.path.join(КАЛЬК, "404.html")})])
факт(код == 2, "правка клиентской страницы без прогона тоже ловится")

# Одноимённый файл в другом репозитории боевым не считается.
код, текст = позвать([реплика("сделай"),
                      вызов("Write", {"file_path": os.path.join(ЧУЖОЙ, "index.html")})])
факт(код == 0, f"index.html из другого репозитория стража не поднимает: {текст[:70]!r}")
код, _ = позвать([реплика("сделай"),
                  вызов("Write", {"file_path": "/нет/такого/index.html"})])
факт(код == 0, "файл вне репозитория стража не поднимает")

# ── молчит ────────────────────────────────────────────────────────────────
код, текст = позвать([реплика("сделай"), ПРАВКА, ответ_инструмента(), ПРОБА])
факт(код == 0, f"правка с прогоном проходит: код {код}, {текст[:60]!r}")
код, _ = позвать([реплика("сделай"), ПРОБА, ответ_инструмента(), ПРАВКА])
факт(код == 0, "порядок не важен: прогон до правки тоже засчитывается")
код, _ = позвать([реплика("вопрос"),
                  вызов("Edit", {"file_path": os.path.join(КАЛЬК, "docs", "CHANGELOG.md")})])
факт(код == 0, "правка документации прогона не требует")
код, _ = позвать([реплика("макет"),
                  вызов("Write", {"file_path": os.path.join(КАЛЬК, "mockups", "новый.html")})])
факт(код == 0, "макет — не боевой файл, прогона не требует")
код, _ = позвать([реплика("просто вопрос")])
факт(код == 0, "ход без правок проходит")

# ── ход считается с последней реплики Константина ─────────────────────────
код, текст = позвать([реплика("первое"), ПРАВКА, ответ_инструмента(), ПРОБА,
                      реплика("второе"), ПРАВКА, ответ_инструмента()])
факт(код == 2, "прогон из прошлого хода нынешнюю правку не покрывает")
код, _ = позвать([реплика("первое"), ПРАВКА, ответ_инструмента(),
                  реплика("второе"), вызов("Read", {"file_path": "/x.md"})])
факт(код == 0, "правка прошлого хода нынешний ход не держит")

# ── защита от зацикливания ────────────────────────────────────────────────
код, _ = позвать([реплика("сделай"), ПРАВКА], держит=True)
факт(код == 0, "при stop_hook_active страж отходит в сторону — зацикливания нет")
код, _ = позвать([], держит=False)
факт(код == 0, "пустая стенограмма стража не роняет")

shutil.rmtree(КАЛЬК, ignore_errors=True); shutil.rmtree(ЧУЖОЙ, ignore_errors=True)
print("\n".join(отч)); print()
print("\n".join("ЗАМЕЧАНИЕ: " + з for з in зам) if зам else "Замечаний нет")
