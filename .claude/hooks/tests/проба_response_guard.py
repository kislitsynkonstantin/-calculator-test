# -*- coding: utf-8 -*-
"""Проба стража оформления — на собранных ответах и на настоящих.

Первая половина: подсовываем ответы с нарочно внесённым нарушением и смотрим,
что страж его называет. Вторая, более важная: прогоняем верные ответы, включая
настоящие реплики из стенограммы этой сессии, и смотрим, что он молчит.
"""
import glob, json, os, re, subprocess, tempfile

import pathlib as _путь
# Страж берётся тот, рядом с которым лежит проба: файлы скопированы в два
# репозитория, и жёсткий путь проверял бы всегда одну копию.
СТРАЖ = str(_путь.Path(__file__).resolve().parent.parent / 'response-guard.py')
зам, отч = [], []
def факт(у, т): (отч if у else зам).append(("    ок  " if у else "") + т)

def позвать(текст, держит=False):
    с = tempfile.NamedTemporaryFile('w', suffix='.jsonl', delete=False, encoding='utf-8')
    с.write(json.dumps({"type": "assistant", "message": {"role": "assistant",
            "content": [{"type": "text", "text": текст}]}}, ensure_ascii=False) + "\n")
    с.close()
    ввод = json.dumps({"transcript_path": с.name, "stop_hook_active": держит})
    и = subprocess.run(['python3', СТРАЖ], input=ввод, capture_output=True, text=True, timeout=60)
    os.unlink(с.name)
    return и.returncode, (и.stderr or '').strip()

ВЕРНЫЙ = """## What changed [Что изменилось]

The client page now renders the print sheet, with the same classes and sizes.

[Клиентская страница теперь собирает печатный лист теми же классами и кеглями.]

| Step | Result |
|---|---|
| Syntax | passed |

Both rows of the table say the same: the syntax check passed with no findings.

[Обе строки таблицы говорят одно: проверка синтаксиса пройдена, замечаний нет.]

## Summary [Итого]

1. The sheet is rebuilt on the print markup.
2. Probes are green.

[1. Лист пересобран на печатной разметке.
2. Пробы зелёные.]

---

*Отличный макет, внедряй для клиента*"""

код, текст = позвать(ВЕРНЫЙ)
факт(код == 0 and not текст, f"на верном ответе страж молчит: {текст[:100]!r}")

# ── ответ двумя половинами: это дрейф, а не вторая законная форма ──────────
# 17.09.2026 страж был научен такие ответы пропускать; 18.09.2026 поблажка
# снята. Скил требует пару на каждый абзац, и Константин читает именно так.
ПОЛОВИНАМИ = """## What changed [Что изменилось]

The client page now renders the print sheet with the same classes and sizes.
Probes are green, and nothing else on the page moved: the header keeps its
height, the totals strip keeps its place, and the print view is unchanged.

The check ran at three widths, as it always does, and the screenshots were read
as whole frames rather than as answers to the question asked.

---

Клиентская страница собирает печатный лист теми же классами и кеглями. Пробы
чистые, и больше на странице ничего не двигалось: шапка держит высоту, полоска
итога стоит на месте, вид печати прежний.

Проверка прогнана на трёх ширинах, как всегда, а снимки прочитаны кадром
целиком, а не ответом на заданный вопрос.

## Summary [Итого]

| Что | Состояние |
|---|---|
| Проверка синтаксиса | пройдена |

Обе строки таблицы говорят одно: проверка пройдена, замечаний нет.

*Ты попросил собрать клиентский лист теми же классами.*"""

код, текст = позвать(ПОЛОВИНАМИ)
факт("Русская проза без английской половины" in текст,
     f"ответ двумя половинами — находка, а не норма: {текст[:120]!r}")
факт(код == 2, f"находка держит ход, а не печатается в пустоту (код {код})")

код, текст = позвать(ПОЛОВИНАМИ.rsplit("*Ты попросил", 1)[0])
факт(код == 2 and "Эха просьбы" in текст,
     f"без эха страж останавливает ход (код {код}): {текст[:80]!r}")

# ── находки ────────────────────────────────────────────────────────────────
случаи = [
    ("билингва", ВЕРНЫЙ.replace(
        "[Клиентская страница теперь собирает печатный лист теми же классами и кеглями.]",
        "Клиентская страница теперь собирает печатный лист теми же классами и кеглями.")),
    ("сводка", ВЕРНЫЙ.replace("## Summary [Итого]", "## Итого [Summary]")),
    ("эхо", ВЕРНЫЙ.rsplit("---", 1)[0]),
    ("заголовки", ВЕРНЫЙ.replace("## What changed [Что изменилось]", "## What changed")),
    ("таблицы", ВЕРНЫЙ.replace(
        "Both rows of the table say the same: the syntax check passed with no findings.\n\n"
        "[Обе строки таблицы говорят одно: проверка синтаксиса пройдена, замечаний нет.]",
        "Both rows say the check passed.")),
    ("обращение", ВЕРНЫЙ.replace(
        "[Обе строки таблицы говорят одно: проверка синтаксиса пройдена, замечаний нет.]",
        "[Как вы видите, обе строки говорят одно: проверка пройдена.]")),
    ("ссылки", ВЕРНЫЙ.replace("Probes are green.",
                              "Probes are green, see test.calculator.baniamsk.ru/mockups/x.html")),
    ("преамбула", "Конечно! " + ВЕРНЫЙ),
    # Обе половины по-русски: пара формально на месте, а читать одно и то же
    # приходится дважды. Так вышли два ответа подряд 18.09.2026.
    ("перевод", ВЕРНЫЙ.replace(
        "The client page now renders the print sheet, with the same classes and sizes.",
        "Клиентская страница теперь собирает печатный лист теми же классами и кеглями.")),
]
ПРИЗНАК = {"билингва": "без английской половины", "сводка": "порядок английский",
           "эхо": "Эха просьбы", "заголовки": "Заголовки без русской половины",
           "таблицы": "нет русского абзаца", "обращение": "Обращение на «вы»",
           "ссылки": "без https", "преамбула": "с преамбулы",
           "перевод": "не переведена, а повторена"}
for имя, ответ in случаи:
    код, текст = позвать(ответ)
    факт(ПРИЗНАК[имя] in текст,
         f"находка «{имя}» называется: {текст.splitlines()[-1][:80] if текст else 'молчит'!r}")

# ── ложных срабатываний быть не должно ────────────────────────────────────
код, текст = позвать("Остановился.\n\n[Stopped.]")
факт(код == 0 and not текст, f"короткая реплика сводки и эха не требует: {текст[:60]!r}")

# «выложить», «выдать», «вывод» — не обращение на «вы»
код, текст = позвать(ВЕРНЫЙ.replace(
    "[Обе строки таблицы говорят одно: проверка синтаксиса пройдена, замечаний нет.]",
    "[Выложил, выдал ссылку и сделал вывод: проверка синтаксиса пройдена.]"))
факт("обращение" not in текст, f"«выложил/выдал/вывод» за «вы» не принимаются: {текст[:80]!r}")

# эхо с «вы» в словах Константина не должно браковать верный ответ
код, текст = позвать(ВЕРНЫЙ.replace("*Отличный макет, внедряй для клиента*",
                                    "*Как вы это сделали? Покажите ваш план*"))
факт("обращение" not in текст, f"«вы» в эхе просьбы не считается: {текст[:80]!r}")

# Русская половина под таблицей стоит одна и несёт её содержание — этого
# требует само правило таблиц, и «перевод» на неё ругаться не должен.
код, текст = позвать(ВЕРНЫЙ.replace(
    "Both rows of the table say the same: the syntax check passed with no findings.\n\n"
    "[Обе строки таблицы говорят одно: проверка синтаксиса пройдена, замечаний нет.]",
    "[Обе строки таблицы говорят одно: проверка синтаксиса пройдена, замечаний нет.]"))
факт("не переведена" not in текст,
     f"русская половина под таблицей — не находка: {текст[:100]!r}")

код, _ = позвать(ВЕРНЫЙ, держит=True)
факт(код == 0, "при stop_hook_active страж отходит в сторону")

# ── настоящие ответы из стенограммы этой сессии ───────────────────────────
стенограммы = sorted(glob.glob('/root/.claude/projects/-home-user-vscode-workspace/*.jsonl'),
                     key=os.path.getmtime, reverse=True)
проверено, срабатываний, примеры = 0, 0, []
if стенограммы:
    свои = []
    for строка in open(стенограммы[0], encoding='utf-8'):
        try: з = json.loads(строка)
        except Exception: continue
        if з.get("type") != "assistant": continue
        с = (з.get("message") or {}).get("content")
        if not isinstance(с, list): continue
        т = "\n".join(ч.get("text","") for ч in с if isinstance(ч, dict) and ч.get("type")=="text")
        if т.strip() and "## Summary [Итого]" in т: свои.append(т)
    for т in свои[-12:]:
        код, текст = позвать(т)
        проверено += 1
        if текст:
            срабатываний += 1
            примеры.extend(с.strip()[:100] for с in текст.splitlines()
                            if с.strip().startswith('•'))
факт(проверено >= 5, f"настоящих содержательных ответов прогнано: {проверено}")
# На настоящих ответах страж срабатывает — и это не ложные находки, а тот самый
# перевёрнутый порядок, о котором предупреждает CLAUDE.md. Требуем не тишины,
# а однородности: все находки должны быть известного рода, иначе страж просто
# шумит.
# Смысл проверки — не тишина, а отсутствие выдумок: каждая находка на настоящем
# ответе обязана быть одного из известных родов. Ответы прошлых дней законно
# ловятся «эхом» и «таблицами» — правила вводились позже, чем они написаны;
# находка же с незнакомой формулировкой означала бы, что страж шумит.
чужие = [п for п in примеры if not any(з in п for з in ПРИЗНАК.values())]
факт(not чужие, f"находки на настоящих ответах — только известного рода: {чужие[:2]}")
отч.append(f"    ок  перевёрнутый порядок найден в {срабатываний} из {проверено} "
           f"последних содержательных ответов — ради этого страж и написан")

print("\n".join(отч)); print()
print("\n".join("ЗАМЕЧАНИЕ: " + з for з in зам) if зам else "Замечаний нет")
