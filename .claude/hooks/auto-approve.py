#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Автоодобрение запросов на разрешение — со списком исключений.

Константин 20.09.2026: «эти разрешения на запросы постоянные бесят. Ты можешь
сделать хук на автоодобрение или еще как-то обойти? Я всё равно не понимаю,
что ты там пишешь. Всё подтверждаю. А если ночью, то процесс зависает из-за
этого».

Ночной ход, упёршийся в вопрос, стоит до утра — это и есть главная цена
вопросов, а не раздражение. Поэтому по умолчанию хук отвечает «разрешено» и
ход идёт дальше.

**Но не на всё.** «Всё подтверждаю» — это про обычную работу: правки файлов,
пробы, коммиты, выкладку на тест. Есть десяток действий, которые нельзя
откатить и которые в три часа ночи никто не остановит: стирание папки,
переписывание истории ветки, `drop`/`truncate` в общей базе, выпуск на боевой
домен. Они по-прежнему спрашивают — не потому, что Константин должен читать
команду, а потому, что у такого действия должен быть человек.

**Окон с разрешением не остаётся ни одного.** 21.09.2026 Константин прислал
снимок окна «Execute Sql requests permission»: «вот эти сообщения до сих пор
появляются. Убери их, даже важные. Перед важными просто задавай вопрос
человеческим языком с восклицательным знаком». Прежний ответ `ask` — это и
есть окно с командой внутри; читать её он не берётся, а ночью такое окно
держит ход до утра.

Поэтому необратимое теперь не спрашивает окном, а **останавливается**:
хук отвечает `deny` и объясняет словами, что именно опасно. Вызов не
проходит, я спрашиваю Константина в переписке — человеческим языком, со
знаком ⚠️, — и, получив согласие, повторяю вызов с пометкой согласия:

  • в запросе к базе — строкой-комментарием `-- одобрено Константином`;
  • в команде оболочки — приставкой `ОДОБРЕНО_КОНСТАНТИНОМ=1`.

Пометка не защита от меня — она защита от забывчивости: поставить её можно
только осознанно, и в истории видно, что согласие было. Решение остаётся за
человеком, а окно исчезает.

Ответ хука — одно из трёх:
  • allow — пропустить без вопроса (по умолчанию и при пометке согласия);
  • deny  — остановить необратимое и объяснить, о чём спросить человека;
  • ask   — больше не используется: это и есть то самое окно.

Правило добавляется сюда, а не в настройки: здесь рядом лежит причина, по
которой оно написано, и её видно в минуту срабатывания.
"""
import json
import re
import sys

# ── Что по-прежнему спрашивает ───────────────────────────────────────────────
# Пара «что ищем в команде» → «как объяснить человеку, о чём его спрашивают».
ОПАСНЫЕ_КОМАНДЫ = [
    (re.compile(r"\bgit\s+push\b[^|;&]*\s(--force\b|-f\b|--force-with-lease\b)"),
     "переписывание истории ветки на сервере"),
    (re.compile(r"\bgit\s+reset\s+--hard\b"),
     "сброс рабочей копии: несохранённые правки пропадут"),
    (re.compile(r"\bgit\s+clean\b[^|;&]*\s-\w*f"),
     "стирание неотслеженных файлов"),
    (re.compile(r"\bgit\s+branch\s+(-D|--delete\s+--force)\b"),
     "удаление ветки вместе с её работой"),
    (re.compile(r"\bcurl\b[^|;&]*\|\s*(ba)?sh\b"),
     "скачанное из сети выполняется как команда"),
    (re.compile(r"\bwget\b[^|;&]*\|\s*(ba)?sh\b"),
     "скачанное из сети выполняется как команда"),
    (re.compile(r"\bsudo\b"),
     "права суперпользователя"),
    (re.compile(r">\s*/dev/sd|mkfs\b|dd\s+if=.*\bof=/dev/"),
     "запись мимо файловой системы"),
]

# Тот же список для запросов в базу: она общая у теста и боя, и правка видна
# клиентам в ту же минуту.
ОПАСНЫЙ_SQL = [
    (re.compile(r"\bdrop\s+(table|schema|database|type|function|policy)\b", re.I),
     "удаление объекта базы"),
    (re.compile(r"\btruncate\b", re.I),
     "очистка таблицы целиком"),
    (re.compile(r"\bdelete\s+from\b(?![\s\S]*\bwhere\b)", re.I),
     "удаление всех строк таблицы: нет `where`"),
    (re.compile(r"\bupdate\b(?![\s\S]*\bwhere\b)[\s\S]*\bset\b", re.I),
     "правка всех строк таблицы: нет `where`"),
    (re.compile(r"\balter\s+table\b[\s\S]*\bdrop\b", re.I),
     "удаление колонки"),
    (re.compile(r"\bgrant\b|\brevoke\b|\bcreate\s+policy\b|\bdrop\s+policy\b", re.I),
     "правка прав доступа к данным"),
]

# ── Разборы, которые не удаются одной строкой ────────────────────────────────

# Кавычки снимаются до сверки с образцами. Без этого `git commit -m 'убрал
# rm -rf из примера'` спрашивал бы разрешения на безобидный коммит: текст
# сообщения — не команда, и искать в нём опасные слова бессмысленно.
КАВЫЧКИ = re.compile(r"'[^']*'|\"[^\"]*\"")

# Стирание в блокноте сессии безобидно: он и заведён под черновики. Проверяется
# не «есть ли безопасный путь в строке», а «все ли цели безопасны»: вырезать
# путь из строки мало — от `rm -rf <путь>` остаётся `rm -rf`, и образец
# по-прежнему совпадает, а цели уже не видно.
БЕЗОПАСНЫЙ_КОРЕНЬ = re.compile(r"^(/tmp/claude-|/tmp/[^/]*scratchpad|/var/folders/)")
РЕКУРСИВНОЕ_СТИРАНИЕ = re.compile(
    r"\brm\s+((?:-\S+\s+)*)(?=\S)", re.UNICODE)

# Боевой репозиторий — именно `/home/user/calculator`, без «-test» и без
# продолжения имени. Путь может стоять и в `cd` перед командой, поэтому
# ищется он по всей строке, а не рядом с `git push`.
БОЕВОЙ_ПУТЬ = re.compile(r"(?<![\w-])/home/user/calculator(?![\w-])")
ГИТ_ЗАПИСЬ = re.compile(r"\bgit\s+(push|commit|merge|rebase|tag)\b")


def рекурсивное_стирание_вне_блокнота(команда):
    """Есть ли в команде `rm -rf`, целящийся не в черновики.

    Возвращает True, когда хотя бы одна цель лежит вне безопасных корней или
    определить цель не удалось: в сомнении спрашиваем.
    """
    for кусок in re.split(r"[;&|]+", команда):
        слова = кусок.split()
        if not слова:
            continue
        # `cd … && rm …` уже разрезан по `&&`, поэтому команда — первое слово.
        try:
            место = слова.index("rm")
        except ValueError:
            continue
        ключи = [с for с in слова[место + 1:] if с.startswith("-")]
        цели = [с for с in слова[место + 1:] if not с.startswith("-")]
        буквы = "".join(ключи)
        рекурсивно = ("r" in буквы or "R" in буквы) and "f" in буквы
        if not рекурсивно:
            continue
        if not цели:
            return True                      # цели не видно — спрашиваем
        if any(not БЕЗОПАСНЫЙ_КОРЕНЬ.match(ц.strip("'\"")) for ц in цели):
            return True
    return False


# Пометка согласия: её ставлю я сам, получив ответ Константина в переписке.
СОГЛАСИЕ_SQL = re.compile(r"--\s*одобрено\s+константином", re.I)
СОГЛАСИЕ_КОМАНДА = re.compile(r"\bОДОБРЕНО_КОНСТАНТИНОМ=1\b")

КАК_СПРОСИТЬ = (" Окна больше нет: спроси Константина в переписке — словами,"
                " со знаком ⚠️, — и повтори вызов с пометкой согласия"
                " ({}).")


def остановить(причина, пометка):
    ответ("deny", "Остановлено нарочно: " + причина + "."
          + КАК_СПРОСИТЬ.format(пометка))


def ответ(решение, причина):
    print(json.dumps({
        "hookSpecificOutput": {
            "hookEventName": "PreToolUse",
            "permissionDecision": решение,
            "permissionDecisionReason": причина,
        }
    }, ensure_ascii=False))
    sys.exit(0)


def разобрать():
    try:
        return json.loads(sys.stdin.read() or "{}")
    except Exception:
        return {}


def главная():
    данные = разобрать()
    имя = данные.get("tool_name") or ""
    вход = данные.get("tool_input") or {}

    if имя == "Bash":
        команда = str(вход.get("command") or "")
        # Содержимое кавычек — текст, а не команда: сообщение коммита с
        # «rm -rf» внутри остаётся коммитом.
        без_кавычек = КАВЫЧКИ.sub(" '' ", команда)
        согласие = bool(СОГЛАСИЕ_КОМАНДА.search(команда))

        if not согласие:
            if рекурсивное_стирание_вне_блокнота(без_кавычек):
                остановить("рекурсивное стирание вне блокнота сессии — "
                           "отменить нечем", "ОДОБРЕНО_КОНСТАНТИНОМ=1")
            if БОЕВОЙ_ПУТЬ.search(без_кавычек) and ГИТ_ЗАПИСЬ.search(без_кавычек):
                остановить("запись в боевой репозиторий — выпуск идёт только "
                           "по слову Константина", "ОДОБРЕНО_КОНСТАНТИНОМ=1")
            for образец, причина in ОПАСНЫЕ_КОМАНДЫ:
                if образец.search(без_кавычек):
                    остановить(причина, "ОДОБРЕНО_КОНСТАНТИНОМ=1")
        ответ("allow", "Обычная работа — пропущено автоодобрением."
              if not согласие else "Согласие получено — пропущено с пометкой.")

    if "execute_sql" in имя or "apply_migration" in имя:
        запрос = str(вход.get("query") or вход.get("sql") or "")
        согласие = bool(СОГЛАСИЕ_SQL.search(запрос))
        if not согласие:
            for образец, причина in ОПАСНЫЙ_SQL:
                if образец.search(запрос):
                    остановить(причина + "; база общая у теста и боя — правка "
                               "видна клиентам сразу",
                               "-- одобрено Константином")
        ответ("allow", "Запрос к базе без разрушающих действий — пропущено."
              if not согласие else "Согласие получено — пропущено с пометкой.")

    # Всё прочее — чтение, правка файлов, пробы, поиск — идёт без вопроса.
    ответ("allow", "Пропущено автоодобрением.")


if __name__ == "__main__":
    главная()
