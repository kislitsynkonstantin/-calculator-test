#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Сверка черновика ответа теми же проверками, что и у стража, — до отправки.

Зачем это отдельно от `response-guard.py`. Страж — хук конца хода: он читает
ответ, который уже написан, и держит ход, пока я не напишу исправленный. Но
написанное к этому времени уже стоит в переписке, и оно там остаётся: 18.09.2026
Константин прислал снимок абзаца с двумя русскими половинами и спросил, почему
так, — он читал первую версию ответа, а исправленная лежала ниже. Страж сделал
свою работу и всё равно не уберёг: убрать из чата он ничего не может.

Поэтому содержательный ответ сначала кладётся черновиком в блокнот сессии и
прогоняется здесь. Проверки берутся у стража, а не переписываются: разойтись
две копии правил обязаны когда-нибудь, а расхождение здесь означало бы, что
черновик чист, а ход всё равно задержан.

    python3 .claude/hooks/сверить-ответ.py /путь/к/черновику.md

Выход нулевой и «чисто» — можно отправлять; иначе перечень замечаний и выход 1.
"""
import importlib.util
import io
import pathlib
import sys

СТРАЖ = pathlib.Path(__file__).resolve().parent / "response-guard.py"


def страж():
    описание = importlib.util.spec_from_file_location("страж_ответа", СТРАЖ)
    модуль = importlib.util.module_from_spec(описание)
    описание.loader.exec_module(модуль)
    return модуль


def главная():
    if len(sys.argv) < 2:
        print("Нужен путь к черновику ответа.", file=sys.stderr)
        return 2
    путь = pathlib.Path(sys.argv[1])
    if not путь.exists():
        print(f"Файла нет: {путь}", file=sys.stderr)
        return 2
    текст = io.open(путь, encoding="utf-8").read()
    м = страж()

    # Порог содержательности тот же, что у стража: короткая реплика правилам
    # оформления не подчиняется, и требовать от неё сводку было бы шумом.
    проза = м.re.sub(r"^\s*\|.*$", "", м.без_кода(текст), flags=м.re.M)
    содержательный = len(проза.strip()) >= м.ПОРОГ_СОДЕРЖАТЕЛЬНОСТИ

    находки = []
    for проверка in м.ПРОВЕРКИ:
        if not содержательный and проверка.__name__ in (
                "сводка", "эхо", "таблицы", "билингва", "перевод"):
            continue
        беда = проверка(текст)
        if беда:
            находки.append(f"  • {беда}")

    if находки:
        print("Черновик не готов — замечания:")
        print("\n".join(находки))
        return 1
    print("Чисто: черновик проходит те же проверки, что и страж конца хода.")
    return 0


if __name__ == "__main__":
    sys.exit(главная())
