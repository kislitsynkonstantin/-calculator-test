#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Страж оформления ответа: билингва, сводка, эхо, обращение, ссылки.

Срабатывает в конце хода (Stop) и читает последнее собственное сообщение из
стенограммы. Первое время работает вполсилы: находки печатаются, но ход не
останавливается (РЕЖИМ = 'предупреждать'). Причина в том, что признаки здесь
не такие однозначные, как синтаксис файла: часть проверок опирается на
регулярные выражения, и сломать блокировкой верный ответ было бы хуже, чем
пропустить неверный. Когда за неделю ложных срабатываний не окажется, пункты
«билингва», «сводка» и «эхо» переводятся в блокирующие — их правка дешёвая и
однозначная.

Почему эти правила вообще вынесены из CLAUDE.md. Они занимали в нём 23 % текста
и при этом отказывали чаще прочих: не от забывчивости, а оттого, что внимание
к формату падает к концу длинной сессии — первые ответы выходят парными, а к
двадцатому проза съезжает в одноязычную. Запись в файле от этого не спасает,
потому что файл читается один раз при запуске; хук читает ответ каждый раз.

История, ради которой правила писались, оставлена здесь же, у самих проверок:
она нужна в ту минуту, когда правило сработало, а не в минуту, когда сессия
только началась.
"""
import json
import re
import sys

РЕЖИМ = "блокировать"   # 'предупреждать' или 'блокировать'

# Короткая реплика вроде «Остановился.» сводки и эха не требует: правило
# CLAUDE.md говорит о содержательном ответе. Порог — в знаках прозы, без
# учёта блоков кода и таблиц.
ПОРОГ_СОДЕРЖАТЕЛЬНОСТИ = 400


def прочитать_ввод():
    try:
        return json.loads(sys.stdin.read() or "{}")
    except json.JSONDecodeError:
        return {}


def последнее_сообщение(путь):
    """Текст последней собственной реплики — без вызовов инструментов."""
    текст = None
    try:
        строки = open(путь, encoding="utf-8").read().splitlines()
    except OSError:
        return None
    for строка in строки:
        строка = строка.strip()
        if not строка:
            continue
        try:
            запись = json.loads(строка)
        except json.JSONDecodeError:
            continue
        if запись.get("type") != "assistant":
            continue
        содержимое = (запись.get("message") or {}).get("content")
        if not isinstance(содержимое, list):
            continue
        куски = [ч.get("text", "") for ч in содержимое
                 if isinstance(ч, dict) and ч.get("type") == "text"]
        куски = [к for к in куски if к.strip()]
        if куски:
            текст = "\n".join(куски)
    return текст


def без_кода(текст):
    """Проза: без блоков кода — внутри них правила оформления не действуют."""
    return re.sub(r"```.*?```", "", текст, flags=re.S)


def абзацы(текст):
    return [а.strip() for а in без_кода(текст).split("\n\n") if а.strip()]


КИРИЛЛИЦА = re.compile(r"[а-яёА-ЯЁ]")
ЛАТИНИЦА = re.compile(r"[a-zA-Z]")


def русский(строка):
    рус = len(КИРИЛЛИЦА.findall(строка))
    лат = len(ЛАТИНИЦА.findall(строка))
    return рус > лат and рус > 3


# ── отдельные проверки ─────────────────────────────────────────────────────

def эхо(текст):
    """Последний блок — просьба Константина, повторённая курсивом.

    Записано 13.08.2026: когда правок в работе несколько сразу, именно по эху
    он сверяет, что я взял, и на длинном ответе это избавляет от прокрутки.
    """
    части = абзацы(текст)
    if not части:
        return "Ответ пуст."
    if not re.match(r"^\*[^*].*\*$", части[-1].replace("\n", " ").strip(), re.S):
        return "Эха просьбы в конце нет: последний блок не набран курсивом."
    return None


def сводка(текст):
    """Блок «## Summary [Итого]» с нумерованным перечнем — перед эхом.

    Заголовок именно в этом порядке: до 16.08.2026 сводка была единственным
    местом, где русское шло первым, и это исключение отменено.
    """
    if "## Summary [Итого]" not in текст:
        if "## Итого [Summary]" in текст:
            return "Сводка озаглавлена по-русски: порядок английский — «## Summary [Итого]»."
        return "Нет блока «## Summary [Итого]» перед эхом просьбы."
    хвост = текст.split("## Summary [Итого]", 1)[1]
    # Перечень бывает нумерованным списком и таблицей: таблицей сводка идёт
    # с сентября 2026, и она читается лучше на телефоне. Годится и то, и другое,
    # лишь бы это был перечень, а не проза.
    if re.search(r"^\s*1[.)]\s", хвост, re.M) or re.search(r"^\s*\|.+\|", хвост, re.M):
        return None
    return "Сводка есть, но перечня в ней нет — ни списка, ни таблицы."


def билингва(текст):
    """Английский абзац и русский перевод в квадратных скобках под ним.

    Отказ 15.08.2026 и 16.08.2026 выглядел одинаково: первые пары выходят
    верными, а к середине технического ответа проза становится одноязычной.
    Считаем русские абзацы, не заключённые в скобки и не служебные.

    17.09.2026 сюда была добавлена поблажка: ответ, собранный двумя половинами
    через линейку, страж пропускал. Поблажка снята 18.09.2026 — она узаконила
    дрейф вместо того, чтобы его останавливать. Скил bilingual-response требует
    пару на каждый абзац («one paragraph in = one paragraph out»), и Константин
    читает именно так: английский абзац и сразу его перевод, а не текст и
    отдельно перевод всего текста.
    """
    одинокие = []
    for абзац in абзацы(текст):
        первая = абзац.splitlines()[0].strip()
        если_служебный = (
            первая.startswith(("#", ">", "|", "-", "*", "`"))
            or re.match(r"^\d+[.)]\s", первая)
            or первая.startswith("[")
            or re.match(r"^\*.*\*$", абзац.replace("\n", " ").strip(), re.S)
        )
        if если_служебный:
            continue
        if русский(абзац):
            одинокие.append(первая[:60])
    if одинокие:
        return ("Русская проза без английской половины — абзацы: "
                + "; ".join(f"«{о}…»" for о in одинокие[:3]))
    return None


def заголовки(текст):
    """Заголовок идёт строкой «## Английский [Русский]»."""
    плохие = []
    for строка in без_кода(текст).splitlines():
        if re.match(r"^#{2,3}\s", строка):
            подпись = re.sub(r"^#{2,3}\s+", "", строка).strip()
            if "[" not in подпись or not подпись.endswith("]"):
                плохие.append(подпись[:50])
    if плохие:
        return "Заголовки без русской половины: " + "; ".join(f"«{п}»" for п in плохие[:3])
    return None


def таблицы(текст):
    """После таблицы — русский абзац, несущий её содержание.

    Отмечено дважды 14.08.2026: таблицы остаются английскими, потому что
    двуязычные ячейки нечитаемы, и без абзаца под ними Константину не остаётся
    ничего.
    """
    части = абзацы(текст)
    для_каждой = []
    for номер, часть in enumerate(части):
        if not re.search(r"^\s*\|.*\|\s*$", часть, re.M):
            continue
        # Русскую половину ищем в двух следующих блоках, а не в одном: общий
        # порядок ставит английский абзац первым, и русский идёт под ним —
        # оба правила выполняются только парой, а не одним русским абзацем.
        следом = части[номер + 1: номер + 3]
        if not any(русский(с) for с in следом):
            для_каждой.append(часть.splitlines()[0][:50])
    if для_каждой:
        return ("После таблицы нет русского абзаца с её содержанием: "
                + "; ".join(f"«{т}…»" for т in для_каждой[:2]))
    return None


ОБРАЩЕНИЕ = re.compile(r"(?<![а-яё])(вы|вас|вам|вами|ваш|ваша|ваше|ваши|вашего|"
                       r"вашему|вашим|вашей|ваших)(?![а-яё])", re.I)


def обращение(текст):
    """Обращение на «ты».

    Проверка идёт по границе слова: без неё срабатывает «выложить», «выдать»,
    «вывод». И эхо просьбы из неё исключено — там дословно повторены слова
    Константина, и его собственное «вы» забраковало бы верный ответ.
    """
    части = абзацы(текст)
    тело = "\n\n".join(части[:-1]) if len(части) > 1 else (части[0] if части else "")
    тело = re.sub(r"«[^»]{0,400}»", "", тело)      # прямая речь и цитаты
    тело = re.sub(r"^>.*$", "", тело, flags=re.M)  # цитатные блоки
    # Слово, названное предметом разговора, обращением не является: в ячейке
    # таблицы и внутри обратных кавычек «вы» упоминают, а не обращаются им.
    # Найдено на собственном ответе про эти же хуки 13.09.2026.
    тело = re.sub(r"^\s*\|.*$", "", тело, flags=re.M)
    тело = re.sub(r"`[^`]{0,200}`", "", тело)
    найдено = [с.group(0) for с in ОБРАЩЕНИЕ.finditer(тело)]
    if найдено:
        return "Обращение на «вы»: " + ", ".join(sorted(set(найдено))[:4]) + " — принято «ты»."
    return None


def ссылки(текст):
    """Адрес, который надо открыть, даётся полной markdown-ссылкой.

    Без протокола интерфейс не делает адрес нажимаемым, и его приходится
    выделять вручную. Записано 15.08.2026.
    """
    голые = re.findall(r"(?<![/\w.])((?:test\.)?calculator\.baniamsk\.ru/[\w\-./]+)", без_кода(текст))
    голые = [г for г in голые if f"https://{г}" not in текст]
    беды = []
    if голые:
        беды.append("адрес без https:// и без ссылки: " + ", ".join(sorted(set(голые))[:2]))
    if re.search(r"github\.com/[\w\-]+/[\w\-]+/blob/", без_кода(текст)):
        беды.append("ссылка на исходник GitHub там, где страница открывается на домене")
    return "; ".join(беды) if беды else None


def преамбула(текст):
    первая = (абзацы(текст) or [""])[0].splitlines()[0].strip()
    if re.match(r"^(конечно|понял|хорошо|sure|got it|certainly|great)\b", первая, re.I):
        return f"Ответ начинается с преамбулы: «{первая[:40]}…»"
    return None


ПРОВЕРКИ = (билингва, заголовки, таблицы, обращение, ссылки, преамбула, сводка, эхо)
# Блокирует пока одно эхо — по прямой просьбе Константина 18.09.2026: «Почему
# перестал в конце ответа курсивом дублировать мой запрос? Если нужно, добавь
# это в хук». Предупреждения до него не доходили: страж пишет в stderr и выходит
# нулём, а такой вывод в этой среде модели не показывается. Признак эха
# однозначен — последний блок набран курсивом, — и ложная находка на нём
# невозможна. Остальные проверки остаются предупреждениями.
СТРОГИЕ = {"эхо"}


def главная():
    ввод = прочитать_ввод()
    if ввод.get("stop_hook_active"):
        sys.exit(0)
    путь = ввод.get("transcript_path") or ""
    текст = последнее_сообщение(путь) if путь else None
    if not текст:
        sys.exit(0)

    проза = re.sub(r"^\s*\|.*$", "", без_кода(текст), flags=re.M)
    содержательный = len(проза.strip()) >= ПОРОГ_СОДЕРЖАТЕЛЬНОСТИ

    находки = []
    for проверка in ПРОВЕРКИ:
        # Короткая реплика в одно-два слова правилам оформления не подчиняется:
        # так сказано и в самом CLAUDE.md — исключение ровно для неё.
        if not содержательный and проверка.__name__ in (
                "сводка", "эхо", "таблицы", "билингва"):
            continue
        беда = проверка(текст)
        if беда:
            находки.append((проверка.__name__, беда))

    if not находки:
        sys.exit(0)
    печать = "\n".join(f"  • {б}" for _, б in находки)
    строго = РЕЖИМ == "блокировать" and any(и in СТРОГИЕ for и, _ in находки)
    print("Оформление ответа — замечания:\n" + печать, file=sys.stderr)
    sys.exit(2 if строго else 0)


if __name__ == "__main__":
    главная()
