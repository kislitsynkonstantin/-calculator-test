def сдвиг_тона(тон):
    return 0.0 if тон == "эталон" else float(тон) - 184


def повернуть(ш6, сдвиг):
    """Поворот тона с сохранением светлоты и насыщенности."""
    r, g, b = (int(ш6[к:к + 2], 16) / 255 for к in (0, 2, 4))
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    r, g, b = colorsys.hls_to_rgb(((h * 360 + сдвиг) % 360) / 360, l, s)
    return "%02x%02x%02x" % tuple(round(x * 255) for x in (r, g, b))


def яркость(ш6):
    """Относительная яркость по WCAG — та, от которой считается контраст."""
    к = [int(ш6[и:и + 2], 16) / 255 for и in (0, 2, 4)]
    к = [x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4 for x in к]
    return 0.2126 * к[0] + 0.7152 * к[1] + 0.0722 * к[2]


def повернуть_с_яркостью(ш6, сдвиг):
    """Поворот тона с прежней насыщенностью и прежней яркостью для глаза:
    светлота подбирается так, чтобы контраст с любым фоном не изменился."""
    r, g, b = (int(ш6[к:к + 2], 16) / 255 for к in (0, 2, 4))
    h, _, s = colorsys.rgb_to_hls(r, g, b)
    нужно, h2 = яркость(ш6), ((h * 360 + сдвиг) % 360) / 360
    низ, верх = 0.0, 1.0
    for _ in range(40):
        середина = (низ + верх) / 2
        rr, gg, bb = colorsys.hls_to_rgb(h2, середина, s)
        if яркость(rgb_шестн(*(round(x * 255) for x in (rr, gg, bb)))) < нужно:
            низ = середина
        else:
            верх = середина
    rr, gg, bb = colorsys.hls_to_rgb(h2, (низ + верх) / 2, s)
    return rgb_шестн(*(round(x * 255) for x in (rr, gg, bb)))


def картинка(оригинал, тон):
    """Картинка под тон: на эталоне — оригинал байт в байт, иначе фирменные
    пиксели (те же 175–195° тона, что и у цветов) повёрнуты, прозрачность и
    серые — как были. Сжатие детерминированное: одна и та же картинка под
    один и тот же тон всегда даёт одни и те же байты."""
    if тон == "эталон":
        return оригинал
    from PIL import Image
    сдвиг = сдвиг_тона(тон)
    им = Image.open(io.BytesIO(оригинал)).convert("RGBA")
    пиксели = им.load()
    цвета = им.getcolors(1 << 24)
    # Картинка с белым рисунком стоит на тёмном: ночной логотип, значок
    # приложения. Поворот тона со светлотой по HLS делает синий темнее для
    # глаза — крыша ночного логотипа читалась бы 2,4:1 вместо 4,5:1 у
    # бирюзовой. Такие картинки держат яркость оригинала: контраст с фоном
    # остаётся ровно прежним. Картинки с тёмным рисунком стоят на светлом и
    # идут за палитрой как есть.
    нейтр = [(н, r + g + b) for н, (r, g, b, a) in цвета
             if a > 200 and not фирменный(rgb_шестн(r, g, b))]
    светлая = sum(н * с for н, с in нейтр) / max(1, sum(н for н, _ in нейтр)) > 3 * 128
    замена = {}
    for _, (r, g, b, a) in цвета:
        ш6 = rgb_шестн(r, g, b)
        if фирменный(ш6):
            н = повернуть_с_яркостью(ш6, сдвиг) if светлая else повернуть(ш6, сдвиг)
            замена[(r, g, b)] = tuple(int(н[к:к + 2], 16) for к in (0, 2, 4))
    ш, в = им.size
    for y in range(в):
        for x in range(ш):
            r, g, b, a = пиксели[x, y]
            н = замена.get((r, g, b))
            if н:
                пиксели[x, y] = н + (a,)
    буфер = io.BytesIO()
    им.save(буфер, format="PNG", optimize=False, compress_level=9)
    return буфер.getvalue()


def перекрасить_картинки(было, стало):
    """Переводит картинки с тона `было` на тон `стало`: вшитые в страницы
    ищутся по своему нынешнему виду, файлы на домене переписываются."""
    import base64
    оригиналы = [п for п in sorted(ЛОГОТИПЫ.glob("встроенный-*.png"))]
    пары = [(base64.b64encode(картинка(п.read_bytes(), было)).decode(),
             base64.b64encode(картинка(п.read_bytes(), стало)).decode()) for п in оригиналы]
    сдв_было, сдв_стало = сдвиг_тона(было), сдвиг_тона(стало)
    for путь, вид in ФАЙЛЫ:
        if вид != "блок":
            continue
        т = путь.read_text(encoding="utf-8")
        for старая, новая in пары:
            т = т.replace("base64," + старая, "base64," + новая)
        # значок вкладки: цвет из эталона, повёрнутый под нужный тон
        def знак(м):
            ш6 = м.group(2).lower()
            for эт in ("1e6c72", "2a8f97"):
                if ш6 == (повернуть(эт, сдв_было) if сдв_было else эт):
                    return м.group(1) + (повернуть(эт, сдв_стало) if сдв_стало else эт)
            return м.group(0)
        т = ЗНАЧОК.sub(знак, т)
        путь.write_text(т, encoding="utf-8")
    for путь in ФАЙЛЫ_КАРТИНОК:
        путь.write_bytes(картинка((ЛОГОТИПЫ / путь.name).read_bytes(), стало))


def собрать(тон, картинки_были=None):
    эт = json.loads(ЭТАЛОН.read_text(encoding="utf-8"))
    значения = dict(эт["значения"])
    if тон != "эталон":
        # Поворот тона с сохранением светлоты и насыщенности: у каждого
        # оттенка остаётся его место в теме — светлая подложка остаётся
        # светлой подложкой, чернила — чернилами. Тон бирюзы в эталоне ~184°.
        сдвиг = сдвиг_тона(тон)
        for имя, ш6 in значения.items():
            значения[имя] = повернуть(ш6, сдвиг)
    # Картинки переводятся с того тона, на котором стоят сейчас: он записан
    # в блоке палитры. `картинки_были` — только для перехода, когда блок уже
    # был перекрашен, а картинки ещё нет.
    перекрасить_картинки(картинки_были or текущий_тон(), тон)
    блок = блок_палитры(значения, set(эт["rgb"]), тон)
    for путь, вид in ФАЙЛЫ:
        if вид != "блок":
            continue
        т = путь.read_text(encoding="utf-8")
        н, к = т.find(НАЧАЛО), т.find(КОНЕЦ)
        if н < 0 or к < 0:
            raise SystemExit(f"Блока палитры в {путь.name} нет — сначала `перевести`.")
        путь.write_text(т[:н] + блок + т[к + len(КОНЕЦ):], encoding="utf-8")
    print(f"палитра: {тон}, переменных {len(значения)}; справка берёт её из калькулятора")


if __name__ == "__main__":
    к = sys.argv[1] if len(sys.argv) > 1 else "остаток"
    if к == "перевести":
        перевести()
    elif к == "остаток":
        print(f"вписанных руками: {len(остаток())}")
    elif к == "собрать":
        собрать(sys.argv[2])
    else:
        raise SystemExit(__doc__)
