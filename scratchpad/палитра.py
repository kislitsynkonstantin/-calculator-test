ШЕСТН = re.compile(r"#([0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b")
RGBA = re.compile(r"rgba\(\s*(\d{1,3})\s*,\s*(\d{1,3})\s*,\s*(\d{1,3})\s*,")


def нормал(ш):
    if len(ш) == 3:
        ш = "".join(с * 2 for с in ш)
    return ш[:6].lower()


def фирменный(ш6):
    r, g, b = (int(ш6[к:к + 2], 16) / 255 for к in (0, 2, 4))
    if max(r, g, b) - min(r, g, b) < 0.02:
        return False
    h, _, _ = colorsys.rgb_to_hls(r, g, b)
    return 175 <= h * 360 <= 195


def rgb_шестн(r, g, b):
    return "%02x%02x%02x" % (int(r), int(g), int(b))


# ── Разметка файла на области: HTML, <style>, <script>, комментарии ─────────
def области(т):
    """Список (начало, конец, вид) — вид: html, css, js."""
    вышло, п, вид = [], 0, "html"
    while п < len(т):
        if вид == "html":
            м = re.compile(r"<(style|script)\b[^>]*>", re.I).search(т, п)
            if not м:
                вышло.append((п, len(т), "html")); break
            вышло.append((п, м.end(), "html"))
            п, вид = м.end(), ("css" if м.group(1).lower() == "style" else "js")
        else:
            закр = "</style>" if вид == "css" else "</script>"
            к = т.lower().find(закр, п)
            к = len(т) if к < 0 else к
            вышло.append((п, к, вид))
            п, вид = к, "html"
    return вышло


def комментарии(т, начало, конец, вид):
    """Промежутки-комментарии внутри области. В JS — грубо: /* */ и // до
    конца строки, если перед // не двоеточие (адреса) и не кавычка рядом.
    Ошибка здесь безопасна: цвет в ложном комментарии просто останется
    вписанным и попадёт в отчёт `остаток`."""
    кус = т[начало:конец]
    пром = [(начало + м.start(), начало + м.end())
            for м in re.finditer(r"/\*[\s\S]*?\*/", кус)]
    if вид == "js":
        for м in re.finditer(r"(?m)^[ \t]*//.*$", кус):
            пром.append((начало + м.start(), начало + м.end()))
        for м in re.finditer(r"(?m)(?<=[;{})\s])//(?!/).*$", кус):
            пром.append((начало + м.start(), начало + м.end()))
    if вид == "html":
        пром += [(начало + м.start(), начало + м.end())
                 for м in re.finditer(r"<!--[\s\S]*?-->", кус)]
    return пром


def места(т):
    """Все фирменные цвета: (позиция, конец, вид_записи, шестн6, альфа|None, область, в_комментарии)."""
    вышло = []
    строки_искл = []
    for и in ИСКЛЮЧЕНИЯ:
        for м in re.finditer(re.escape(и), т):
            н = т.rfind("\n", 0, м.start()) + 1
            к = т.find("\n", м.end()); к = len(т) if к < 0 else к
            строки_искл.append((н, к))
    блок = (т.find(НАЧАЛО), т.find(КОНЕЦ))
    for н, к, вид in области(т):
        ком = комментарии(т, н, к, вид)
        кус = т[н:к]
        for м in list(ШЕСТН.finditer(кус)) + list(RGBA.finditer(кус)):
            п = н + м.start()
            строка_н = т.rfind("\n", 0, п) + 1
            строка_к = т.find("\n", п)
            if строка_к - строка_н > 3000:
                continue                       # base64 и прочие вшитые файлы
            if блок[0] >= 0 and блок[0] <= п <= блок[1]:
                continue
            if any(а <= п < б for а, б in строки_искл):
                continue
            if м.re is ШЕСТН:
                ш = м.group(1)
                ш6 = нормал(ш)
                альфа = int(ш[6:8], 16) if len(ш) == 8 else None
                запись = "hex"
            else:
                ш6 = rgb_шестн(*м.groups())
                альфа = None
                запись = "rgba"
            if not фирменный(ш6):
                continue
            вышло.append(dict(п=п, к=н + м.end(), запись=запись, ш6=ш6, альфа=альфа,
                              вид=вид, коммент=any(а <= п < б for а, б in ком)))
    return sorted(вышло, key=lambda м: м["п"])


def имена(оттенки):
    """Оттенок → имя переменной: светлота в процентах и буква для соседей."""
    по_свет = {}
    for ш6 in оттенки:
        r, g, b = (int(ш6[к:к + 2], 16) / 255 for к in (0, 2, 4))
        h, l, s = colorsys.rgb_to_hls(r, g, b)
        по_свет.setdefault(round(l * 100), []).append((-s, ш6))
    вышло = {}
    for свет, ряд in по_свет.items():
        ряд.sort()
        for и, (_, ш6) in enumerate(ряд):
            вышло[ш6] = f"--br-{свет:02d}" + ("" if и == 0 else "абвгдежзиклмнопрстуф"[и - 1])
    return вышло


def блок_палитры(значения, с_rgb, тон="эталон"):
    """Текст блока между метками. значения: имя → шестн6. Тон записывается в
    сам блок: по нему видно, какая палитра стоит, и проба может проверить
    смену туда и обратно от текущей, а не только от бирюзы."""
    строки = [НАЧАЛО + " — блок пишет scratchpad/палитра.py, руками не править.",
              f"   Тон: {тон}.",
              "   Каждый фирменный оттенок — одна переменная; имя — светлота в процентах.",
              "   Смена цвета: python3 scratchpad/палитра.py собрать <тон>. */",
              ":root{"]
    for имя in sorted(значения, key=lambda и: (int(re.search(r"\d+", и).group()), и)):
        ш6 = значения[имя]
        ряд = f"  {имя}:#{ш6};"
        if имя in с_rgb:
            r, g, b = (int(ш6[к:к + 2], 16) for к in (0, 2, 4))
            ряд += f" {имя}-rgb:{r},{g},{b};"
        строки.append(ряд)
    строки.append("}")
    строки.append(КОНЕЦ)
    return "\n".join(строки)


def перевести():
    тексты = {путь: путь.read_text(encoding="utf-8") for путь, _ in ФАЙЛЫ}
    if any(НАЧАЛО in т for т in тексты.values()) or any("var(--br-" in т for т in тексты.values()):
        raise SystemExit("Файлы уже переведены на палитру. Смотри `остаток`.")
    места_ф = {путь: [м for м in места(тексты[путь]) if not м["коммент"]] for путь, _ in ФАЙЛЫ}
    оттенки = sorted({м["ш6"] for мм in места_ф.values() for м in мм})
    имя = имена(оттенки)
    с_rgb = {имя[м["ш6"]] for мм in места_ф.values() for м in мм
             if м["запись"] == "rgba" or м["альфа"] is not None}
    значения = {имя[ш]: ш for ш in оттенки}
    for путь, вид in ФАЙЛЫ:
        т = тексты[путь]
        for м in reversed(места_ф[путь]):
            и, ш6 = имя[м["ш6"]], м["ш6"]
            r, g, b = (int(ш6[к:к + 2], 16) for к in (0, 2, 4))
            зап_rgb = f", {r},{g},{b}" if вид == "запас" else ""
            зап = f", #{ш6}" if вид == "запас" else ""
            if м["запись"] == "rgba":
                новое = f"rgba(var({и}-rgb{зап_rgb}),"
            elif м["альфа"] is not None:
                новое = f"rgba(var({и}-rgb{зап_rgb}),{round(м['альфа'] / 255, 4)})"
            else:
                новое = f"var({и}{зап})"
            т = т[:м["п"]] + новое + т[м["к"]:]
        if вид == "блок":
            # Блок — перед первым <style>: переменные объявлены раньше, чем
            # ими пользуется хоть одно правило.
            стиль = '<style id="палитра">\n' + блок_палитры(значения, с_rgb) + "\n</style>\n"
            п = т.find("<style")
            т = т[:п] + стиль + т[п:]
        путь.write_text(т, encoding="utf-8")
        print(f"{путь.name}: мест {len(места_ф[путь])}")
    ЭТАЛОН.write_text(json.dumps({"значения": значения, "rgb": sorted(с_rgb)},
                                 ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"оттенков: {len(оттенки)}, пар rgb: {len(с_rgb)}")


def остаток(печать=True):
    """Фирменные цвета, оставшиеся вписанными руками, — по всем файлам."""
    ост = []
    for путь, _ in ФАЙЛЫ:
        if not путь.exists():
            continue
        т = путь.read_text(encoding="utf-8")
        for м in места(т):
            if м["коммент"]:
                continue
            # Запасное значение внутри var(--br-…, #…) — не вписанный цвет.
            if re.search(r"var\(--br-[^,()]*,\s*[^()]*$", т[max(0, м["п"] - 40):м["п"]]):
                continue
            ост.append(dict(м, файл=путь.name))
            if печать:
                н = т.rfind("\n", 0, м["п"]) + 1
                print(f"{путь.name}:{т.count(chr(10), 0, м['п']) + 1}\t#{м['ш6']}\t"
                      f"{т[max(н, м['п'] - 60):м['к'] + 30].strip()}")
    return ост


