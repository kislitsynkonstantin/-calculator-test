#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Палитра калькулятора: один блок, из которого берутся все фирменные цвета.

Константин 24.09.2026: «под цвет ты можешь подготовить структуру? Чтобы
остаться на основном цвете, но подготовить токены/цвета к замене одним
действием потом».

До этого бирюзовый жил в файле в двух видах: три четверти — в переменных
тем (`--green-*`, `--bl-*`, `--lg-*`), четверть — вписанным руками прямо в
правила, в атрибуты `style`, в строки, из которых собираются лист печати и
договор, и в `rgba(42,143,151,…)`. Переключатель цвета перекрасил бы первые
и оставил бы вторые бирюзовыми.

Теперь каждый фирменный оттенок — переменная `--br-NN` в одном блоке
`<style id="палитра">` в начале `index.html` (NN — светлота оттенка в
процентах, буква в конце различает оттенки одной светлоты). Для
полупрозрачных — пара `--br-NN-rgb` из трёх чисел: `rgba(var(--br-38-rgb),.2)`
даёт ровно тот же пиксель, что и прежнее `rgba(42,143,151,.2)`. Отдельные
документы, которые калькулятор собирает сам (окно печати, договор, график
платежей, печать комплектаций, справка), получают этот же блок вместе с
разметкой — функцией `сПалитрой(html)`.

Какие цвета фирменные: оттенок от 175° до 195° по кругу и хоть какая-то
насыщенность. Серые, белый, чёрный, красный ошибок, жёлтый предупреждений
остаются как были. Смысловые наборы, которые только случайно бирюзовые,
перечислены в ИСКЛЮЧЕНИЯ: цвет примечания выбирает сам менеджер, цвет роли
различает роли между собой — перекрашивать их вместе с темой нельзя.

    python3 палитра.py перевести     # однократный перевод файла на палитру
    python3 палитра.py остаток       # что осталось вписанным руками
    python3 палитра.py собрать 215   # палитра с основным тоном 215° (синий)
    python3 палитра.py собрать эталон   # вернуть бирюзовую

`собрать` и есть «одно действие»: переписывается только блок между метками,
остальной файл не трогается.
"""
import colorsys
import io
import json
import pathlib
import re
import sys

import os

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
ФАЙЛ = КОРЕНЬ / "index.html"
ЭТАЛОН = pathlib.Path(__file__).resolve().parent / "палитра-эталон.json"
СПРАВКА = pathlib.Path(os.environ.get(
    "BM_MANUAL_SRC", "/home/user/vscode-workspace/docs/справка"))

# Файлы и то, как в них ложится палитра:
#   блок  — свой блок переменных между метками (отдельная страница на домене);
#   запас — блока нет, у каждой переменной запасное значение: оболочки справки
#           лежат в общей с боевым доменом таблице, и боевой код, который
#           палитру в справку не вкладывает, должен видеть прежние цвета.
ФАЙЛЫ = [
    (ФАЙЛ, "блок"),
    (КОРЕНЬ / "404.html", "блок"),
    (СПРАВКА / "manual--shell.html", "запас"),
    (СПРАВКА / "guide--shell.html", "запас"),
]

НАЧАЛО = "/* ПАЛИТРА:НАЧАЛО"
КОНЕЦ = "/* ПАЛИТРА:КОНЕЦ */"

# Строки, где цвет смысловой, а не фирменный.
ИСКЛЮЧЕНИЯ = (
    "_LIST = ['#eab308'",          # набор цветов на выбор
    "noteHighlightColor:",         # цвет примечания — выбор менеджера
    "name: 'Мятный'",
    "ЦВЕТ_ПРИМЕЧАНИЙ_СНЯТЫЕ",
    "ROLE_COLORS",                 # цвета ролей различают роли между собой
    'id="themeColorMeta"',         # метатег: переменных не понимает
)

ШЕСТН = re.compile(r"#([0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b")
RGBA = re.compile(r"rgba\(\s*(\d{1,3})\s*,\s*(\d{1,3})\s*,\s*(\d{1,3})\s*,")


def нормал(ш):
    if len(ш) == 3:
        ш = "".join(с * 2 for с in ш)
    return ш[:6].lower()


def фирменный(ш6):
    r, g, b = (int(ш6[к:к + 2], 16) / 255 for к in (0, 2, 4))
    if max(r, g, b) - min(r, g, b) < 0.02:
        return False
    h, _, _ = colorsys.rgb_to_hls(r, g, b)
    return 175 <= h * 360 <= 195


def rgb_шестн(r, g, b):
    return "%02x%02x%02x" % (int(r), int(g), int(b))


# ── Разметка файла на области: HTML, <style>, <script>, комментарии ─────────
def области(т):
    """Список (начало, конец, вид) — вид: html, css, js."""
    вышло, п, вид = [], 0, "html"
    while п < len(т):
        if вид == "html":
            м = re.compile(r"<(style|script)\b[^>]*>", re.I).search(т, п)
            if not м:
                вышло.append((п, len(т), "html")); break
            вышло.append((п, м.end(), "html"))
            п, вид = м.end(), ("css" if м.group(1).lower() == "style" else "js")
        else:
            закр = "</style>" if вид == "css" else "</script>"
            к = т.lower().find(закр, п)
            к = len(т) if к < 0 else к
            вышло.append((п, к, вид))
            п, вид = к, "html"
    return вышло


def комментарии(т, начало, конец, вид):
    """Промежутки-комментарии внутри области. В JS — грубо: /* */ и // до
    конца строки, если перед // не двоеточие (адреса) и не кавычка рядом.
    Ошибка здесь безопасна: цвет в ложном комментарии просто останется
    вписанным и попадёт в отчёт `остаток`."""
    кус = т[начало:конец]
    пром = [(начало + м.start(), начало + м.end())
            for м in re.finditer(r"/\*[\s\S]*?\*/", кус)]
    if вид == "js":
        for м in re.finditer(r"(?m)^[ \t]*//.*$", кус):
            пром.append((начало + м.start(), начало + м.end()))
        for м in re.finditer(r"(?m)(?<=[;{})\s])//(?!/).*$", кус):
            пром.append((начало + м.start(), начало + м.end()))
    if вид == "html":
        пром += [(начало + м.start(), начало + м.end())
                 for м in re.finditer(r"<!--[\s\S]*?-->", кус)]
    return пром


def места(т):
    """Все фирменные цвета: (позиция, конец, вид_записи, шестн6, альфа|None, область, в_комментарии)."""
    вышло = []
    строки_искл = []
    for и in ИСКЛЮЧЕНИЯ:
        for м in re.finditer(re.escape(и), т):
            н = т.rfind("\n", 0, м.start()) + 1
            к = т.find("\n", м.end()); к = len(т) if к < 0 else к
            строки_искл.append((н, к))
    блок = (т.find(НАЧАЛО), т.find(КОНЕЦ))
    for н, к, вид in области(т):
        ком = комментарии(т, н, к, вид)
        кус = т[н:к]
        for м in list(ШЕСТН.finditer(кус)) + list(RGBA.finditer(кус)):
            п = н + м.start()
            строка_н = т.rfind("\n", 0, п) + 1
            строка_к = т.find("\n", п)
            if строка_к - строка_н > 3000:
                continue                       # base64 и прочие вшитые файлы
            if блок[0] >= 0 and блок[0] <= п <= блок[1]:
                continue
            if any(а <= п < б for а, б in строки_искл):
                continue
            if м.re is ШЕСТН:
                ш = м.group(1)
                ш6 = нормал(ш)
                альфа = int(ш[6:8], 16) if len(ш) == 8 else None
                запись = "hex"
            else:
                ш6 = rgb_шестн(*м.groups())
                альфа = None
                запись = "rgba"
            if not фирменный(ш6):
                continue
            вышло.append(dict(п=п, к=н + м.end(), запись=запись, ш6=ш6, альфа=альфа,
                              вид=вид, коммент=any(а <= п < б for а, б in ком)))
    return sorted(вышло, key=lambda м: м["п"])


def имена(оттенки):
    """Оттенок → имя переменной: светлота в процентах и буква для соседей."""
    по_свет = {}
    for ш6 in оттенки:
        r, g, b = (int(ш6[к:к + 2], 16) / 255 for к in (0, 2, 4))
        h, l, s = colorsys.rgb_to_hls(r, g, b)
        по_свет.setdefault(round(l * 100), []).append((-s, ш6))
    вышло = {}
    for свет, ряд in по_свет.items():
        ряд.sort()
        for и, (_, ш6) in enumerate(ряд):
            вышло[ш6] = f"--br-{свет:02d}" + ("" if и == 0 else "абвгдежзиклмнопрстуф"[и - 1])
    return вышло


def блок_палитры(значения, с_rgb):
    """Текст блока между метками. значения: имя → шестн6."""
    строки = [НАЧАЛО + " — блок пишет scratchpad/палитра.py, руками не править.",
              "   Каждый фирменный оттенок — одна переменная; имя — светлота в процентах.",
              "   Смена цвета: python3 scratchpad/палитра.py собрать <тон>. */",
              ":root{"]
    for имя in sorted(значения, key=lambda и: (int(re.search(r"\d+", и).group()), и)):
        ш6 = значения[имя]
        ряд = f"  {имя}:#{ш6};"
        if имя in с_rgb:
            r, g, b = (int(ш6[к:к + 2], 16) for к in (0, 2, 4))
            ряд += f" {имя}-rgb:{r},{g},{b};"
        строки.append(ряд)
    строки.append("}")
    строки.append(КОНЕЦ)
    return "\n".join(строки)


def перевести():
    тексты = {путь: путь.read_text(encoding="utf-8") for путь, _ in ФАЙЛЫ}
    if any(НАЧАЛО in т for т in тексты.values()) or any("var(--br-" in т for т in тексты.values()):
        raise SystemExit("Файлы уже переведены на палитру. Смотри `остаток`.")
    места_ф = {путь: [м for м in места(тексты[путь]) if not м["коммент"]] for путь, _ in ФАЙЛЫ}
    оттенки = sorted({м["ш6"] for мм in места_ф.values() for м in мм})
    имя = имена(оттенки)
    с_rgb = {имя[м["ш6"]] for мм in места_ф.values() for м in мм
             if м["запись"] == "rgba" or м["альфа"] is not None}
    значения = {имя[ш]: ш for ш in оттенки}
    for путь, вид in ФАЙЛЫ:
        т = тексты[путь]
        for м in reversed(места_ф[путь]):
            и, ш6 = имя[м["ш6"]], м["ш6"]
            r, g, b = (int(ш6[к:к + 2], 16) for к in (0, 2, 4))
            зап_rgb = f", {r},{g},{b}" if вид == "запас" else ""
            зап = f", #{ш6}" if вид == "запас" else ""
            if м["запись"] == "rgba":
                новое = f"rgba(var({и}-rgb{зап_rgb}),"
            elif м["альфа"] is not None:
                новое = f"rgba(var({и}-rgb{зап_rgb}),{round(м['альфа'] / 255, 4)})"
            else:
                новое = f"var({и}{зап})"
            т = т[:м["п"]] + новое + т[м["к"]:]
        if вид == "блок":
            # Блок — перед первым <style>: переменные объявлены раньше, чем
            # ими пользуется хоть одно правило.
            стиль = '<style id="палитра">\n' + блок_палитры(значения, с_rgb) + "\n</style>\n"
            п = т.find("<style")
            т = т[:п] + стиль + т[п:]
        путь.write_text(т, encoding="utf-8")
        print(f"{путь.name}: мест {len(места_ф[путь])}")
    ЭТАЛОН.write_text(json.dumps({"значения": значения, "rgb": sorted(с_rgb)},
                                 ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"оттенков: {len(оттенки)}, пар rgb: {len(с_rgb)}")


def остаток(печать=True):
    """Фирменные цвета, оставшиеся вписанными руками, — по всем файлам."""
    ост = []
    for путь, _ in ФАЙЛЫ:
        if not путь.exists():
            continue
        т = путь.read_text(encoding="utf-8")
        for м in места(т):
            if м["коммент"]:
                continue
            # Запасное значение внутри var(--br-…, #…) — не вписанный цвет.
            if re.search(r"var\(--br-[^,()]*,\s*[^()]*$", т[max(0, м["п"] - 40):м["п"]]):
                continue
            ост.append(dict(м, файл=путь.name))
            if печать:
                н = т.rfind("\n", 0, м["п"]) + 1
                print(f"{путь.name}:{т.count(chr(10), 0, м['п']) + 1}\t#{м['ш6']}\t"
                      f"{т[max(н, м['п'] - 60):м['к'] + 30].strip()}")
    return ост


def собрать(тон):
    эт = json.loads(ЭТАЛОН.read_text(encoding="utf-8"))
    значения = dict(эт["значения"])
    if тон != "эталон":
        # Поворот тона с сохранением светлоты и насыщенности: у каждого
        # оттенка остаётся его место в теме — светлая подложка остаётся
        # светлой подложкой, чернила — чернилами. Тон бирюзы в эталоне ~184°.
        сдвиг = float(тон) - 184
        for имя, ш6 in значения.items():
            r, g, b = (int(ш6[к:к + 2], 16) / 255 for к in (0, 2, 4))
            h, l, s = colorsys.rgb_to_hls(r, g, b)
            r, g, b = colorsys.hls_to_rgb(((h * 360 + сдвиг) % 360) / 360, l, s)
            значения[имя] = "%02x%02x%02x" % tuple(round(x * 255) for x in (r, g, b))
    блок = блок_палитры(значения, set(эт["rgb"]))
    for путь, вид in ФАЙЛЫ:
        if вид != "блок":
            continue
        т = путь.read_text(encoding="utf-8")
        н, к = т.find(НАЧАЛО), т.find(КОНЕЦ)
        if н < 0 or к < 0:
            raise SystemExit(f"Блока палитры в {путь.name} нет — сначала `перевести`.")
        путь.write_text(т[:н] + блок + т[к + len(КОНЕЦ):], encoding="utf-8")
    print(f"палитра: {тон}, переменных {len(значения)}; справка берёт её из калькулятора")


if __name__ == "__main__":
    к = sys.argv[1] if len(sys.argv) > 1 else "остаток"
    if к == "перевести":
        перевести()
    elif к == "остаток":
        print(f"вписанных руками: {len(остаток())}")
    elif к == "собрать":
        собрать(sys.argv[2])
    else:
        raise SystemExit(__doc__)
