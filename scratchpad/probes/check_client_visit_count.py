#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Проба счёта открытий клиентской страницы.

Считается приход по ссылке, а не загрузка страницы. Проба держит ровно это:
  • первое открытие вкладки — свежий приход (p_fresh = true);
  • обновление той же вкладки — не приход (p_fresh = false);
  • возврат во вкладку (visibilitychange) — не приход, пока перерыв невелик;
    перерыв больше трёх часов делает заход новым, и это правило живёт
    в самой функции `client_link_open` — проба его не видит и видеть не может:
    ответ базы здесь подменён. Правило проверено запросом к базе 18.09.2026
    (приход → строка, обновление сразу → та же, обновление через 20 часов →
    новая, возврат через 25 минут → та же);
  • новая вкладка — снова свежий приход;
  • предпросмотр менеджера (?preview=1) не отмечается вовсе и говорит об этом
    полосой сверху — кнопка в калькуляторе называется «Открыть», и без надписи
    заход менеджера выглядит пропавшим открытием;
  • предпросмотр — это пометка в адресе И сессия менеджера в этом браузере.
    Ни память вкладки, ни состояние записи истории, ни тип перехода в этом не
    участвуют: тип перехода браузеры называют по-разному (Chromium — переходом,
    Safari на телефоне — перезагрузкой), и проба, гоняемая одним Chromium,
    такую разницу увидеть не может в принципе;
  • чистая ссылка — всегда обычное открытие, в том числе вставленная в ту же
    вкладку, где только что смотрели предпросмотр;
  • тот же адрес с пометкой, открытый там, где сессии менеджера нет, —
    обычное открытие с отметкой о прочтении. Это и есть защита от утечки:
    менеджер может скопировать адрес из строки браузера и отправить его
    клиенту, у клиента он сработает как обычная ссылка;
  • вызов уходит на client_link_open и без единого параметра в адресе
    (у PostgREST параметры на /rpc/ — фильтры по столбцам, и «?t=…» давал 400).

Живая база из контейнера закрыта шлюзом, поэтому ответ подменяется: проверяется
то, что отправляет страница, а поведение самой функции — запросом к базе.
"""
import json
import os
import pathlib
import re
import sys
import time
import threading
import http.server
import socketserver
import functools

from playwright.sync_api import sync_playwright

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent.parent
def хром():
    """Путь к браузеру. Номер сборки в нём меняется при обновлении образа,
    поэтому вписанный в пробу он однажды перестал бы совпадать. Значение
    кладёт хук запуска сессии; нет его — находим сами."""
    из_среды = os.environ.get("BM_CHROMIUM")
    if из_среды and pathlib.Path(из_среды).exists():
        return из_среды
    найденные = sorted(pathlib.Path("/opt/pw-browsers").glob("chromium-*/chrome-linux/chrome"))
    if not найденные:
        raise SystemExit("Chromium в /opt/pw-browsers не найден — запусти "
                         ".claude/hooks/session-start.sh")
    return str(найденные[-1])


ХРОМ = хром()
СТРАНИЦА = (КОРЕНЬ / "404.html").read_text(encoding="utf-8")
КОД = "adkv8q5j"

СНИМОК = {
    "status": "ok",
    "snapshot_at": "2026-09-16T10:00:00+00:00",
    "price_until": "2026-09-30",
    "snapshot": {
        "проект": "Баня 6×4", "разделы": [], "итого": 1200000,
        "шапка": {}, "параметры": [], "снимки": [],
    },
}

НАХОДКИ = []


def сервер():
    класс = functools.partial(http.server.SimpleHTTPRequestHandler, directory=str(КОРЕНЬ))
    socketserver.TCPServer.allow_reuse_address = True
    с = socketserver.TCPServer(("127.0.0.1", 0), класс)
    threading.Thread(target=с.serve_forever, daemon=True).start()
    return с, с.server_address[1]


def подключить(контекст, порт, журнал):
    def страница(маршрут):
        маршрут.fulfill(status=200, content_type="text/html; charset=utf-8", body=СТРАНИЦА)

    def база(маршрут):
        зпр = маршрут.request
        имя = зпр.url.rsplit("/", 1)[-1]
        адрес, _, хвост = имя.partition("?")
        журнал.append({"имя": адрес, "хвост": хвост,
                       "тело": json.loads(зпр.post_data or "{}")})
        ответ = СНИМОК if адрес == "client_link_get" else {"status": "ok", "new_visit": True}
        маршрут.fulfill(status=200, content_type="application/json", body=json.dumps(ответ))

    контекст.route("**/rest/v1/rpc/**", база)
    контекст.route(f"http://127.0.0.1:{порт}/{КОД}*", страница)


def сессия_менеджера(порт):
    """Хранилище браузера с ключом сессии — того же вида, что кладёт supabase-js
    на домене калькулятора. Клиентская страница смотрит только на его наличие.
    Кладётся состоянием хранилища, а не начальным скриптом: скрипт выполняется
    на пустой странице, и до целевого происхождения его запись не доезжает."""
    return {"cookies": [], "origins": [{
        "origin": f"http://127.0.0.1:{порт}",
        "localStorage": [{"name": "sb-jogylulfstjsznduirub-auth-token",
                          "value": '{"access_token":"проба","user":{"id":"u-проба"}}'}],
    }]}


def открытия(журнал):
    return [з for з in журнал if з["имя"] == "client_link_open"]


def главная():
    с, порт = сервер()
    адрес = f"http://127.0.0.1:{порт}/{КОД}"
    журнал = []
    with sync_playwright() as pw:
        бр = pw.chromium.launch(executable_path=ХРОМ, args=["--no-sandbox"])

        # ── вкладка первая: приход, обновление, возврат ──────────────────────
        к1 = бр.new_context()
        подключить(к1, порт, журнал)
        с1 = к1.new_page()
        с1.goto(адрес, wait_until="load")
        с1.wait_for_timeout(700)
        о = открытия(журнал)
        if len(о) != 1:
            НАХОДКИ.append(f"первое открытие дало {len(о)} отметок вместо одной")
        elif о[0]["тело"].get("p_fresh") is not True:
            НАХОДКИ.append(f"первое открытие отмечено не как приход: {о[0]['тело']}")
        if о and о[0]["хвост"]:
            НАХОДКИ.append(f"в адрес вызова попали параметры «?{о[0]['хвост']}» — PostgREST ответит 400")

        с1.reload(wait_until="load")
        с1.wait_for_timeout(700)
        о = открытия(журнал)
        if len(о) != 2:
            НАХОДКИ.append(f"после обновления отметок {len(о)}, ожидалось 2")
        elif о[1]["тело"].get("p_fresh") is not False:
            НАХОДКИ.append(f"обновление страницы посчитано новым приходом: {о[1]['тело']}")

        # Возврат во вкладку: страница переспрашивает версию и отмечается,
        # но приходом это не считается.
        с1.evaluate("""() => {
          Object.defineProperty(document, 'visibilityState', { get: () => 'visible', configurable: true });
          document.dispatchEvent(new Event('visibilitychange'));
        }""")
        с1.wait_for_timeout(700)
        о = открытия(журнал)
        if len(о) < 3:
            НАХОДКИ.append("возврат во вкладку не отметился вовсе — время последнего захода не сдвинется")
        elif о[-1]["тело"].get("p_fresh") is not False:
            НАХОДКИ.append(f"возврат во вкладку посчитан новым приходом: {о[-1]['тело']}")
        к1.close()

        # ── вкладка вторая: снова приход ─────────────────────────────────────
        было = len(открытия(журнал))
        к2 = бр.new_context()
        подключить(к2, порт, журнал)
        с2 = к2.new_page()
        с2.goto(адрес, wait_until="load")
        с2.wait_for_timeout(700)
        о = открытия(журнал)
        if len(о) != было + 1:
            НАХОДКИ.append(f"новая вкладка дала {len(о) - было} отметок вместо одной")
        elif о[-1]["тело"].get("p_fresh") is not True:
            НАХОДКИ.append(f"новая вкладка не посчитана приходом: {о[-1]['тело']}")
        if с2.evaluate("() => !!document.querySelector('.cl-pv')"):
            НАХОДКИ.append("клиент видит полосу предпросмотра — она только для менеджера")
        к2.close()

        # ── предпросмотр менеджера не отмечается ─────────────────────────────
        было = len(открытия(журнал))
        # Пометка действует только там, где лежит сессия менеджера: ключ
        # supabase на том же домене, что и калькулятор.
        к3 = бр.new_context(storage_state=сессия_менеджера(порт))
        подключить(к3, порт, журнал)
        с3 = к3.new_page()
        с3.goto(адрес + "?preview=1", wait_until="load")
        с3.wait_for_timeout(700)
        if len(открытия(журнал)) != было:
            НАХОДКИ.append("предпросмотр менеджера отметился как открытие клиента")
        # Адрес смотровой страницы признака не прячет — и не должен:
        # спрятанный признак приходилось отличать по типу перехода, а его
        # браузеры называют по-разному.
        адресПосле = с3.evaluate("() => location.href")
        if "preview=1" not in адресПосле:
            НАХОДКИ.append(f"признак предпросмотра пропал из адреса ({адресПосле}) — "
                           "значит, он снова прячется где-то ещё")
        # Обновление смотровой вкладки не превращает её в клиентскую.
        с3.reload(wait_until="load")
        с3.wait_for_timeout(700)
        if len(открытия(журнал)) != было:
            НАХОДКИ.append("обновление смотровой вкладки посчиталось открытием клиента")
        if not с3.evaluate("() => !!document.querySelector('.cl-pv')"):
            НАХОДКИ.append("после обновления вкладка забыла, что она смотровая")
        полоса = с3.evaluate("""() => {
          const п = document.querySelector('.cl-pv');
          if (!п) return null;
          const r = п.getBoundingClientRect();
          const лист = document.querySelector('.bl-doc');
          return { текст: п.textContent, верх: r.top,
                   надЛистом: !!лист && r.bottom <= лист.getBoundingClientRect().top + 1 };
        }""")
        if not полоса:
            НАХОДКИ.append("в предпросмотре нет полосы — заход менеджера выглядит "
                           "пропавшим открытием")
        else:
            # Надпись — две фразы и ни одной лишней: что это предпросмотр и что
            # заход не считается. Про служебный адрес в ней ничего нет: адрес,
            # скопированный из строки браузера, у клиента работает обычной
            # ссылкой, и предупреждать не о чем (Константин, 17.09.2026, вернул
            # подпись снимком).
            т = " ".join(полоса["текст"].split())
            if т != "Предпросмотр. Так страницу видит клиент. Этот заход в счёт открытий не идёт.":
                НАХОДКИ.append(f"полоса предпросмотра говорит не то: {т[:90]!r}")
            if полоса["верх"] > 1:
                НАХОДКИ.append("полоса предпросмотра стоит не сверху страницы")
            if not полоса["надЛистом"]:
                НАХОДКИ.append("полоса предпросмотра налезает на лист")

        # Чистый адрес, вставленный в ту же вкладку, — обычное открытие.
        # Это и ломалось дважды: сначала память вкладки не отпускала признак,
        # потом его отличали по типу перехода, а Safari на телефоне назвал
        # вставленный адрес перезагрузкой (Константин, 17.09.2026).
        было3 = len(открытия(журнал))
        с3.goto(адрес, wait_until="load")
        с3.wait_for_timeout(700)
        о = открытия(журнал)
        if len(о) != было3 + 1:
            НАХОДКИ.append(f"чистый адрес, вставленный в смотровую вкладку, дал {len(о) - было3} "
                           "отметок вместо одной")
        elif о[-1]["тело"].get("p_fresh") is not True:
            НАХОДКИ.append(f"вставленный адрес не посчитан приходом: {о[-1]['тело']}")
        if с3.evaluate("() => !!document.querySelector('.cl-pv')"):
            НАХОДКИ.append("чистый адрес в смотровой вкладке показал полосу предпросмотра")

        # Тот самый адрес, что мог утечь клиенту: пометка в нём есть, а сессии
        # менеджера у клиента нет — и ссылка ведёт себя обычной.
        было5 = len(открытия(журнал))
        к5 = бр.new_context()
        подключить(к5, порт, журнал)
        с5 = к5.new_page()
        с5.goto(адрес + "?preview=1", wait_until="load")
        с5.wait_for_timeout(700)
        о = открытия(журнал)
        if len(о) != было5 + 1:
            НАХОДКИ.append(f"адрес с пометкой в чужом браузере дал {len(о) - было5} отметок "
                           "вместо одной — утёкший адрес молча съедает открытия клиента")
        elif о[-1]["тело"].get("p_fresh") is not True:
            НАХОДКИ.append(f"адрес с пометкой в чужом браузере не посчитан приходом: {о[-1]['тело']}")
        if с5.evaluate("() => !!document.querySelector('.cl-pv')"):
            НАХОДКИ.append("клиент видит полосу предпросмотра по утёкшему адресу")
        к5.close()

        # Та же ссылка, отправленная клиенту, считается как обычно.
        было4 = len(открытия(журнал))
        к4 = бр.new_context()
        подключить(к4, порт, журнал)
        с4 = к4.new_page()
        с4.goto(адрес, wait_until="load")
        с4.wait_for_timeout(700)
        о = открытия(журнал)
        if len(о) != было4 + 1:
            НАХОДКИ.append(f"ссылка, скопированная из смотровой вкладки, дала "
                           f"{len(о) - было4} отметок вместо одной")
        elif о[-1]["тело"].get("p_fresh") is not True:
            НАХОДКИ.append(f"клиент по этой ссылке не посчитан приходом: {о[-1]['тело']}")
        if с4.evaluate("() => !!document.querySelector('.cl-pv')"):
            НАХОДКИ.append("клиент по скопированной ссылке видит полосу предпросмотра")
        к4.close()
        к3.close()

        # Прежняя функция больше не зовётся: в базе она осталась только ради
        # боевого домена, и новая страница ходить в неё не должна.
        if any(з["имя"] == "client_link_seen" for з in журнал):
            НАХОДКИ.append("страница всё ещё зовёт client_link_seen вместо client_link_open")

        бр.close()
    с.shutdown()

    if НАХОДКИ:
        print("НАХОДКИ:")
        for н in НАХОДКИ:
            print("  ✗", н)
        sys.exit(1)
    print("Чисто: приход, обновление, возврат, новая вкладка и предпросмотр —"
          " отмечаются так, как задумано.")
    print("Отметок всего:", len(открытия(журнал)))


if __name__ == "__main__":
    главная()
