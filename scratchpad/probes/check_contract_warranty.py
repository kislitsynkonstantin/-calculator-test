#!/usr/bin/env python3
"""Гарантия договора — по его спецификации.

Константин, 22.10.2026, снимками гарантии основного договора и договора на
отделку: «Подстраивай пункты в гарантии под спецификации, которая идёт к
договору. Если в договоре нет инженерки — убирай. Также по другим, плитки если
нет, тоже убирай. Плитка и Инженерка могут быть записаны как ручные опции,
проверяй это в коде тоже. Если есть — то добавляй в договор».

Проба у каркаса и бруса держит:
  • без инженерии и плитки в расчёте строк «Инженерные системы» и «Плиточные
    работы» нет ни в одном договоре; конструктив, окна, кровля, фасад в
    основном и отделка в договоре на отделку — есть;
  • «Консультация по инженерным коммуникациям» и подготовка «под укладку
    плитки» строк не добавляют;
  • своя позиция «Электромонтаж…» в разделе отделки — строка инженерии в
    договоре на отделку, и только в нём; своя позиция «Укладка плитки…» —
    строка плитки там же;
  • своя позиция в разделе инженерных коммуникаций — строка инженерии в
    основном договоре;
  • покраска в основном договоре или в договоре на отделку — строка
    «Покрасочные работы» и оговорки о покрытии в нём, в другом нет (23.10.2026);
  • у бруса строки «Фасадные работы» нет и при внешней отделке в расчёте —
    брус и есть фасад (23.10.2026); у каркаса она есть;
  • снятая галочка у своей позиции строку убирает.

    python3 check_contract_warranty.py
"""
import json, pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).parent))
import check_glulam_contracts as кд
import check_glulam_sections as г
import check_preset_chip as м
from playwright.sync_api import sync_playwright

НАХОДКИ = []

ГАРАНТИЯ = """(ид) => { const v = getContractVarsKar(ид); const д = new DOMParser().parseFromString(buildContractHtmlKar(v), 'text/html');
  return [...д.querySelectorAll('.bars .bar .l')].map(б => б.textContent.trim()); }"""

СВОЯ = """([к, имя, вкл]) => { const список = getCustomOpts(к);
  let co = список.find(x => x.name === имя);
  if (!co) { co = { id: customIdCounter++, name: имя, price: 50000, checked: true }; список.push(co); }
  co.checked = вкл; calc(); return true; }"""

КАТАЛОГ = """([к, образец, вкл]) => { const о = OPTIONS.find(o => o.section === к && new RegExp(образец, 'i').test(o.name || ''));
  if (!о) return false; if (!!checkedOptions[о.id] !== вкл) toggleOpt(о.id);
  // Позиция без цены в фикстуре галочку нажатием не берёт — ставим напрямую.
  if (!!checkedOptions[о.id] !== вкл) { if (вкл) checkedOptions[о.id] = true; else delete checkedOptions[о.id]; }
  calc(); return true; }"""


def прогон(бр, порт, ш, тех):
    н = f"[{ш}, {тех}]"
    к = бр.new_context(viewport={"width": ш, "height": 900})
    стр = к.new_page()
    ош = []
    стр.on("pageerror", lambda e: ош.append(str(e)))
    стр.add_init_script(г.ЗАГЛУШКА)
    стр.add_init_script("window.__ТАБЛИЦЫ = window.__ТАБЛИЦЫ || {}; Object.assign(window.__ТАБЛИЦЫ, "
                        + json.dumps(кд.таблицы(), ensure_ascii=False) + ");"
                        "window.addEventListener('DOMContentLoaded', () => { window._sbProfile = { role: 'admin', full_name: 'Проба' }; });")
    стр.goto(f"http://127.0.0.1:{порт}/index.html", wait_until="load")
    стр.wait_for_timeout(2500)
    кд.открыть(стр, тех)
    # Чистый лист: инженерию и плитку из каталога снимаем, если фикстура их отметила.
    стр.evaluate("""() => { OPTIONS.forEach(o => { if (checkedOptions[o.id] && (o.section === 'engineering'
      || ГАРАНТИЯ_ИНЖЕНЕРИЯ.test(o.name || '') || (ГАРАНТИЯ_ПЛИТКА.test(o.name || '') && !ГАРАНТИЯ_НЕ_ПЛИТКА.test(o.name || ''))))
      toggleOpt(o.id); }); calc(); }""")
    осн, отд = 1, 2

    def г_(ид):
        return стр.evaluate(ГАРАНТИЯ, ид)

    def ждать(ид, есть, нет, что):
        с = г_(ид)
        for строка in есть:
            if строка not in с:
                НАХОДКИ.append(f"{н} {что}: в договоре {ид} нет строки «{строка}» — {с}")
        for строка in нет:
            if строка in с:
                НАХОДКИ.append(f"{н} {что}: в договоре {ид} лишняя строка «{строка}» — {с}")

    первая = "Домокомплект и конструктив" if тех == "glulam" else "Конструктив объекта"
    ждать(осн, [первая], ["Инженерные системы"], "без инженерии")
    # У бруса строки фасада нет и при отмеченной внешней отделке: брус и есть
    # фасад (Константин, 23.10.2026). У каркаса — есть, когда фасад в расчёте.
    стр.evaluate("() => { if (isPrintSectionEmpty('exterior')) { const о = OPTIONS.find(o => o.section === 'exterior' && !o.included); if (о) { checkedOptions[о.id] = true; calc(); } } }")
    if not стр.evaluate("() => isPrintSectionEmpty('exterior')"):
        ждать(осн, [] if тех == "glulam" else ["Фасадные работы"], ["Фасадные работы"] if тех == "glulam" else [], "внешняя отделка в расчёте")
    else:
        НАХОДКИ.append(f"{н} в фикстуре не удалось отметить внешнюю отделку — строка фасада не проверена")
    ждать(отд, ["Отделочные работы"], ["Инженерные системы", "Плиточные работы"], "без инженерии и плитки")

    # Консультация и подготовка под плитку строк не добавляют.
    if стр.evaluate(КАТАЛОГ, ["engineering", "консультац", True]):
        ждать(осн, [], ["Инженерные системы"], "одна консультация")
    for к_ in ("steam", "interior"):
        if стр.evaluate(КАТАЛОГ, [к_, "под укладку плитки", True]):
            ждать(отд, [], ["Плиточные работы"], "подготовка под плитку")

    # Свои позиции в разделе отделки — строки в договоре на отделку.
    стр.evaluate(СВОЯ, ["interior", "Электромонтаж освещения в комнате отдыха", True])
    ждать(отд, ["Инженерные системы"], [], "своя позиция электромонтажа в отделке")
    ждать(осн, [], ["Инженерные системы"], "своя позиция электромонтажа в отделке")
    стр.evaluate(СВОЯ, ["interior", "Укладка плитки в санузле", True])
    ждать(отд, ["Плиточные работы"], [], "своя позиция плитки")
    стр.evaluate(СВОЯ, ["interior", "Укладка плитки в санузле", False])
    стр.evaluate(СВОЯ, ["interior", "Электромонтаж освещения в комнате отдыха", False])
    ждать(отд, [], ["Инженерные системы", "Плиточные работы"], "свои позиции сняты")

    # Своя позиция в инженерных коммуникациях — строка в основном договоре.
    стр.evaluate(СВОЯ, ["engineering", "Подключение к скважине", True])
    ждать(осн, ["Инженерные системы"], [], "своя позиция в инженерных коммуникациях")
    # Позиция инженерии из каталога — тоже.
    стр.evaluate(СВОЯ, ["engineering", "Подключение к скважине", False])
    if стр.evaluate(КАТАЛОГ, ["engineering", "сантехнич|электротехнич|септик", True]):
        ждать(осн, ["Инженерные системы"], [], "инженерия из каталога")

    # Покраска там, где она стоит: в основном договоре или в договоре на
    # отделку — строка «Покрасочные работы» 12 месяцев и оговорки о покрытии
    # в этом договоре, в другом их нет (Константин, 23.10.2026).
    ТЕКСТ = """(ид) => new DOMParser().parseFromString(buildContractHtmlKar(getContractVarsKar(ид)), 'text/html').body.innerText.replace(/\\s+/g, ' ')"""
    ПЕРЕНЕСТИ = """(куда) => { contractsConfig.forEach(c => { c.sections = c.sections.filter(к => к !== 'paint'); });
      const ц = contractsConfig.find(c => c.id === куда); if (ц) ц.sections.push('paint'); calc(); return getPPContracts().map(c => c.id + ':' + c.sections.join(',')); }"""
    стр.evaluate("() => { if (isPrintSectionEmpty('paint')) { const о = OPTIONS.find(o => o.section === 'paint' && !o.included); if (о) { checkedOptions[о.id] = true; calc(); } } }")
    if стр.evaluate("() => isPrintSectionEmpty('paint')"):
        НАХОДКИ.append(f"{н} в фикстуре не удалось отметить покраску — строка покраски не проверена")
    else:
        for куда, другой in ((осн, отд), (отд, осн)):
            стр.evaluate(ПЕРЕНЕСТИ, куда)
            ждать(куда, ["Покрасочные работы"], [], f"покраска в договоре {куда}")
            ждать(другой, [], ["Покрасочные работы"], f"покраска в договоре {куда}")
            т_ = стр.evaluate(ТЕКСТ, куда)
            for фраза in ("лакокрасочные материалы — гарантия производителя", "выцветание, потемнение и износ покрытия"):
                if фраза not in т_:
                    НАХОДКИ.append(f"{н} покраска в договоре {куда}: в гарантии нет «{фраза}»")
            if фраза in стр.evaluate(ТЕКСТ, другой):
                НАХОДКИ.append(f"{н} покраска в договоре {куда}: оговорка о покрытии стоит и в договоре {другой}")

    if ош:
        НАХОДКИ.append(f"{н} ошибки страницы: {ош[:3]}")
    к.close()
    print(f"  {н} проверено: гарантия основного и отделки — без инженерии и плитки, с консультацией, со своими позициями и из каталога")


def главная():
    с, порт = м.сервер()
    try:
        with sync_playwright() as pw:
            бр = pw.chromium.launch(executable_path=м.хром(), args=["--no-sandbox"])
            for тех in ("frame", "glulam"):
                for ш in (390, 1440):
                    прогон(бр, порт, ш, тех)
            бр.close()
    finally:
        с.shutdown()
    if НАХОДКИ:
        print("НАХОДКИ:")
        for н in НАХОДКИ:
            print("  ✗", н)
        sys.exit(1)
    print("Чисто: строки гарантии следуют спецификации договора — инженерия и плитка только там, где они есть, в том числе своими позициями, у бруса нет строки фасада, покраска — в том договоре, где стоит; у каркаса и бруса, на 390 и 1440.")


if __name__ == "__main__":
    главная()
