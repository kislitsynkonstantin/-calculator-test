#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Проба справки: журнал обновлений и глава, на которую он ссылается.

Держит правила из CLAUDE.md, которые иначе проверяются только глазами:
  • ссылка из журнала обязана находить свой абзац — при неверной фразе goTo
    не падает, глава просто открывается сверху, и ссылка выглядит рабочей;
  • ссылок в выпуске заметно меньше, чем пунктов: подчёркивание в каждом
    пункте превращает журнал в частокол;
  • абзац — одна мысль: больше ~400 знаков прозы в главе читать на телефоне
    тяжело. Число — повод найти шов между мыслями, а не место для разреза:
    резать надо там, где кончается одна мысль и начинается другая, даже если
    куски выйдут разной длины (Константин, 18.09.2026: «абзацы разделяй по
    смыслу, а не просто равные промежутки»).
    нечем (журнал меряется свободнее: пункт там — заголовок плюс объяснение);
  • справка написана из контекста менеджера, он её читатель, а не персонаж:
    слово «менеджер» законно в названии поля документа и в правиле доступа,
    где роли сравниваются между собой;
  • эмодзи в доме нет;
  • «Лог развития» — очередь, а не летопись: закрытая задача из него убирается,
    номера идут подряд, счётчик сходится со списком.

Одно проба не решает, а выносит на глаза: «раньше» в пунктах текущего выпуска.
Законно оно ровно тогда, когда прежнее поведение стояло в выпущенной версии;
если речь о подверсии в скобках — менеджер такого не видел, и противопоставлять
ему нечего. Судить об этом проба не умеет, поэтому просто перечисляет находки
отдельным списком, и решение остаётся за чтением.
"""
import html
import os
import pathlib
import re
import sys
import tempfile

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import справка  # noqa: E402

def хром():
    """Путь к браузеру. Номер сборки в нём меняется при обновлении образа,
    поэтому вписанный в пробу он однажды перестал бы совпадать. Значение
    кладёт хук запуска сессии; нет его — находим сами."""
    из_среды = os.environ.get("BM_CHROMIUM")
    if из_среды and pathlib.Path(из_среды).exists():
        return из_среды
    найденные = sorted(pathlib.Path("/opt/pw-browsers").glob("chromium-*/chrome-linux/chrome"))
    if not найденные:
        raise SystemExit("Chromium в /opt/pw-browsers не найден — запусти "
                         ".claude/hooks/session-start.sh")
    return str(найденные[-1])


ХРОМ = хром()
ЗНАЧКИ = re.compile("[\U0001F300-\U0001FAFF\u2600-\u27BF]")
ПРОЗА = 400
ЖУРНАЛ = 500
НАХОДКИ = []
ДАВНЕЕ = []
# Глава «Лог развития» (ch-tasks) написана для администратора: менеджерам она
# не видна вовсе, и менеджер там законно третье лицо.
БЕЗ_МЕНЕДЖЕРА = {"tasks"}
# Главы, за которые отвечает текущая работа: находки в них держат ход,
# остальное показывается как давнее и ходу не мешает.
СВОИ = {"sharing", "updates", "data", "settings", "tech"}
# Слово «менеджер» законно в двух случаях: название поля документа и правило
# доступа, где роли сравниваются между собой.
ЗАКОННО = re.compile(r"реквизит|подпис|прав[ае]? |роли|администратор|редактор|доступ"
                     r"|заказчик|у менеджера|менеджеров? (?:нет|не )"
                     r"|друг(?:ому|ого) менеджер")


# Портянка держит ход в любой главе, а не только в тех, что правились сейчас:
# «проверь всю справку, чтобы портянок нигде не было» (Константин, 18.09.2026).
# Остальные правила — про менеджера в третьем лице, значки, «раньше» — остаются
# при прежнем делении: они о тексте той работы, которая идёт.
ПОРТЯНКА = re.compile(r"абзац на \d+ знаков|идут встык")


def находка(где, сообщение):
    своё = где in СВОИ or ПОРТЯНКА.search(сообщение)
    (НАХОДКИ if своё else ДАВНЕЕ).append(f"[{где}] {сообщение}")


def текст(кусок):
    return html.unescape(re.sub(r"<[^>]+>", "", кусок)).strip()


def главы(м):
    """Куски справки по главам: имя без приставки «ch-» → разметка главы."""
    итог = {}
    for сп in re.finditer(r'<div class="ch[^"]*" id="ch-([^"]+)"', м):
        конец = re.search(r'<div class="ch[^"]*" id="', м[сп.end():])
        конец = сп.end() + конец.start() if конец else -1
        итог[сп.group(1)] = м[сп.start():конец if конец > 0 else len(м)]
    return итог


def узлы(кусок):
    """Ровно те элементы, среди которых goTo ищет фразу."""
    образец = r"<(h3|p|li)\b[^>]*>(.*?)</\1>|<div class=\"(?:sec|tip|warn)\"[^>]*>(.*?)</div>"
    return [текст("".join(g for g in с.groups()[1:] if g))
            for с in re.finditer(образец, кусок, re.S)]


def отбивка(м):
    """Соседние абзацы глав обязаны отделяться друг от друга на вид.

    Правило «абзац — одна мысль» проверялось по знакам, и главы его проходили:
    абзацы были короткие. А на экране они шли встык — общий сброс снял поля
    у <p>, и пять абзацев подряд читались сплошной портянкой. Проверять надо
    отрисовку, а не разметку: разделённый в исходнике текст выглядит слипшимся
    (Константин, 18.09.2026, снимок главы «Ссылка клиенту» на боевом домене).
    """
    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        return []
    временный = pathlib.Path(tempfile.mkdtemp()) / "справка.html"
    временный.write_text(м, encoding="utf-8")
    находки = []
    with sync_playwright() as pw:
        бр = pw.chromium.launch(executable_path=ХРОМ, args=["--no-sandbox"])
        стр = бр.new_page(viewport={"width": 390, "height": 900})
        стр.goto(временный.as_uri(), wait_until="load")
        стр.wait_for_timeout(500)
        for глава in главы(м):
            стр.evaluate("(г) => go(г)", глава)
            стр.wait_for_timeout(120)
            слипшиеся = стр.evaluate("""(глава) => {
              const гл = document.getElementById('ch-' + глава);
              if (!гл) return [];
              /* Меряем поток прозы: абзацы, списки и плашки. Карточки шагов,
                 строки журнала и пункты списка задач разделены линейкой или
                 подложкой — у них расстояние ноль по замыслу, и требовать от
                 них отбивки значило бы ловить не портянку, а вёрстку. */
              const свой = э => {
                if (!э.offsetHeight) return false;
                if ((э.textContent || '').trim().length < 40) return false;
                const т = э.tagName.toLowerCase();
                return t_ok(т) || э.classList.contains('tip') ||
                       э.classList.contains('warn') || э.classList.contains('quote');
                function t_ok(т) { return т === 'p' || т === 'ul' || т === 'ol'; }
              };
              const делит = (а, б) => {
                const са = getComputedStyle(а), сб = getComputedStyle(б);
                const рамка = з => parseFloat(з) || 0;
                if (рамка(са.borderBottomWidth) || рамка(сб.borderTopWidth)) return true;
                const фон = з => z_пусто(з) ? null : з;
                function z_пусто(з) { return !з || з === 'rgba(0, 0, 0, 0)' || з === 'transparent'; }
                return !!(фон(са.backgroundColor) || фон(сб.backgroundColor));
              };
              const плохие = [];
              const обойти = узел => {
                const дети = [...узел.children];
                let пред = null;
                дети.forEach(э => {
                  if (свой(э)) {
                    if (пред) {
                      const щель = э.getBoundingClientRect().top - пред.getBoundingClientRect().bottom;
                      if (щель < 6 && !делит(пред, э)) плохие.push({
                        щель: Math.round(щель),
                        что: пред.tagName.toLowerCase() + '+' + э.tagName.toLowerCase(),
                        начало: э.textContent.trim().slice(0, 40) });
                    }
                    пред = э;
                  } else {
                    пред = null;
                  }
                  обойти(э);
                });
              };
              обойти(гл);
              return плохие;
            }""", глава)
            for с in слипшиеся:
                находки.append(f"[{глава}] {с['что']}: блоки идут встык ({с['щель']} px) — "
                               f"«{с['начало']}…»")
        бр.close()
    return находки


def снимки(м):
    """Главы читаются картинкой целиком, а не по найденным строкам.

    Правило дома: снимок смотрят как кадр, а не как ответ на заданный вопрос.
    Для справки это единственный способ увидеть, что абзац не слипся с
    соседним и заголовок не уехал.
    """
    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        return
    куда = pathlib.Path(__file__).parent
    временный = pathlib.Path(tempfile.mkdtemp()) / "справка.html"
    временный.write_text(м, encoding="utf-8")
    with sync_playwright() as pw:
        бр = pw.chromium.launch(executable_path=ХРОМ, args=["--no-sandbox"])
        стр = бр.new_page(viewport={"width": 390, "height": 900})
        стр.goto(временный.as_uri(), wait_until="load")
        стр.wait_for_timeout(600)
        # Кадр берётся у места, которое правилось: целая глава на телефоне —
        # полотно в десять экранов, на нём не видно ничего.
        for глава, якорь in (("sharing", "Ссылка клиенту"), ("updates", "Клиенту можно отправить спецификацию ссылкой")):
            стр.evaluate(f"() => go('{глава}')")
            стр.wait_for_timeout(300)
            стр.evaluate("""(я) => {
              const гл = document.querySelector('.ch.active') || document;
              const у = [...гл.querySelectorAll('h3, .upd-item, p')]
                .find(n => n.textContent.includes(я));
              if (у) у.scrollIntoView({ block: 'start' });
            }""", якорь)
            стр.wait_for_timeout(400)
            стр.screenshot(path=str(куда / f"справка-{глава}.png"))
        бр.close()


def главная():
    м = справка.достать()
    гл = главы(м)

    # ── ссылки журнала находят свой абзац ────────────────────────────────────
    for глава, фраза in re.findall(r"goTo\('([^']+)','([^']+)'\)", м):
        if глава not in гл:
            НАХОДКИ.append(f"ссылка ведёт в главу «{глава}», которой нет")
        elif not any(фраза.lower() in у.lower() for у in узлы(гл[глава])):
            НАХОДКИ.append(f"ссылка на «{глава}» ищет фразу {фраза!r} — в главе её нет, "
                           "глава просто откроется сверху")

    # ── текущий выпуск: пунктов больше, чем ссылок ───────────────────────────
    журнал = гл.get("updates", "")
    выпуски = re.split(r'(?=<div class="upd">)', журнал)
    текущий = next((в for в in выпуски if "upd-state" in в), "")
    пунктов = текущий.count('class="upd-item"')
    ссылок = текущий.count('class="upd-link"')
    if пунктов and ссылок > пунктов * 0.6:
        НАХОДКИ.append(f"в текущем выпуске {ссылок} ссылок на {пунктов} пунктов — частокол; "
                       "ссылку получает то, о чём есть что дочитать")

    # ── пункт называет место, а не показывает пальцем ────────────────────────
    # «Внизу видно, что расчёт ещё не сохранён» — внизу чего? Пункт журнала
    # читают в одиночку: менеджер открыл выпуск и смотрит на одну строку, а не
    # на соседние и не на мою переписку. Место называется словом — «внизу
    # экрана», «в списке расчётов», «в окне печати», — и называется в заголовке
    # или в первом предложении, дальше уже есть за что держаться.
    # Константин 20.09.2026, со снимком третьего пункта: «нужно писать
    # с контекстом. „Внизу“, чего? По смыслу догадываться. Пиши понятно.
    # Каждое сообщение самостоятельно».
    БЕЗ_МЕСТА = re.compile(r"\b(внизу|вверху|сверху|снизу|справа|слева|здесь|там)\b", re.I)
    ЧТО_ИМЕННО = re.compile(
        r"экран|окн[аеоу]|списк|панел|карточк|страниц|шапк|меню|вкладк|полоск"
        r"|раздел|таблиц|форм[аеы]|документ|поле|поля|колонк|строк|карт[аеы]"
        r"|подвал|футер|ряд|блок", re.I)
    for блок in re.findall(r'<div class="upd-item">(.*?)</div>', текущий, re.S):
        заголовок = re.search(r"<strong>(.*?)</strong>", блок, re.S)
        заголовок = текст(заголовок.group(1)) if заголовок else ""
        остаток = текст(re.sub(r"<strong>.*?</strong>", "", блок, count=1, flags=re.S))
        первое = re.split(r"(?<=[.;])\s+", re.sub(r"\s+", " ", остаток))[0]
        for кусок in (заголовок, первое):
            for с in БЕЗ_МЕСТА.finditer(кусок):
                хвост = " ".join(кусок[с.end():].split()[:4])
                if not ЧТО_ИМЕННО.search(хвост):
                    НАХОДКИ.append(
                        f"пункт журнала показывает пальцем: «{с.group(0)} "
                        f"{хвост}…» — {с.group(0)} чего? Пункт читают в "
                        f"одиночку, место называется словом: «{заголовок[:45]}»")

    # ── абзац — одна мысль ───────────────────────────────────────────────────
    def мерить(куски, предел, где):
        for кусок in куски:
            for абзац in re.split(r"<br>\s*<br>", кусок):
                т = текст(абзац)
                if len(т) > предел:
                    находка(где, f"абзац на {len(т)} знаков — искать смысловой шов: "
                                 f"«{т[:70]}…»")

    for имя, кусок in гл.items():
        if имя == "updates":
            continue
        мерить(re.findall(r"<p>(.*?)</p>", кусок, re.S), ПРОЗА, имя)
    мерить(re.findall(r'<div class="upd-item">(.*?)</div>', текущий, re.S), ЖУРНАЛ, "updates")

    # ── менеджер — читатель, а не персонаж ───────────────────────────────────
    # Глава «Лог развития» — исключение: её читает администратор.
    for имя, кусок in гл.items():
        if имя in БЕЗ_МЕНЕДЖЕРА:
            continue
        for предложение in re.split(r"(?<=[.!?])\s+", текст(кусок)):
            if "менеджер" in предложение.lower() and not ЗАКОННО.search(предложение.lower()):
                находка(имя, f"о менеджере в третьем лице: «{предложение[:110]}…»")

    # ── что видит администратор, менеджеру не рассказываем ──────────────────
    # «Калькулятор для менеджеров. То, что видит администратор и редактор —
    # нигде не пишем» (Константин, 19.09.2026, снимок пункта журнала). Слово
    # само по себе не запрещено: менеджеру надо знать, к кому идти и чего он
    # сам не может. Находка — там, где чужая роль описана как действующее лицо:
    # что ей видно, что у неё открыто, что ей доступно. Глава «Лог развития»
    # исключение: её читает администратор, менеджеру она не видна вовсе.
    ЧУЖАЯ_РОЛЬ = re.compile(r"администратор|редактор(?!\s+комплектац)", re.I)
    # Законно: маршрут менеджера («напишите администратору») и его собственный
    # предел («цены правит администратор — у менеджера прав нет»).
    # Было шире: любое «администратору» в дательном падеже считалось маршрутом
    # и выпускало «оба блока видны только администратору и редактору» — ровно ту
    # фразу, ради которой правило и писалось. Оставлены две формы, и обе про
    # менеджера: куда ему идти и чего он сам не может.
    РОЛЬ_ЗАКОННО = re.compile(
        r"напиш\w*\s+администратор|обрат\w*\s+к администратор|"
        r"правит администратор|у менеджера прав", re.I)
    # Описание чужой роли: ей что-то видно, открыто, доступно, она что-то видит.
    РОЛЬ_ОПИСАНА = re.compile(
        r"(?:видит|видно|видны|доступн\w+|открыт\w*|работает|может|"
        r"стоят|показыва\w+)[^.]{0,80}(?:администратор|редактор)|"
        r"(?:администратор|редактор)\w*[^.]{0,80}"
        r"(?:видит|видно|видны|доступн\w+|открыт\w*|работает|может|"
        r"стоят|показыва\w+)", re.I)
    for имя, кусок in гл.items():
        if имя in БЕЗ_МЕНЕДЖЕРА:
            continue
        for предложение in re.split(r"(?<=[.!?])\s+", текст(кусок)):
            if not ЧУЖАЯ_РОЛЬ.search(предложение):
                continue
            if РОЛЬ_ЗАКОННО.search(предложение):
                continue
            if РОЛЬ_ОПИСАНА.search(предложение):
                находка(имя, f"о том, что видит администратор или редактор: "
                             f"«{предложение[:110]}…»")

    # ── «Лог развития»: очередь, а не летопись ──────────────────────────────
    лог = гл.get("tasks", "")
    карточки = re.findall(r'<span class="tsk-num">(\d+)</span>\s*<span class="tsk-name">(.*?)</span>'
                          r'\s*<span class="tsk-st[^"]*">([^<]*)</span>', лог, re.S)
    номера = [int(н) for н, _, _ in карточки]
    if номера and номера != list(range(1, len(номера) + 1)):
        НАХОДКИ.append(f"номера задач идут не подряд: {номера} — снятая задача оставила дыру")
    счётчик = re.search(r'<div class="sec">(\d+) задач[^<]*</div>', лог)
    if not счётчик:
        НАХОДКИ.append("в «Логе развития» нет счётчика задач")
    elif int(счётчик.group(1)) != len(карточки):
        НАХОДКИ.append(f"счётчик обещает {счётчик.group(1)} задач, а карточек {len(карточки)}")
    # Ссылка на соседнюю задачу по номеру обязана во что-то попадать. Номера
    # сдвигаются при каждом снятии задачи из очереди, а ссылка на них остаётся
    # прежней — и начинает указывать на чужую работу молча. 19.09.2026 после
    # снятия двух задач «задача 5» стала бы «Проверкой по коду» вместо
    # «Договора в калькуляторе».
    for ссылка in re.findall(r"задач[аеиу]\s+(\d+)", текст(лог)):
        if int(ссылка) not in номера:
            НАХОДКИ.append(f"ссылка на «задачу {ссылка}» никуда не ведёт: "
                           f"в очереди номера {номера}")
    # Сделанная задача живёт в журнале обновлений, а не в очереди.
    ЗАКРЫТО = re.compile(r"сделан|готов|выпущен|закрыт|внедрён", re.I)
    for _, имя, состояние in карточки:
        if ЗАКРЫТО.search(состояние):
            имя = текст(имя)
            НАХОДКИ.append(f"задача «{имя[:50]}» помечена «{состояние}» — закрытая "
                           "задача из очереди убирается")

    # ── эмодзи ───────────────────────────────────────────────────────────────
    for имя, кусок in гл.items():
        э = sorted(set(re.findall(ЗНАЧКИ, кусок)))
        if э:
            находка(имя, f"эмодзи в тексте: {э} — в доме их нет, знак рисуется svg")

    if ДАВНЕЕ:
        print(f"Давнее, не этой работы ({len(ДАВНЕЕ)}) — ходу не мешает:")
        for н in ДАВНЕЕ:
            print("  ·", н)
        print()
    # «Раньше» в текущем выпуске — на глаза, без приговора.
    прошедшее = []
    for блок in re.findall(r'<div class="upd-item">(.*?)</div>', текущий, re.S):
        т = re.sub(r"\s+", " ", текст(блок))
        for предложение in re.split(r"(?<=[.;])\s+", т):
            if re.search(r"\b(раньше|прежде|до этого)\b", предложение, re.I):
                прошедшее.append(предложение.strip()[:120])
    if прошедшее:
        print(f"Сверить глазами — «раньше» в текущем выпуске ({len(прошедшее)}):")
        for п in прошедшее:
            print("  ?", п)
        print("  Законно, если так было в выпущенной версии; про подверсию в скобках —"
              " менеджер её не видел.\n")

    НАХОДКИ.extend(отбивка(м))
    снимки(м)
    if НАХОДКИ:
        print("НАХОДКИ:")
        for н in НАХОДКИ:
            print("  ✗", н)
        sys.exit(1)
    print(f"Чисто: {пунктов} пунктов и {ссылок} ссылок в текущем выпуске, "
          "все ссылки находят свой абзац, абзацы в норме.")


