#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Задаток — только первый платёж договора, остальные — оплата.

Константин 19.10.2026, на предложение оставить задатком только первый платёж:
«Тут все платежи оставь задатком, кроме финальных, где работы уже выполнены.
Поправь это в платежном плане и договорах». До этого в основном договоре
задатком назывались все шесть платежей, включая последний — «в день окончания
работ по утеплению и монтажу пленок»; задаток обеспечивает договор, а платёж за
уже сделанную работу обеспечивать нечего. В плане первый этап звался авансом.

Константин 21.10.2026, снимком графика платежей: «Задаток оставь только первый
платёж. Остальные поставь оплата. Только тот, что в день подписания пусть будет
задаток. Поправь это в обоих договорах» — правило 19.10.2026 этим снято.

Проба держит:
  • в обоих договорах первый срок платежа начинается со «задаток», каждый
    следующий — с «оплата»; задатка дальше первого платежа нет;
  • последний в основном — «оплата в день окончания …», в договоре на
    отделку — «оплата в день подписания Акта»;
  • первый этап плана — «Задаток по договору» и «Задаток по договору отделки»;
  • сохранённый план с прежним именем «Аванс по договору» получает новое имя
    при восстановлении состава, а своё имя этапа (custom) не трогается.

    python3 check_deposit_terms.py
"""
import pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).parent))
import check_contract_otd as о
import check_preset_chip as м
from playwright.sync_api import sync_playwright

НАХОДКИ = []

ДОГОВОР = """(ид) => { const д = new DOMParser().parseFromString(buildContractHtmlKar(getContractVarsKar(ид)), 'text/html');
  const т = э => э.textContent.replace(/\\s+/g, ' ').trim();
  return { сроки: [...д.querySelectorAll('.g1 .tm')].map(т) }; }"""

ИМЕНА = """() => getPPContracts().map(c => (c.payments[0] || {}).label)"""

ПРЕЖНИЕ = """() => { const c = contractsConfig.find(x => x.id === 1); getPPContracts();
  const было = c.payments.map(p => ({...p}));
  c.payments[0].label = 'Аванс по договору';
  c.payments.push({ label: 'Аванс', sub: '', pct: 0, custom: true });
  проставитьКодыСоставов();
  const итог = [c.payments[0].label, c.payments[c.payments.length - 1].label];
  c.payments = было; return итог; }"""


def проверить(н, д, ид):
    с = д["сроки"]
    имя = "основной" if ид == 1 else "на отделку"
    if len(с) < 2:
        НАХОДКИ.append(f"{н} {имя}: в графике меньше двух платежей — проверять нечего: {с}")
        return
    if not с[0].startswith("задаток"):
        НАХОДКИ.append(f"{н} {имя}: первый платёж не задаток: «{с[0]}»")
    for срок in с[1:]:
        if not срок.startswith("оплата"):
            НАХОДКИ.append(f"{н} {имя}: платёж после первого не оплата: «{срок}»")
    ждём = "оплата в день окончания " if ид == 1 else "оплата в день подписания Акта"
    if not с[-1].startswith(ждём):
        НАХОДКИ.append(f"{н} {имя}: финальный платёж «{с[-1]}», ждём «{ждём}…»")


def прогон(бр, порт, ш):
    к, стр, ош = о.начать(бр, порт, ш, "admin")
    for ид in (1, 2):
        проверить(f"[{ш}]", стр.evaluate(ДОГОВОР, ид), ид)
    имена = стр.evaluate(ИМЕНА)
    if имена[:2] != ["Задаток по договору", "Задаток по договору отделки"]:
        НАХОДКИ.append(f"[{ш}] первые этапы плана: {имена[:2]}")
    пр = стр.evaluate(ПРЕЖНИЕ)
    if пр != ["Задаток по договору", "Аванс"]:
        НАХОДКИ.append(f"[{ш}] сохранённый план с прежним именем: {пр} (ждём новое имя у типового этапа и прежнее у своего)")
    for е in [е for е in ош if "supabase.co" not in е][:3]:
        НАХОДКИ.append(f"[{ш}] ошибка страницы: {е[:160]}")
    к.close()


def главная():
    с, порт = м.сервер()
    try:
        with sync_playwright() as pw:
            бр = pw.chromium.launch(executable_path=м.хром(), args=["--no-sandbox"])
            for ш in (390, 1440):
                прогон(бр, порт, ш)
            бр.close()
    finally:
        с.shutdown()
    if НАХОДКИ:
        print("НАХОДКИ:")
        for н in НАХОДКИ:
            print("  ✗", н)
        raise SystemExit(1)
    print("Чисто: в обоих договорах задаток — только первый платёж, остальные — оплата; первый этап "
          "плана — задаток, сохранённый план берёт новое имя, своё имя этапа не трогается; на 390 и 1440.")


if __name__ == "__main__":
    главная()
