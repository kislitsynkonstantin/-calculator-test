#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Глаз пароля на экране входа меняет значок.

Константин, 23.10.2026, двумя снимками экрана входа — пароль скрыт и виден, а
глаз один и тот же: «когда глаз нажимаешь, чтобы в одной из версий он был
перечёркнут, а в другой открыт. Сейчас вообще не меняется, только чуть
подсветка».

Проба на 390 и 1440 px, днём и ночью:
  • пароль скрыт — открытый глаз, без черты; подпись «Показать пароль»;
  • нажатие — пароль виден, глаз перечёркнут; подпись «Скрыть пароль»;
  • второе нажатие возвращает и поле, и значок;
  • кнопка не сдвинулась и не изменила размер при смене значка.

    python3 check_login_eye.py
"""
import pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).parent))
import check_login_states as л
from playwright.sync_api import sync_playwright

НАХОДКИ = []
СОСТОЯНИЕ = """() => { const к = document.querySelector('#loginScreen .lg-eye'), р = к.getBoundingClientRect();
  return { тип: document.getElementById('loginPassword').type, черта: !!к.querySelector('svg line'), подпись: к.getAttribute('aria-label'),
    рамка: [Math.round(р.left), Math.round(р.top), Math.round(р.width), Math.round(р.height)] }; }"""


def главная():
    с, порт = л.сервер()
    try:
        with sync_playwright() as pw:
            бр = pw.chromium.launch(executable_path=л.хром(), args=["--no-sandbox"])
            for ш, в in ((390, 844), (1440, 900)):
                for ночь in (False, True):
                    где = f"{ш}px · {'ночь' if ночь else 'день'}"
                    к, стр, ош = л.открыть(бр, порт, ш, в, True, ночь)
                    стр.fill("#loginPassword", "проба-пароль")
                    до = стр.evaluate(СОСТОЯНИЕ)
                    if до["тип"] != "password" or до["черта"] or до["подпись"] != "Показать пароль":
                        НАХОДКИ.append(f"[{где}] скрытый пароль — ждём открытый глаз и «Показать пароль»: {до}")
                    стр.click("#loginScreen .lg-eye")
                    после = стр.evaluate(СОСТОЯНИЕ)
                    if после["тип"] != "text" or not после["черта"] or после["подпись"] != "Скрыть пароль":
                        НАХОДКИ.append(f"[{где}] видимый пароль — ждём перечёркнутый глаз и «Скрыть пароль»: {после}")
                    if после["рамка"] != до["рамка"]:
                        НАХОДКИ.append(f"[{где}] кнопка глаза сдвинулась при смене значка: {до['рамка']} → {после['рамка']}")
                    стр.click("#loginScreen .lg-eye")
                    снова = стр.evaluate(СОСТОЯНИЕ)
                    if снова["тип"] != "password" or снова["черта"]:
                        НАХОДКИ.append(f"[{где}] второе нажатие не вернуло скрытый пароль и открытый глаз: {снова}")
                    if ош:
                        НАХОДКИ.append(f"[{где}] ошибки страницы: {ош[:3]}")
                    к.close()
            бр.close()
    finally:
        с.shutdown()
    if НАХОДКИ:
        print("НАХОДКИ:")
        for т in НАХОДКИ:
            print("  ✗", т)
        raise SystemExit(1)
    print("Чисто: глаз пароля на экране входа — открытый, пока пароль скрыт, перечёркнутый, когда виден; подпись следует за ним, кнопка стоит на месте — на 390 и 1440, днём и ночью.")


if __name__ == "__main__":
    главная()
