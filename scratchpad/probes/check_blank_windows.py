def m_светлая(цвет):
    if not цвет or len(цвет) < 3:
        return False
    r, g, b = цвет[:3]
    return (0.299 * r + 0.587 * g + 0.114 * b) > 170


def m_строка(цвет):
    return ", ".join(str(int(з)) for з in (цвет or [])[:3])


