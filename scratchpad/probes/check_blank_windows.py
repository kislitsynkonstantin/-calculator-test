def проверить_ряд(стр, ширина, имяТемы):
    м = спросить(стр, РЯД)
    if not м or м.get("нет"):
        плохо("ряда вкладок редактора нет в разметке")
        return
    for п in м["пересечения"]:
        плохо(f"[{имяТемы} {ширина}] кнопка наехала на вкладку: {п}")
    # На узком экране лента вкладок обязана иметь свою линейку во всю ширину:
    # без неё подчёркивание выбранной вкладки висит обрывком над кнопками.
    if ширина <= 640 and not м.get("линейкаЛенты"):
        плохо(f"[{имяТемы} {ширина}] под лентой вкладок нет линейки — подчёркивание "
              "активной вкладки повисает обрывком")
    # Редактор собран из двух колонок; на телефоне они обязаны встать друг под
    # друга. Правка эта была сделана только для «Бланка», и в «Модерне» на
    # 390 px список получал 140 px: названия рвались по одному слову в строку,
    # из четырёх вкладок была видна одна. Проба этого не видела, потому что
    # мерила пустой редактор, открытый на 1440 и потом уменьшенный, —
    # раскладка считается при отрисовке. Константин, 19.09.2026.
    if ширина <= 760 and м.get("колонки"):
        узкие = [к for к in м["колонки"] if к["w"] < ширина - 2]
        if узкие:
            плохо(f"[{имяТемы} {ширина}] редактор остался в две колонки: "
                  f"{', '.join(str(к['w']) + ' px' for к in м['колонки'])} — "
                  f"на телефоне названия рвутся по слову в строку")
    for з in м["зазоры"]:
        if з["доЛинейки"] < 6:
            плохо(f"[{имяТемы} {ширина}] {з['ид']} прижата к линейке ряда: {з['доЛинейки']} px")
        # Кнопка стоит под лентой вкладок только на узком экране; на широком
        # она в одной строке с ними, и расстояние вверх там отрицательное.
        if з["доВкладок"] is not None and 0 <= з["доВкладок"] < 12:
            плохо(f"[{имяТемы} {ширина}] {з['ид']} стоит под подчёркиванием вкладки: "
                  f"{з['доВкладок']} px — черта читается границей кнопки")
        # Площадь нажатия и зазор до соседа — разные вещи, и меряются обе.
        # Кнопка рисуется лёгкой, а нажимается полем вокруг: если поле меньше
        # 44 px, по ней не попасть, а если поля соседок сошлись — нажатие у шва
