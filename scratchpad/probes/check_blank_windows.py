# Проба ряда мерила зазоры, наезды и площадь нажатия — геометрию. Цвет надписей
# она не трогала вовсе, и оттого выбранная вкладка простояла бледной три
# выпуска подряд: правило темы красило все четыре одним `!important` в самые
# бледные чернила, перебивая акцент, который код ставит выбранной. Мерится
# ровно два правила: любая надпись читается (4,5 к одному), и выбранная не
# тише невыбранных — иначе она не выглядит выбранной, как бы ни называлась
# в разметке (Константин, 19.09.2026, третий раз об одном месте).
ВКЛАДКИ = """() => {
  const фон = (э) => {
    let у = э;
    while (у) {
      const ф = getComputedStyle(у).backgroundColor;
      if (ф && ф !== 'rgba(0, 0, 0, 0)' && !/,\\s*0\\)$/.test(ф)) return ф;
      у = у.parentElement;
    }
    return 'rgb(255, 255, 255)';
  };
  const свет = (з) => {
    const [r, g, b] = (з.match(/[\\d.]+/g) || [0, 0, 0]).slice(0, 3).map(Number);
    const к = (v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4); };
    return 0.2126 * к(r) + 0.7152 * к(g) + 0.0722 * к(b);
  };
  const контраст = (а, б) => {
    const x = свет(а), y = свет(б);
    return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05);
  };
  const кнопки = [...document.querySelectorAll('#kedTabsHost button')]
    .filter(э => э.getClientRects().length);
  if (!кнопки.length) return { нет: true };
  return {
    вкладки: кнопки.map(б => {
      const с = getComputedStyle(б);
      return { текст: б.textContent.trim().slice(0, 18), цвет: с.color,
               активна: б.classList.contains('is-active'),
               контраст: +контраст(с.color, фон(б)).toFixed(2) };
    }),
  };
}"""


def проверить_вкладки(стр, ширина, имяТемы):
    м = спросить(стр, ВКЛАДКИ)
    if not м or м.get("нет"):
        плохо(f"[{имяТемы} {ширина}] вкладок уровней нет на экране")
        return
    вкладки = м["вкладки"]
    выбранные = [в for в in вкладки if в["активна"]]
    прочие = [в for в in вкладки if not в["активна"]]
    for в in вкладки:
        if в["контраст"] < 4.5:
            плохо(f"[{имяТемы} {ширина}] вкладка «{в['текст']}» не читается: "
                  f"{в['контраст']} к одному при мерке 4,5 ({в['цвет']})")
    if not выбранные:
        плохо(f"[{имяТемы} {ширина}] ни одна вкладка не помечена выбранной — "
              "выбранную не за что зацепить ни стилям, ни пробе")
        return
    if len(выбранные) > 1:
        плохо(f"[{имяТемы} {ширина}] выбранными помечены {len(выбранные)} вкладки сразу")
    в = выбранные[0]
    if прочие:
        цвета = {п["цвет"] for п in прочие}
        if в["цвет"] in цвета:
            плохо(f"[{имяТемы} {ширина}] выбранная вкладка «{в['текст']}» набрана тем же "
                  f"цветом, что и невыбранные ({в['цвет']}) — выбор держится одной чертой")
        # «Тише соседей» само по себе не находка: контраст к фону — это
        # читаемость, а выбор несут ещё цвет и насыщенность начертания.
        # В «Модерне» выбранная набрана бирюзовым по белому (6,1) рядом с
        # серыми (7,46) и при этом явно сильнее их — жирная, цветная, с чертой.
        # Мерка срабатывала на исправном ряде. Находка — только настоящий
        # перевёртыш: выбранная вдвое тише самой тихой из остальных.
        тише = min(п["контраст"] for п in прочие)
        if в["контраст"] < тише / 2:
            плохо(f"[{имяТемы} {ширина}] выбранная вкладка вдвое тише невыбранных: "
                  f"{в['контраст']} против {тише} — она читается выключенной")


