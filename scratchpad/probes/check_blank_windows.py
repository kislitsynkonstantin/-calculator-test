# ── значок готовых комплектаций в списке проектов ───────────────────────────
def проверить_значок(стр):
    """На листе значок стоит сам: без коробки, без заливки, чернилами акцента.

    В «Модерне» он остаётся залитым квадратом с белым знаком — тему не трогали,
    и проба это держит: правка одной темы не должна тихо менять другую.
    """
    for имяТемы, лист in (("бланк", True), ("модерн", False)):
        тема(стр, "blank" if лист else "modern")
        м = спросить(стр, """() => {
          // Значок стоит у проектов с закрытым замком — в пробе замок ставим
          // сами и пересобираем список, иначе значка нет вовсе.
          try { _lockedSlugs.add(projectSlug(PROJECTS[0][0])); } catch (e) {}
          if (typeof filterProjects === 'function') filterProjects();
          // Список открывается нажатием; в пробе разворачиваем его сами.
          const обёртка = document.getElementById('projectSelectWrap')
            || document.querySelector('.custom-select-wrap');
          if (обёртка) обёртка.classList.add('open');
          const з = document.querySelector('.custom-select-dropdown .proj-kit-badge');
          if (!з) return { нет: true };
          const с = getComputedStyle(з);
          const svg = з.querySelector('svg');
          const числа = т => (т.match(/[\\d.]+/g) || []).slice(0, 4).map(Number);
          return { фон: числа(с.backgroundColor), прозрачность: числа(с.backgroundColor)[3],
                   цвет: числа(с.color), поля: с.padding,
                   знак: svg ? Math.round(svg.getBoundingClientRect().width) : 0 };
        }""")
        if not м or м.get("нет"):
            плохо(f"[{имяТемы}] значка готовых комплектаций нет в списке проектов")
            continue
        залит = not (м["прозрачность"] == 0 or len(м["фон"]) < 3)
        if лист:
            if залит:
                плохо(f"[{имяТемы}] значок остался с заливкой rgb({m_строка(м['фон'])}) — "
                      "на листе он стоит сам, без коробки")
            if м["знак"] < 14:
                плохо(f"[{имяТемы}] знак мелкий: {м['знак']} px — без коробки он чуть крупнее")
            if м["поля"].strip() not in ("0px", "0px 0px", "0px 0px 0px 0px"):
                плохо(f"[{имяТемы}] у значка остались поля коробки: {м['поля']}")
        else:
            if not залит:
                плохо("[модерн] значок потерял заливку — эту тему не трогали")
        try:
            стр.locator("#projectSelectWrap .custom-select-dropdown").screenshot(
                path=str(pathlib.Path(__file__).parent / f"значок-{имяТемы}.png"), timeout=3000)
        except Exception:
            pass
        спросить(стр, """() => {
          const о = document.getElementById('projectSelectWrap')
            || document.querySelector('.custom-select-wrap');
          if (о) о.classList.remove('open');
        }""")


# ── разделы в таблице комплектаций ──────────────────────────────────────────
def проверить_разделы(стр):
    """Раздел набран как раздел в расчёте: крупный бледный номер, название
    чернилами акцента, черта в два пикселя. «Модерн» остаётся прежним —
    прописные с разрядкой и номер без ведущего нуля.

    Прежде проба смотрела на цвет самой ячейки и сверяла его со строками.
    Цвет ячейки был верным всё это время, а номер и название лежат в ней
    отдельными `span` — и их красило чужое правило, писанное для прочерка
    «не входит»: серым в две трети яркости. Разное со строками — значит
    «разное», и проба молчала. Теперь сверяются сами части заголовка, и не
    «не как у строк», а «как в расчёте»: тот же токен, тот же вес, та же
    непрозрачность (Константин, 19.09.2026: «убого… повтори как тут»).
    """
    для_тем(стр)
    стр.evaluate("() => { openKompl(); switchKomplTab('table'); }")
    стр.wait_for_timeout(400)
    м = спросить(стр, """() => {
      const раздел = document.querySelector('#komplTable tr.kompl-sec td');
      if (!раздел) return { нет: true };
      const с = getComputedStyle(раздел);
      const строка = document.querySelector('#komplTable tbody tr:not(.kompl-sec) td');
      const числа = з => (з.match(/[\\d.]+/g) || []).slice(0, 3).map(Number);
      const часть = (э) => {
        if (!э) return null;
        const к = getComputedStyle(э);
        return { цвет: числа(к.color), вес: Number(k_вес(к.fontWeight)),
                 кегль: Math.round(parseFloat(к.fontSize)),
                 муть: Number(к.opacity) };
      };
      function k_вес(з) { return з === 'normal' ? 400 : (з === 'bold' ? 700 : з); }
      // Образец — заголовок раздела самого расчёта: на него и равняемся.
      const обрНомер = document.querySelector('.section-header .sec-no');
      const обрИмя = document.querySelector('.section-header');
      return { черта: parseFloat(с.borderBottomWidth) || 0,
               цветЧерты: числа(с.borderBottomColor),
               цвет: числа(с.color),
               цветСтроки: строка ? числа(getComputedStyle(строка).color) : null,
               номер: часть(раздел.querySelector('.ks-no')),
               имя: часть(раздел.querySelector('.ks-name')),
               обрНомер: часть(обрНомер),
               обрИмя: обрИмя ? числа(getComputedStyle(обрИмя).color) : null };
    }""")
    if not м or м.get("нет"):
        плохо("в таблице комплектаций нет строк-разделов с именем класса")
        return
    if м["черта"] < 2:
        плохо(f"раздел в «Бланке» без черты: {м['черта']} px — он сливается со строками")
    яркость = 0.299 * м["цветЧерты"][0] + 0.587 * м["цветЧерты"][1] + 0.114 * м["цветЧерты"][2]
    if яркость > 150:
        плохо(f"черта раздела бледная: rgb({m_строка(м['цветЧерты'])})")
    if м["цвет"] == м["цветСтроки"]:
        плохо("название раздела набрано тем же цветом, что и строки")
    if not м["номер"] or not м["имя"]:
        плохо("в заголовке раздела таблицы нет номера или названия — "
              "сверять не с чем")
        return
    if not м["обрНомер"] or not м["обрИмя"]:
        плохо("на странице нет заголовка раздела расчёта — не с чем сверять")
        return
    if м["номер"]["цвет"] != м["обрНомер"]["цвет"]:
        плохо(f"номер раздела в таблице набран не тем цветом, что в расчёте: "
              f"rgb({m_строка(м['номер']['цвет'])}) против "
              f"rgb({m_строка(м['обрНомер']['цвет'])})")
    if м["номер"]["вес"] != м["обрНомер"]["вес"]:
        плохо(f"номер раздела в таблице другого веса, чем в расчёте: "
              f"{м['номер']['вес']} против {м['обрНомер']['вес']}")
    if м["имя"]["цвет"] != м["обрИмя"]:
        плохо(f"название раздела в таблице набрано не чернилами акцента: "
              f"rgb({m_строка(м['имя']['цвет'])}) против "
              f"rgb({m_строка(м['обрИмя'])})")
    # Непрозрачность — отдельная мерка: цвет может быть верным, а элемент
    # приглушён чужим правилом, и на экране это тот же серый.
    for имя, ч in (("номер", м["номер"]), ("название", м["имя"])):
        if ч["муть"] < 1:
            плохо(f"{имя} раздела приглушено: opacity {ч['муть']} — "
                  "на экране это тот же серый, каким бы ни был цвет")
    стр.locator("#komplTable").screenshot(
        path=str(pathlib.Path(__file__).parent / "бланк-разделы.png"))


