#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Номера приходных ордеров не повторяются во всей компании.

Константин 18.10.2026 на предложение вести выданные номера в базе («номер
остаётся случайным и не по порядку, но в компании не повторяется нигде»):
«конечно, так и надо было сразу сделать».

Проба держит, на заглушке базы с ключом «год + номер», как в таблице
cash_order_numbers:
  • выданный номер записывается в базу — с годом даты ордера, кодом расчёта
    и днём;
  • номер, занятый другим расчётом, заменяется другим случайным, и в базе
    повторов нет; если заняты все трёхзначные номера года — встаёт
    четырёхзначный;
  • тот же номер в другом году свободен;
  • новый день ордера — новый номер тоже записывается;
  • вписанный рукой номер, занятый другим расчётом, — подсказка сверить с
    кассовой книгой, а свой же номер этого расчёта подсказки не даёт.
Данные учебные.

    python3 check_cash_order_unique.py
"""
import pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).parent))
import check_preset_chip as м
import check_approval_report as з
from playwright.sync_api import sync_playwright

НАХОДКИ = []


def плохо(т):
    НАХОДКИ.append(т)


ВЫДАТЬ = """async ([дата, занятые]) => {
  window.__ТАБЛИЦЫ.cash_order_numbers = занятые.map(н => ({ year: 2026, number: н, preset_code: '999999', day: '2026-10-01' }));
  _ордер = { договор: 1, номер: '', выдан: false, дата, днём: '', номера: {}, отмечены: {}, список: false };
  выдатьНомерОрдера(); await _ордерЗапись;
  const код = String(_активныйПресетКод() || '');
  const мои = window.__ТАБЛИЦЫ.cash_order_numbers.filter(р => String(р.preset_code) === код);
  const все = window.__ТАБЛИЦЫ.cash_order_numbers.map(р => р.year + ':' + р.number);
  return { номер: _ордер.номер, мои: мои.map(р => [р.year, String(р.number), р.day]), повторы: все.length - new Set(все).size, код }; }"""


def прогон(бр, порт):
    н = "[1440]"
    стр, ошибки = з.начать(бр, порт, 1440, 900)
    if not стр.evaluate("() => typeof закрепитьНомерОрдера === 'function'"):
        плохо(f"{н} в калькуляторе нет записи номеров ордеров в базу"); стр.close(); return
    # Пустая база — номер записан.
    р = стр.evaluate(ВЫДАТЬ, ["2026-10-18", []])
    if not р["мои"] or р["мои"][0] != [2026, р["номер"], "2026-10-18"] or not р["код"]:
        плохо(f"{н} выданный номер не записан в базу с годом, кодом и днём: {р}")
    # Занят почти весь год: свободны 3 номера — вероятнее всего придётся
    # перебрать, и в базе не должно стать повторов.
    свободные = {555, 556, 557}
    занятые = [ч for ч in range(100, 1000) if ч not in свободные]
    р = стр.evaluate(ВЫДАТЬ, ["2026-10-18", занятые])
    if р["повторы"] or not р["мои"] or int(р["номер"]) in занятые:
        плохо(f"{н} номер совпал с занятым другим расчётом или в базе повтор: {р['номер']}, повторов {р['повторы']}")
    # Заняты все трёхзначные — встаёт четырёхзначный.
    р = стр.evaluate(ВЫДАТЬ, ["2026-10-18", list(range(100, 1000))])
    if len(р["номер"]) != 4 or р["повторы"] or not р["мои"]:
        плохо(f"{н} все трёхзначные заняты — ждали четырёхзначный и запись в базе: {р['номер']}, {р['мои']}")
    # Другой год — тот же номер свободен.
    р = стр.evaluate("""async () => {
      window.__ТАБЛИЦЫ.cash_order_numbers = [{ year: 2026, number: 321, preset_code: '999999', day: '2026-10-01' }];
      _ордер = { договор: 1, номер: '321', выдан: true, дата: '2027-01-10', днём: '2027-01-10', номера: {}, отмечены: {}, список: false };
      await закрепитьНомерОрдера('2027-01-10', false);
      return { номер: _ордер.номер, строк: window.__ТАБЛИЦЫ.cash_order_numbers.filter(р => р.number === 321).map(р => р.year) }; }""")
    if р["номер"] != "321" or sorted(р["строк"]) != [2026, 2027]:
        плохо(f"{н} тот же номер в другом году должен быть свободен: {р}")
    # Новый день — новый номер тоже записан.
    р = стр.evaluate("""async () => {
      window.__ТАБЛИЦЫ.cash_order_numbers = [];
      _ордер = { договор: 1, номер: '', выдан: false, дата: '2026-10-18', днём: '', номера: {}, отмечены: {}, список: false };
      выдатьНомерОрдера(); await _ордерЗапись;
      сменитьДеньОрдера('2026-10-20'); await _ордерЗапись;
      return { номера: [_ордер.номера['2026-10-18'], _ордер.номер], в_базе: window.__ТАБЛИЦЫ.cash_order_numbers.map(р => [String(р.number), р.day]) }; }""")
    if sorted(р["в_базе"]) != sorted([[р["номера"][0], "2026-10-18"], [р["номера"][1], "2026-10-20"]]):
        плохо(f"{н} номер нового дня не записан: {р}")
    # Рукой — чужой номер: подсказка; свой: молчание.
    р = стр.evaluate("""async () => {
      const код = String(_активныйПресетКод() || '');
      window.__ТАБЛИЦЫ.cash_order_numbers = [{ year: 2026, number: 444, preset_code: '999999', day: '2026-10-01' },
                                            { year: 2026, number: 777, preset_code: код, day: '2026-10-18' }];
      _ордер = { договор: 1, номер: '444', выдан: true, дата: '2026-10-18', днём: '2026-10-18', номера: {}, отмечены: {}, список: false };
      window.__тосты = [];
      await закрепитьНомерОрдера('2026-10-18', true);
      const чужой = window.__тосты.slice();
      window.__тосты = []; _ордер.номер = '777';
      await закрепитьНомерОрдера('2026-10-18', true);
      return { чужой, свой: window.__тосты.slice(), номер: _ордер.номер }; }""")
    if not any("уже выдан" in т for т in р["чужой"]):
        плохо(f"{н} вписанный рукой чужой номер прошёл без подсказки: {р['чужой']}")
    if р["свой"] or р["номер"] != "777":
        плохо(f"{н} свой номер этого расчёта дал подсказку или был заменён: {р}")
    if ошибки:
        плохо(f"{н} ошибки страницы: {ошибки[:3]}")
    стр.close()


def главная():
    с, порт = м.сервер()
    try:
        with sync_playwright() as п:
            бр = п.chromium.launch(executable_path=м.хром())
            try:
                прогон(бр, порт)
            finally:
                бр.close()
    finally:
        с.shutdown()
    if НАХОДКИ:
        print("НАХОДКИ:")
        for т in НАХОДКИ:
            print(" —", т)
        sys.exit(1)
    print("Чисто: номер ордера записывается в базу по году; занятый другим расчётом заменяется, все трёхзначные заняты — "
          "четырёхзначный; другой год свободен; новый день записан; чужой номер рукой — подсказка, свой — нет.")


if __name__ == "__main__":
    главная()
