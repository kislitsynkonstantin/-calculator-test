#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Снимок для ссылки клиенту берёт разделы спецификации, а не окна печати.

Константин 24.09.2026, снимком листа по ссылке рядом с печатью: по ссылке
«0 ₽» и ни одного раздела, в печати — 6 318 543 ₽. Две причины, обе старше
этого дня: набор разделов печати пуст, пока окно печати не открывали (ссылка,
выданная из списка пресетов, уходила пустой), а печать договора сужала его до
разделов договора (ссылка несла одну его часть — в базе лежал снимок на
4,58 млн при печати на 6,32).

Проба гоняет все три пути:

  • окно печати не открывали — снимок полный: итог равен итогу расчёта,
    разделы есть;
  • в окне печати выбран договор — снимок всё равно полный, а окно печати
    осталось на договоре: и набор, и лист в окне прежние;
  • в спецификации раздел снят вручную — снимок его не несёт: выбор
    спецификации ссылка уважает.

    python3 check_link_snapshot_sections.py
"""
import importlib.util
import pathlib
import sys

from playwright.sync_api import sync_playwright

ЗДЕСЬ = pathlib.Path(__file__).resolve().parent
спец = importlib.util.spec_from_file_location("пт", ЗДЕСЬ / "check_palette_tone.py")
ПТ = importlib.util.module_from_spec(спец)
спец.loader.exec_module(ПТ)
НАХОДКИ = []

ШАГИ = """async () => {
  const пауза = (мс = 300) => new Promise(r => setTimeout(r, мс));
  const в = {};
  const сн = () => { const с = снимокДляСсылки() || {}; return { итог: с.итог || 0, разделы: (с.разделы || []).map(р => р.ключ) }; };
  // опции каталога с ценой — чтобы итог был не одной базой
  OPTIONS.filter(o => !o.included && o.price && document.getElementById('chk_' + o.id)).slice(0, 3)
    .forEach(o => { try { toggleOpt(o.id); } catch (e) {} });
  await пауза();
  в.итогРасчёта = al2ИтогДо();
  // 1. окно печати не открывали
  в.безОкна = сн();
  // 2. договор в окне печати
  openPrintPreview(); await пауза(600);
  в.всеРазделы = [...printActiveSections].length;
  if (!contractsConfig.length) contractsConfig.push({ id: 1, name: 'Основной', sections: ['frame'] });
  const дог = contractsConfig[0];
  дог.sections = ['frame'];
  printActiveContractId = null;
  printSelectContract(дог.id); await пауза();
  в.окноДо = [...printActiveSections].sort();
  в.договор = сн();
  в.окноПосле = [...printActiveSections].sort();
  в.договорАктивен = printActiveContractId === дог.id;
  // 3. спецификация без одного раздела
  printSelectContract(дог.id); await пауза();          // снять договор
  printSectionSelectAll(true); await пауза();
  const снять = (в.безОкна.разделы.find(к => к !== 'frame') || 'insulation');
  togglePrintSection(снять, false); await пауза();
  в.снятый = снять;
  в.безРаздела = сн();
  return в;
}"""


def главная():
    с, порт = ПТ.сервер()
    try:
        with sync_playwright() as pw:
            бр = pw.chromium.launch(executable_path=ПТ.хром(), args=["--no-sandbox"])
            for ш in (390, 1440):
                к, стр, ошибки = ПТ.открыть(бр, порт, ш, 900, True, False)
                где = f"{ш}px"
                try:
                    в = стр.evaluate(ШАГИ)
                except Exception as e:
                    НАХОДКИ.append(f"[{где}] проба оборвалась: {e!s:.300}")
                    к.close()
                    continue
                if not в["безОкна"]["разделы"] or в["безОкна"]["итог"] != в["итогРасчёта"]:
                    НАХОДКИ.append(f"[{где}] без окна печати снимок {в['безОкна']['итог']} ₽, разделов "
                                   f"{len(в['безОкна']['разделы'])}, а расчёт {в['итогРасчёта']} ₽")
                if в["договор"]["итог"] != в["итогРасчёта"] or len(в["договор"]["разделы"]) < 2:
                    НАХОДКИ.append(f"[{где}] при договоре в окне печати снимок {в['договор']['итог']} ₽ и "
                                   f"{в['договор']['разделы']} — ушла часть договора")
                if в["окноДо"] != в["окноПосле"] or not в["договорАктивен"]:
                    НАХОДКИ.append(f"[{где}] сборка снимка сбила окно печати: было {в['окноДо']}, стало {в['окноПосле']}")
                if в["снятый"] in в["безРаздела"]["разделы"]:
                    НАХОДКИ.append(f"[{где}] раздел «{в['снятый']}», снятый в спецификации, остался в снимке")
                if ошибки:
                    НАХОДКИ.append(f"[{где}] ошибки страницы: " + "; ".join(ошибки)[:200])
                print(f"  {где}: расчёт {в['итогРасчёта']}, без окна {в['безОкна']['итог']}, "
                      f"при договоре {в['договор']['итог']}, разделов {len(в['договор']['разделы'])}")
                к.close()
            бр.close()
    finally:
        с.shutdown()
    if НАХОДКИ:
        print("НАХОДКИ:")
        for н in НАХОДКИ:
            print("  ✗", н)
        sys.exit(1)
    print("Чисто: снимок ссылки полный и без открытого окна печати, и при договоре в нём, "
          "окно печати остаётся как было, а снятый в спецификации раздел в ссылку не идёт.")


if __name__ == "__main__":
    главная()
