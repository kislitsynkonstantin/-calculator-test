"""«Проверка»: проект по планировке — этажность, терраса, габариты.

Константин 17.10.2026, снимком строк разбора «Габариты», «Этажность», «Форма
кровли», «Терраса», «Парная»: «Вот эти пункты все добавь к проверке по
планировке и визуализации».

Сведения читаются из текста PDF архитектора, когда планировка добавляется
файлом, и хранятся на снимке (data-plan). Проба сама собирает учебные листы в
Chromium — названия листов, экспликацию, размерные числа (горизонтальные и
повёрнутые), штамп с годом — прикрепляет их через «Добавить изображение», как
менеджер, и держит:
  • этажность: мансарда или второй этаж на листах у одноэтажного проекта —
    замечание; один «План 1 этажа» у проекта в полтора или два этажа —
    замечание; мансарда у двухэтажного и наоборот — молчит;
  • терраса: на плане есть, у проекта площадей террас нет — замечание с
    площадью; у проекта есть, в прочитанной экспликации нет — замечание;
    подпись «Терраса» на чертеже без площади тоже считается;
  • габариты: размер в названии против размерных чисел плана, ±0,5 м, стороны
    в любом порядке, «х» кириллицей; числа штампа и таблицы справа не
    считаются; размеры с листа «Обмеры» считаются;
  • пункты ведут к сведениям проекта (#projectInfo);
  • планировка картинкой — один вопрос сверить всё глазами, вместе с парной;
  • сведения живут в пресете: сохранение, выгрузка в хранилище, открытие.
Проекты, площади и комнаты в пробе выдуманы: репозиторий публичный.

    python3 check_plan_by_pdf.py
"""
import functools, http.server, json, os, pathlib, re, socketserver, tempfile, threading
from playwright.sync_api import sync_playwright

КОРЕНЬ = pathlib.Path(os.environ.get("BM_ROOT") or pathlib.Path(__file__).resolve().parent.parent.parent)
ЗДЕСЬ = pathlib.Path(__file__).parent
PDFJS = ЗДЕСЬ / "pdfjs"
КАРТИНКА = ЗДЕСЬ / "образцы_приложения2" / "планировка.png"
ЗАГЛУШКА = (ЗДЕСЬ / "stub_sb.js").read_text(encoding="utf-8")
ФИКСТУРА = json.loads((ЗДЕСЬ / "kit_fixture.json").read_text(encoding="utf-8"))
ЦЕНЫ = ("window.__ТАБЛИЦЫ = Object.assign(window.__ТАБЛИЦЫ || {}, " + json.dumps(ФИКСТУРА, ensure_ascii=False) + ");"
        "window.addEventListener('DOMContentLoaded', () => { window._sbProfile = Object.assign(window._sbProfile || {}, { role: 'manager' }); });")
НАХОДКИ, ОТЧЁТ = [], []
ПАПКА = pathlib.Path(tempfile.mkdtemp(prefix="план_pdf_"))


def факт(ок, т):
    (ОТЧЁТ if ок else НАХОДКИ).append(т)


class Тихий(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *а):
        pass


def отдать(r):
    путь = PDFJS / r.request.url.rsplit("/", 1)[-1]
    if путь.exists():
        r.fulfill(status=200, content_type="application/javascript", body=путь.read_bytes())
    else:
        r.abort()


# ── Учебные листы A3: чертёж слева, экспликация справа, штамп внизу ──
def текст(x, y, т, повёрнут=False, кегль=4):
    поворот = "transform:rotate(-90deg);transform-origin:left top;" if повёрнут else ""
    return f'<div style="position:absolute;left:{x}mm;top:{y}mm;font-size:{кегль}mm;white-space:nowrap;{поворот}">{т}</div>'


def лист(куски):
    штамп = [текст(300, 272, "Стадия", кегль=3), текст(330, 272, "Лист", кегль=3), текст(350, 272, "Листов", кегль=3),
             текст(300, 282, "ЭП", кегль=3), текст(330, 282, "1", кегль=3), текст(380, 282, "2026", кегль=3)]
    контур = '<div style="position:absolute;left:40mm;top:50mm;width:160mm;height:110mm;border:1.5mm solid #000"></div>'
    return '<div style="position:relative;width:420mm;height:297mm;page-break-after:always;overflow:hidden">' + контур + "".join(куски + штамп) + "</div>"


def экспликация(строки):
    к = [текст(260, 40, "Экспликация помещений")]
    for н, (номер, имя, площадь) in enumerate(строки):
        у = 50 + н * 8
        к += [текст(260, у, номер), текст(270, у, имя)] + ([текст(340, у, площадь)] if площадь else [])
    return к


РАЗМЕРЫ_А = [текст(100, 30, "9 600"), текст(60, 40, "3 600"), текст(130, 40, "6 000"), текст(25, 140, "6 000", повёрнут=True)]
ЛИСТЫ = {
    # Один этаж, терраса в экспликации, габариты 9,6 × 6,0; в таблице справа
    # лишнее число «12 500», в штампе год — оба не размеры плана.
    "А": [лист([текст(20, 12, "План 1 этажа")] + РАЗМЕРЫ_А
               + экспликация([("1", "Гостиная", "20,9"), ("2", "Парная", "6,9"), ("3", "Терраса", "12,4")]) + [текст(360, 120, "12 500")])],
    # Терраса — подписью на чертеже, без площади; размеры — на листе «Обмеры».
    "Б": [лист([текст(20, 12, "План 1 этажа"), текст(90, 100, "Терраса")]
               + экспликация([("1", "Гостиная", "20,9"), ("2", "Парная", "6,9"), ("3", "Спальня", "12,8")])),
          лист([текст(20, 12, "План 1 этажа. Обмеры"), текст(100, 30, "8 300"), текст(25, 140, "7 800", повёрнут=True)])],
    # Первый этаж и мансарда на одном листе, террасы нет, размеров нет.
    "В": [лист([текст(20, 12, "План 1 этажа"), текст(20, 170, "План мансарды")]
               + экспликация([("1", "Гостиная", "20,9"), ("2", "Парная", "6,9"), ("3", "Спальня", "12,8")]))],
}

ПУНКТЫ = """() => { const п = проверкаПоЧекЛисту();
  return { з: п.замечания.filter(х => х.раздел === 'project' && !/^Цена/.test(х.т)).map(х => ({ т: х.т, эл: х.эл })),
           в: п.вопросы.filter(т => /планировк/i.test(т) && !/^Добавить/.test(т)), а: п.адреса }; }"""
СНИМКИ = """() => [...document.querySelectorAll('#imageCanvas .canvas-img-item')].map(э => ({ вид: э.dataset.kind || '', план: э.dataset.plan || '' }))"""
ПРОЕКТ = "([и, з]) => { selectedProject[и] = з; calc(); }"

socketserver.TCPServer.allow_reuse_address = True
с = socketserver.TCPServer(("127.0.0.1", 0), functools.partial(Тихий, directory=str(КОРЕНЬ)))
threading.Thread(target=с.serve_forever, daemon=True).start()
хром = os.environ.get("BM_CHROMIUM") or str(sorted(pathlib.Path("/opt/pw-browsers").glob("chromium-*/chrome-linux/chrome"))[-1])


def ждать(стр, мс=350):
    стр.wait_for_timeout(мс)


def прикрепить(стр, файл):
    стр.evaluate("() => { canvasClearAll(); }")
    стр.set_input_files("#canvasFileInput", str(файл))
    for _ in range(60):
        стр.wait_for_timeout(250)
        if стр.evaluate("() => canvasItems.length"):
            break
    стр.wait_for_timeout(1200)
    стр.evaluate("() => calc()")
    ждать(стр)


def сведения(стр):
    п = [json.loads(х["план"]) for х in стр.evaluate(СНИМКИ) if х["вид"] == "план" and х["план"]]
    return п[0] if п else None


def замечания(стр):
    return [х["т"] for х in стр.evaluate(ПУНКТЫ)["з"]]


with sync_playwright() as pw:
    бр = pw.chromium.launch(executable_path=хром, args=["--no-sandbox"])
    # Листы собираются в PDF самим Chromium — так в них настоящий текст с
    # матрицами, как у архитектора, а не картинка.
    печать = бр.new_page()
    for имя, листы in ЛИСТЫ.items():
        печать.set_content("<html><head><meta charset='utf-8'><style>@page{size:420mm 297mm;margin:0}body{margin:0;font-family:sans-serif}</style></head><body>"
                           + "".join(листы) + "</body></html>")
        печать.pdf(path=str(ПАПКА / f"план_{имя}.pdf"), width="420mm", height="297mm", print_background=True)
    печать.close()

    стр = бр.new_page(viewport={"width": 1440, "height": 1000})
    ошибки = []
    стр.on("pageerror", lambda e: ошибки.append(str(e)))
    стр.route("**/fonts.googleapis.com/**", lambda r: r.abort())
    стр.route("**/cdnjs.cloudflare.com/ajax/libs/pdf.js/**", отдать)
    стр.add_init_script(ЗАГЛУШКА)
    стр.add_init_script(ЦЕНЫ)
    стр.goto(f"http://127.0.0.1:{с.server_address[1]}/index.html", wait_until="load")
    стр.wait_for_timeout(2500)
    стр.evaluate("() => { const б = document.getElementById('pricingErrorScreen'); if (б) б.style.display = 'none'; selectProjectOption(0); calc(); }")
    ждать(стр, 500)
    стр.evaluate("() => { window.__выгрузка = uploadCanvasToStorage; window.__проект = selectedProject.slice(); }")
    исходный = стр.evaluate("() => selectedProject.slice(0, 9)")
    факт(исходный[0] == "Проба дом 8×8" and str(исходный[4]) == "1" and (исходный[7] or 0) + (исходный[8] or 0) > 0,
         f"проект пробы — «Проба дом 8×8», один этаж, с террасой: {исходный}")
    вернуть = "() => { window.__проект.forEach((з, и) => { selectedProject[и] = з; }); calc(); }"

    # ── Чтение листов без чертежа: названия и строки ──
    чтение = стр.evaluate("""() => { if (typeof сведенияПланировки !== 'function') return null;
      const лист = строки => ({ текст: { items: строки.flatMap(([y, куски]) => куски.map(([x, т]) => ({ str: т, transform: [1, 0, 0, 1, x, y] }))) } });
      return {
        второй: сведенияПланировки([лист([[800, [[10, 'План второго этажа']]]])]),
        первый: сведенияПланировки([лист([[800, [[10, 'План 1-го этажа']]]])]),
        кровля: сведенияПланировки([лист([[800, [[10, 'План кровли']]], [700, [[10, 'План фундамента']]]])]),
        веранда: сведенияПланировки([лист([[500, [[10, '5'], [20, 'Крытая веранда'], [200, '14,2']]], [490, [[10, '1'], [20, 'Кухня'], [200, '9,1']]]])]),
        пусто: сведенияПланировки([лист([])]),
      }; }""")
    факт(чтение is not None, "функция чтения планировки есть")
    if чтение:
        факт(чтение["второй"] and чтение["второй"]["upper"] == "этаж" and not чтение["второй"]["first"], f"«План второго этажа» — второй этаж: {чтение['второй']}")
        факт(чтение["первый"] and чтение["первый"]["first"] and not чтение["первый"]["upper"], f"«План 1-го этажа» — первый этаж: {чтение['первый']}")
        факт(чтение["кровля"] is None, f"план кровли и фундамента — не этажи, сведений нет: {чтение['кровля']}")
        факт(чтение["веранда"] and чтение["веранда"]["terrace"] and чтение["веранда"]["terraceArea"] == 14.2 and чтение["веранда"]["rooms"] == 2,
             f"«Крытая веранда 14,2» — терраса, две строки экспликации: {чтение['веранда']}")
        факт(чтение["пусто"] is None, "лист без текста — сведений нет")

    # ── Лист А: один этаж, терраса 12,4, габариты 9,6 × 6 ──
    прикрепить(стр, ПАПКА / "план_А.pdf")
    св = сведения(стр)
    факт(bool(св) and св.get("first") and not св.get("upper") and св.get("terrace") and св.get("terraceArea") == 12.4 and св.get("rooms") == 3,
         f"лист А: первый этаж, терраса 12,4, три строки экспликации: {св}")
    факт(bool(св) and св.get("w") == [9600, 6000, 3600] and св.get("d") == [6000],
         f"лист А: размеры по сторонам — 9 600, 6 000, 3 600 и повёрнутое 6 000; «12 500» из таблицы и год из штампа не взяты: {св and (св.get('w'), св.get('d'))}")
    д = стр.evaluate(ПУНКТЫ)
    факт([х["т"] for х in д["з"]] == ["Габариты по планировке 9,6×6 м, в названии проекта 8×8 — расхождение 2 м, сверить проект"],
         f"лист А, проект 8×8: одно замечание — габариты: {д['з']}")
    факт(all(х["эл"] == "projectInfo" for х in д["з"]), f"замечание ведёт к сведениям проекта: {д['з']}")
    факт(not д["в"], f"лист А: вопроса «сверить с планировкой» нет — сведения прочитаны: {д['в']}")
    for имя, ждём in [("Проба дом 9,5×6", []), ("Проба дом 6х10", []), ("Проба дом 6×6", []), ("Проба дом", []),
                      ("Проба дом 12×5", ["Габариты по планировке 9,6×6 м, в названии проекта 12×5 — расхождение 2,4 м, сверить проект"])]:
        стр.evaluate(ПРОЕКТ, [0, имя]); ждать(стр)
        факт(замечания(стр) == ждём, f"лист А, «{имя}»: {'молчит' if not ждём else 'замечание о габаритах'}: {замечания(стр)}")
    стр.evaluate(вернуть); ждать(стр)
    стр.evaluate(ПРОЕКТ, [4, "2"]); ждать(стр)
    факт(замечания(стр)[:1] == ["По планировке один этаж, в проекте два — сверить этажность"], f"лист А, проект в два этажа: {замечания(стр)}")
    стр.evaluate(ПРОЕКТ, [4, "1.5"]); ждать(стр)
    факт(замечания(стр)[:1] == ["По планировке один этаж, в проекте полтора — сверить этажность"], f"лист А, проект в полтора этажа: {замечания(стр)}")
    стр.evaluate(вернуть)
    стр.evaluate("() => { selectedProject[7] = 0; selectedProject[8] = 0; calc(); }"); ждать(стр)
    факт("По планировке есть терраса 12,4 м², в проекте площади террас нет — сверить" in замечания(стр), f"лист А, проект без террас: {замечания(стр)}")
    стр.evaluate(вернуть); ждать(стр)

    # Сведения живут в пресете: сохранение, выгрузка, открытие.
    сост = стр.evaluate("() => collectState()")
    сохр = [х.get("plan") for х in сост.get("canvasImages", []) if х.get("kind") == "план"]
    факт(len(сохр) == 1 and isinstance(сохр[0], dict) and сохр[0].get("w") == [9600, 6000, 3600], f"сведения в снимке расчёта: {сохр}")
    выгр = стр.evaluate("""async (снимки) => { const б = _sbUser; _sbUser = б || { id: 'проба' };
      try { return await window.__выгрузка('проба', снимки.map(с => ({ ...с, src: 'https://example.invalid/' + (с.kind || 'x') + '.png' }))); }
      finally { _sbUser = б; } }""", сост.get("canvasImages", []))
    факт([bool(х.get("plan")) for х in выгр if х.get("kind") == "план"] == [True], f"выгрузка в хранилище несёт сведения: {[х.get('plan') for х in выгр]}")
    стр.evaluate("() => { canvasClearAll(); calc(); }"); ждать(стр)
    факт(not замечания(стр), "холст пуст — замечаний по планировке нет")
    стр.evaluate("async (с) => { await restoreCanvasFromUrls(с); calc(); }", [{**х, "url": х["src"]} for х in сост["canvasImages"]]); ждать(стр, 600)
    факт(bool(сведения(стр)) and замечания(стр) == ["Габариты по планировке 9,6×6 м, в названии проекта 8×8 — расхождение 2 м, сверить проект"],
         f"открытый расчёт: сведения снова на снимке, замечание то же: {замечания(стр)}")

    # ── Лист Б: подпись «Терраса» без площади, размеры на листе «Обмеры» ──
    прикрепить(стр, ПАПКА / "план_Б.pdf")
    св = сведения(стр)
    факт(bool(св) and св.get("terrace") and not св.get("terraceArea") and св.get("w") == [8300] and св.get("d") == [7800],
         f"лист Б: терраса подписью, размеры 8 300 × 7 800 с листа «Обмеры»: {св}")
    факт(len([х for х in стр.evaluate(СНИМКИ) if х["вид"] == "план"]) == 1, "лист Б: «Обмеры» в планировки не попали — снимок один")
    факт(not замечания(стр), f"лист Б, проект 8×8 с террасой: 8,3 × 7,8 в пределах 0,5 м — молчит: {замечания(стр)}")
    стр.evaluate("() => { selectedProject[7] = 0; selectedProject[8] = 0; calc(); }"); ждать(стр)
    факт(замечания(стр) == ["По планировке есть терраса, в проекте площади террас нет — сверить"], f"лист Б, проект без террас: {замечания(стр)}")
    стр.evaluate(вернуть); ждать(стр)

    # ── Лист В: первый этаж и мансарда, террасы нет, размеров нет ──
    прикрепить(стр, ПАПКА / "план_В.pdf")
    св = сведения(стр)
    факт(bool(св) and св.get("first") and св.get("upper") == "мансарда" and not св.get("terrace") and not св.get("w"), f"лист В: мансарда, без террасы и размеров: {св}")
    факт(замечания(стр) == ["По планировке есть мансарда, в проекте один этаж — сверить этажность",
                            "В проекте терраса 10 м², в экспликации планировки её нет — сверить"], f"лист В, одноэтажный проект с террасой: {замечания(стр)}")
    for э in ["1.5", "2"]:
        стр.evaluate(ПРОЕКТ, [4, э]); ждать(стр)
        факт(not any("этажност" in т for т in замечания(стр)), f"лист В, проект в {э} этажа: мансарда — про этажность молчит: {замечания(стр)}")
    стр.evaluate(вернуть); ждать(стр)

    # ── Планировка картинкой: один вопрос про всё ──
    прикрепить(стр, КАРТИНКА)
    стр.evaluate("() => { document.querySelectorAll('#imageCanvas .canvas-img-item').forEach(э => { э.dataset.kind = 'план'; }); calc(); }"); ждать(стр, 600)
    д = стр.evaluate(ПУНКТЫ)
    вопрос = "Сверить с планировкой габариты, этажность, террасу, размер парного отделения и печь"
    факт(д["в"] == [вопрос] and not д["з"], f"планировка картинкой: один вопрос, замечаний нет: {д['в']} {д['з']}")
    факт((д["а"].get(вопрос) or {}).get("эл") == "imageCanvasCard", f"вопрос ведёт к блоку изображений: {д['а'].get(вопрос)}")
    стр.evaluate("() => { document.querySelectorAll('#imageCanvas .canvas-img-item').forEach(э => { э.dataset.steam = '5'; }); calc(); }"); ждать(стр)
    факт(стр.evaluate(ПУНКТЫ)["в"] == ["Сверить с планировкой габариты, этажность, террасу"], f"площадь парной известна — в вопросе парной нет: {стр.evaluate(ПУНКТЫ)['в']}")
    факт(not ошибки, f"ошибок страницы нет: {ошибки[:2]}")
    бр.close()
с.shutdown()

for т in ОТЧЁТ:
    print("    ок  " + т)
if НАХОДКИ:
    print("НАХОДКИ:")
    for т in НАХОДКИ:
        print("  ✗ " + т)
    raise SystemExit(1)
print("Чисто: этажность, терраса и габариты сверяются с планировкой PDF; планировка картинкой — один вопрос; сведения живут в пресете.")
