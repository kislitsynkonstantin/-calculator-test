    факт(замечания(стр) == ["По планировке 8,3×7,8 м, один этаж, с террасой; выбран проект без террасы. Подходящих в каталоге нет — сверить проект"],
         f"лист Б, проект без террас, подходящих нет: {замечания(стр)}")
    стр.evaluate(вернуть); ждать(стр)

    # ── Лист В: первый этаж и мансарда, террасы нет, размеров нет ──
