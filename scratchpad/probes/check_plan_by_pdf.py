    for э, слова in [("2", "в два этажа"), ("1.5", "в полтора этажа")]:
        стр.evaluate(ПРОЕКТ, [4, э]); ждать(стр)
        факт(замечания(стр) == [ПЛАН_А + слова + ХВОСТ], f"лист А, размер впору, проект {слова}: {замечания(стр)}")
    стр.evaluate(ПРОЕКТ, [4, "1"])
    стр.evaluate("() => { selectedProject[7] = 0; selectedProject[8] = 0; calc(); }"); ждать(стр)
    факт(замечания(стр) == [ПЛАН_А + "без террасы" + ХВОСТ], f"лист А, размер впору, проект без террас: {замечания(стр)}")
    стр.evaluate(вернуть); ждать(стр)

    # Сведения живут в пресете: сохранение, выгрузка, открытие.
