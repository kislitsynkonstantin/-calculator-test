#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Журнал действий помнит последний период — в аккаунте.

Константин 29.09.2026, снимком журнала: «тут последний период запоминай на
аккаунт». Журнал открывался всегда на «7 днях», сколько ни выбирай.

Проба на 390 держит:
  • выбранный период уходит в настройки и в профиль аккаунта;
  • закрыли и открыли журнал — он на этом периоде, кнопка отмечена;
  • период из профиля приходит на новое устройство: страница с профилем,
    где записан «Текущий месяц», открывает журнал на нём;
  • свой диапазон дат запоминается вместе с датами;
  • переход из мини-окна («всё время» по одному пресету) разовый: в аккаунт
    не пишется, и следующее открытие журнала — на своём периоде.

    python3 check_actionlog_period.py
"""
import pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).parent))
import check_preset_chip as м
import check_preset_card as к
from playwright.sync_api import sync_playwright

НАХОДКИ = []
ПРОФИЛЬ = "() => { const п = (window.__ТАБЛИЦЫ.profiles || [])[0]; return п && п.app_settings ? { период: п.app_settings.alPeriod, даты: п.app_settings.alRange } : null; }"
СЕЙЧАС = """() => ({ период: _alПериод, кнопка: (document.querySelector('#alPins .al-chip.on') || {}).textContent || '', подпись: (document.getElementById('alPerLabel') || {}).textContent || '' })"""


def открыть_журнал(стр):
    стр.evaluate("() => openActionLog()"); стр.wait_for_timeout(900)
    return стр.evaluate(СЕЙЧАС)


def закрыть_журнал(стр):
    стр.evaluate("() => closeActionLog()"); стр.wait_for_timeout(300)


def прогон(бр, порт):
    н = "[390]"
    стр, ошибки = к.начать(бр, порт, 390, 844, False)
    с = открыть_журнал(стр)
    if с["период"] != "7":
        НАХОДКИ.append(f"{н} без выбора журнал открылся не на 7 днях: {с}")
    # выбор «30 дней» кнопкой
    стр.locator("#alPins .al-chip", has_text="30 дней").first.click(); стр.wait_for_timeout(600)
    if стр.evaluate("() => appSettings.alPeriod") != "30" or (стр.evaluate(ПРОФИЛЬ) or {}).get("период") != "30":
        НАХОДКИ.append(f"{н} выбранный период не записан в аккаунт: настройки {стр.evaluate('() => appSettings.alPeriod')}, профиль {стр.evaluate(ПРОФИЛЬ)}")
    закрыть_журнал(стр)
    с = открыть_журнал(стр)
    if с["период"] != "30" or "30" not in с["кнопка"]:
        НАХОДКИ.append(f"{н} повторно открытый журнал не на 30 днях: {с}")
    закрыть_журнал(стр)
    # свой диапазон
    стр.evaluate("() => { _alДиапазон = { от: '2026-09-01', до: '2026-09-15' }; alПериод('свой'); }"); стр.wait_for_timeout(500)
    п = стр.evaluate(ПРОФИЛЬ) or {}
    if п.get("период") != "свой" or (п.get("даты") or {}).get("от") != "2026-09-01":
        НАХОДКИ.append(f"{н} свой диапазон не записан с датами: {п}")
    закрыть_журнал(стр)
    # переход из мини-окна — разовый
    к.открыть(стр); стр.wait_for_timeout(300)
    стр.evaluate("() => { _пкВкладка = 'l'; заполнитьКарточкуЗначка(); }"); стр.wait_for_timeout(300)
    кн = стр.locator("#presetChipCard [data-act='to-log']")
    if кн.count():
        кн.first.click(); стр.wait_for_timeout(900)
        if стр.evaluate("() => _alПериод") != "всё":
            НАХОДКИ.append(f"{н} переход из мини-окна открыл журнал не за всё время")
        if (стр.evaluate(ПРОФИЛЬ) or {}).get("период") != "свой":
            НАХОДКИ.append(f"{н} переход из мини-окна переписал период в аккаунте: {стр.evaluate(ПРОФИЛЬ)}")
        закрыть_журнал(стр)
        стр.evaluate("() => { _alПресет = null; }")
        с = открыть_журнал(стр)
        if с["период"] != "свой":
            НАХОДКИ.append(f"{н} после перехода из мини-окна журнал открылся не на своём периоде: {с}")
        закрыть_журнал(стр)
    else:
        НАХОДКИ.append(f"{н} в мини-окне нет перехода в журнал — разовый период не проверен")
    for о in [о for о in ошибки if "supabase.co" not in о][:3]:
        НАХОДКИ.append(f"{н} ошибка страницы: {о[:160]}")
    стр.close()
    # ── новое устройство: период приходит из профиля ──
    было = м.ТАБЛИЦЫ_JS
    м.ТАБЛИЦЫ_JS = было + "\n;window.__ТАБЛИЦЫ.profiles.forEach(п => { п.app_settings = Object.assign({}, п.app_settings, { alPeriod: 'мес' }); });"
    try:
        стр, ошибки = к.начать(бр, порт, 390, 844, False)
    finally:
        м.ТАБЛИЦЫ_JS = было
    с = открыть_журнал(стр)
    if с["период"] != "мес" or "месяц" not in с["кнопка"].lower():
        НАХОДКИ.append(f"{н} период из профиля не пришёл на новое устройство: {с}")
    for о in [о for о in ошибки if "supabase.co" not in о][:3]:
        НАХОДКИ.append(f"{н} новое устройство, ошибка страницы: {о[:160]}")
    стр.close()


def главная():
    с, порт = м.сервер()
    try:
        with sync_playwright() as pw:
            бр = pw.chromium.launch(executable_path=м.хром(), args=["--no-sandbox"])
            прогон(бр, порт)
            бр.close()
    finally:
        с.shutdown()
    if НАХОДКИ:
        print("НАХОДКИ:")
        for н in НАХОДКИ:
            print("  ✗", н)
        raise SystemExit(1)
    print("Чисто: журнал действий помнит последний период в аккаунте — и кнопкой, и своим диапазоном с датами, "
          "период из профиля приходит на новое устройство, а переход из мини-окна «за всё время» разовый.")


if __name__ == "__main__":
    главная()
