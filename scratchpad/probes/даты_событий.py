"""Даты событий в заглушке журнала — относительно сегодняшнего дня.

Журнал по умолчанию показывает последние 7 дней. Пробы, где у событий стояли
даты дня их написания (23.09.2026), через неделю стали видеть пустую ленту и
падать с «проба идёт вхолостую»: проверка жива, а смотреть ей не на что.
Найдено 09.10.2026. Сдвиг сохраняет промежутки между событиями — новейшее
встаёт на «сейчас», остальные — на столько же раньше, как в исходной заглушке.
"""
from datetime import datetime, timezone


def освежить(события):
    def дата(с):
        return datetime.fromisoformat(str(с["created_at"]).replace("Z", "+00:00"))
    с_датой = [с for с in события if с.get("created_at")]
    if not с_датой:
        return события
    сдвиг = datetime.now(timezone.utc) - max(дата(с) for с in с_датой)
    for с in с_датой:
        с["created_at"] = (дата(с) + сдвиг).isoformat().replace("+00:00", "Z")
    return события
