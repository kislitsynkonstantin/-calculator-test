#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Проба главного поля скидки: нажатие на подпись решает, что задано рукой.

Скидку дают то процентом, то суммой. До 17.09.2026 в расчёте всегда побеждал
процент: набранные 250 000 ₽ пересчитывались в 4.4 %, и при первой же новой
опции сумма уезжала следом за процентом — держался процент, а не уговор
с клиентом. Теперь главное поле выбирается нажатием на подпись, и жирная
подпись — единственный указатель.

Проба держит:
  • нажатие на «Спец. цена» делает главным процент, на «Скидка» — сумму;
    жирная всегда ровно одна подпись;
  • в режиме суммы поле процента не принимает ввод: считается — значит не
    печатается;
  • главное переживает пересчёт. Добавили опций — в режиме суммы сумма та же
    до рубля, процент пересчитался; в режиме процента наоборот. Это и есть
    смысл всей затеи, и меряется он двумя итогами, а не одним;
  • деньги в режиме суммы считаются от суммы, а не от округлённого процента:
    250 000 ₽ при округлении до 4.4 % превратились бы в 247 807 ₽;
  • подписи нажимаются пальцем — поле нажатия 44 px при неизменной коробке;
  • денежные места (экран, документ печати, платёжный план) ходят через
    общий помощник, а не читают поле процента напрямую.
"""
import os
import pathlib
import re
import sys
import threading
import http.server
import socketserver
import functools

from playwright.sync_api import sync_playwright

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent.parent
ЗАГЛУШКА = (pathlib.Path(__file__).parent / "stub_sb.js").read_text(encoding="utf-8")
НАХОДКИ = []


def хром():
    из_среды = os.environ.get("BM_CHROMIUM")
    if из_среды and pathlib.Path(из_среды).exists():
        return из_среды
    найденные = sorted(pathlib.Path("/opt/pw-browsers").glob("chromium-*/chrome-linux/chrome"))
    if not найденные:
        raise SystemExit("Chromium не найден — запусти .claude/hooks/session-start.sh")
    return str(найденные[-1])


ХРОМ = хром()


def сервер():
    класс = functools.partial(http.server.SimpleHTTPRequestHandler, directory=str(КОРЕНЬ))
    socketserver.TCPServer.allow_reuse_address = True
    с = socketserver.TCPServer(("127.0.0.1", 0), класс)
    threading.Thread(target=с.serve_forever, daemon=True).start()
    return с, с.server_address[1]


def плохо(что):
    НАХОДКИ.append(что)


ИТОГ = 5631974          # столько было на снимке у Константина
ИТОГ2 = 5931974         # тот же расчёт после добавленных опций
СУММА = 250000


def исходное(страница):
    return страница.evaluate("""() => {
      const беда = document.getElementById('pricingErrorScreen');
      if (беда) беда.style.display = 'none';
      // Без входа поверх страницы стоит экран входа и перехватывает нажатия.
      const вход = document.getElementById('loginScreen');
      if (вход) вход.style.display = 'none';
      document.getElementById('resultCard').style.display = 'block';
      document.getElementById('resultCard').scrollIntoView({ block: 'center' });
      window._итогДоСкидки = 5631974;
      _режимСкидки = 'процент';
      _скидкаСуммой = 0;
      document.getElementById('discountPctInput').value = '4.4';
      отметитьГлавноеПолеСкидки();
      return true;
    }""")


def показать(страница):
    """Карточка итога прячется, пока проект не выбран, — а каталог цен живёт
    в базе, до которой из контейнера не дойти. Показываем её руками перед
    каждым нажатием: проверяем переключатель, а не загрузку каталога."""
    страница.evaluate("""() => {
      const к = document.getElementById('resultCard');
      к.style.display = 'block';
      к.scrollIntoView({ block: 'center' });
    }""")


def состояние(страница):
    return страница.evaluate("""() => {
      const проц = document.getElementById('discPctLab');
      const сум = document.getElementById('discSumLab');
      const поле = document.getElementById('discountPctInput');
      const вес = э => getComputedStyle(э).fontWeight;
      return {
        режим: _режимСкидки,
        жирныйПроцент: проц.classList.contains('гл'),
        жирнаяСумма: сум.classList.contains('гл'),
        весПроцента: вес(проц), весСуммы: вес(сум),
        полеТолькоЧтение: !!поле.readOnly,
        вПоле: поле.value,
      };
    }""")


def проверить(страница, окно, ш, в):
    страница.set_viewport_size({"width": ш, "height": в})
    исходное(страница)

    н = состояние(страница)
    if not н["жирныйПроцент"] or н["жирнаяСумма"]:
        плохо(f"[{окно}] по умолчанию главный — процент, а жирная подпись другая: "
              f"процент={н['жирныйПроцент']}, сумма={н['жирнаяСумма']}")
    if н["полеТолькоЧтение"]:
        плохо(f"[{окно}] процент главный, а поле процента не принимает ввод")

    # ── нажатие на «Скидка» ─────────────────────────────────────────────
    показать(страница)
    страница.click("#discSumLab")
    страница.wait_for_timeout(120)
    с = состояние(страница)
    if с["режим"] != "сумма":
        плохо(f"[{окно}] нажатие на «Скидка» не сделало сумму главной: {с['режим']!r}")
    if not с["жирнаяСумма"] or с["жирныйПроцент"]:
        плохо(f"[{окно}] жирной обязана быть ровно одна подпись — главная: "
              f"процент={с['жирныйПроцент']}, сумма={с['жирнаяСумма']}")
    if int(с["весСуммы"]) <= int(н["весСуммы"]):
        плохо(f"[{окно}] «Скидка» стала главной, но вес подписи не изменился "
              f"({н['весСуммы']} → {с['весСуммы']}) — указателя не видно")
    if not с["полеТолькоЧтение"]:
        плохо(f"[{окно}] сумма главная, а в поле процента всё ещё можно печатать — "
              "два числа спорят друг с другом")

    # ── что переживает пересчёт ─────────────────────────────────────────
    было = страница.evaluate("""([сумма, итог2]) => {
      _скидкаСуммой = сумма;
      const до = текущаяСкидка(window._итогДоСкидки);
      // Добавленные опции — это новый целый итог, и calc() кладёт его в
      // _итогДоСкидки до того, как считает скидку. Проба делает так же:
      // иначе она мерила бы часть, а не пересчёт.
      window._итогДоСкидки = итог2;
      const после = текущаяСкидка(итог2);
      return { доСумма: до.сумма, доПроцент: до.процент,
               послеСумма: после.сумма, послеПроцент: после.процент };
    }""", [СУММА, ИТОГ2])
    if round(было["доСумма"]) != СУММА or round(было["послеСумма"]) != СУММА:
        плохо(f"[{окно}] сумма главная, а пересчёт её сдвинул: "
              f"{было['доСумма']:.0f} → {было['послеСумма']:.0f} ₽")
    if abs(было["доПроцент"] - было["послеПроцент"]) < 0.05:
        плохо(f"[{окно}] итог вырос, а процент не пересчитался: "
              f"{было['доПроцент']:.3f} % → {было['послеПроцент']:.3f} %")
    # Деньги идут от суммы, а не от округлённого процента: 4.4 % от 5 631 974 —
    # это 247 807 ₽, и подмена была бы ровно такой.
    округлённо = ИТОГ * (round(было["доПроцент"], 1) / 100)
    if abs(было["доСумма"] - округлённо) < 100:
        плохо(f"[{окно}] сумма считается от округлённого процента: "
              f"{было['доСумма']:.0f} ₽ вместо заданных {СУММА} ₽")

    # ── скидка суммой делится по частям процентом ───────────────────────
    # Печать делят на составы (основной и отделка), платёжный план считает
    # каждый договор отдельно. Вычитать 250 000 ₽ из каждой части нельзя:
    # скидка удвоилась бы. Части получают свою долю по проценту
    # (Константин, 17.09.2026).
    доли = страница.evaluate("""([сумма, итог, основной, отделка]) => {
      _режимСкидки = 'сумма';
      _скидкаСуммой = сумма;
      window._итогДоСкидки = итог;
      const всё = текущаяСкидка(итог);
      const о = текущаяСкидка(основной);
      const т = текущаяСкидка(отделка);
      return { всё: всё.сумма, основной: о.сумма, отделка: т.сумма,
               процентЦелого: всё.процент, процентЧасти: о.процент };
    }""", [СУММА, ИТОГ, int(ИТОГ * 0.7), ИТОГ - int(ИТОГ * 0.7)])
    if round(доли["всё"]) != СУММА:
        плохо(f"[{окно}] на целом расчёте скидка суммой сдвинулась: {доли['всё']:.0f} ₽")
    if abs(доли["основной"] - СУММА * 0.7) > СУММА * 0.01:
        плохо(f"[{окно}] основной состав получил {доли['основной']:.0f} ₽ вместо "
              f"{СУММА * 0.7:.0f} — доля считается не по проценту")
    if abs((доли["основной"] + доли["отделка"]) - СУММА) > 2:
        плохо(f"[{окно}] две части дают {доли['основной'] + доли['отделка']:.0f} ₽ "
              f"вместо {СУММА} — скидка при делении {'удвоилась' if доли['основной'] + доли['отделка'] > СУММА else 'потерялась'}")
    if abs(доли["процентЧасти"] - доли["процентЦелого"]) > 0.001:
        плохо(f"[{окно}] процент у части и у целого разный: "
              f"{доли['процентЧасти']:.3f} против {доли['процентЦелого']:.3f}")

    # ── процент везде виден до десятых ──────────────────────────────────
    # Скидка суммой даёт длинную дробь: 200 000 ₽ от 4 532 171 ₽ — это
    # 4.412896159478537 %, и именно так оно встало в документ клиенту
    # (Константин, 17.09.2026, со снимком).
    подпись = страница.evaluate("""([сумма, итог]) => {
      _режимСкидки = 'сумма';
      window._итогДоСкидки = итог;
      _скидкаСуммой = сумма;
      const точный = текущаяСкидка(итог).процент;
      const вПоле = _процентВПоле(точный);
      return { точный, вПоле, подпись: процентСкидкиДляПодписи(точный) };
    }""", [200000, 4532171])
    if len(подпись["вПоле"].split(".")[-1]) > 1 and "." in подпись["вПоле"]:
        плохо(f"[{окно}] в поле процента {подпись['вПоле']} — больше одного знака после точки")
    знаков = len(str(подпись["подпись"]).split(".")[-1]) if "." in str(подпись["подпись"]) else 0
    if знаков > 1:
        плохо(f"[{окно}] в подпись идёт {подпись['подпись']} — округление не до десятых")
    if abs(подпись["подпись"] - 4.4) > 0.001:
        плохо(f"[{окно}] 200 000 ₽ от 4 532 171 ₽ подписаны как {подпись['подпись']} %, "
              "а это 4.4 %")

    # ── обратно на процент ──────────────────────────────────────────────
    показать(страница)
    страница.click("#discPctLab")
    страница.wait_for_timeout(120)
    п = состояние(страница)
    if п["режим"] != "процент" or not п["жирныйПроцент"] or п["жирнаяСумма"]:
        плохо(f"[{окно}] нажатие на «Спец. цена» не вернуло процент: {п}")
    if п["полеТолькоЧтение"]:
        плохо(f"[{окно}] процент снова главный, а поле не принимает ввод")
    держит = страница.evaluate("""(итог2) => {
      document.getElementById('discountPctInput').value = '4.4';
      window._итогДоСкидки = 5631974;
      const до = текущаяСкидка(5631974);
      window._итогДоСкидки = итог2;
      const после = текущаяСкидка(итог2);
      return { доПроцент: до.процент, послеПроцент: после.процент,
               доСумма: до.сумма, послеСумма: после.сумма };
    }""", ИТОГ2)
    if abs(держит["доПроцент"] - держит["послеПроцент"]) > 0.001:
        плохо(f"[{окно}] процент главный, а пересчёт его сдвинул: "
              f"{держит['доПроцент']} → {держит['послеПроцент']}")
    if abs(держит["послеСумма"] - держит["доСумма"]) < 100:
        плохо(f"[{окно}] итог вырос, а сумма скидки не пересчиталась: "
              f"{держит['доСумма']:.0f} → {держит['послеСумма']:.0f} ₽")

    # ── поле нажатия ────────────────────────────────────────────────────
    # Меряется на видимой карточке: у спрятанной прямоугольник нулевой, и
    # проба намерила бы 32 px вместо 44 — цифра неверная, а вид у неё
    # такой же деловой, как у верной.
    показать(страница)
    поля = страница.evaluate("""() => {
      const мера = ид => {
        const э = document.getElementById(ид);
        const r = э.getBoundingClientRect();
        const с = getComputedStyle(э, '::before');
        const ч = з => parseFloat(з) || 0;
        const поле = с.content === 'none'
          ? { ш: r.width, вы: r.height }
          : { ш: r.width - ч(с.left) - ч(с.right), вы: r.height - ч(с.top) - ч(с.bottom) };
        return { коробка: { ш: r.width, вы: r.height }, поле: поле,
                 палец: getComputedStyle(э).cursor };
      };
      return { процент: мера('discPctLab'), сумма: мера('discSumLab') };
    }""")
    for имя, м in поля.items():
        if м["поле"]["вы"] < 43.5:
            плохо(f"[{окно}] поле нажатия подписи «{имя}» {м['поле']['вы']:.0f} px "
                  "по высоте, нужно 44")
        if м["коробка"]["вы"] > 34:
            плохо(f"[{окно}] подпись «{имя}» нарисована {м['коробка']['вы']:.0f} px — "
                  "поле нажатия оплачено размером")
        if м["палец"] != "pointer":
            плохо(f"[{окно}] подпись «{имя}» не показывает, что её нажимают "
                  f"(курсор {м['палец']!r})")


def исходники():
    """Денежные места обязаны ходить через общий помощник. Проверяется текстом:
    поведение печати и платёжного плана пробе не собрать — каталог цен живёт
    в базе, а до неё из контейнера не дойти."""
    текст = (КОРЕНЬ / "index.html").read_text(encoding="utf-8")
    for имя in ("function calc()", "function buildPrintDoc()"):
        нач = текст.find(имя)
        if нач < 0:
            плохо(f"в исходнике нет {имя}")
            continue
        кусок = текст[нач:нач + 12000]
        if "текущаяСкидка(" not in кусок:
            плохо(f"{имя} считает скидку сам, мимо помощника — режим суммы там не действует")
    for имя in ("function calc()", "function buildPrintDoc()"):
        нач = текст.find(имя)
        if нач < 0:
            continue
        кусок = текст[нач:нач + 12000]
        м = re.search(r"const discountPct = ([^;]+);", кусок, re.S)
        if not м:
            плохо(f"{имя}: не найдено, откуда берётся процент для подписи")
        elif "процентСкидкиДляПодписи" not in м.group(1):
            плохо(f"{имя}: процент в подписи не округляется — в документ уйдёт "
                  "длинная дробь вида «−4.412896159478537 %»")
    if re.search(r"totalAfterKit \* \(1 - discountPct", текст):
        плохо("в расчёте осталось прямое умножение на процент — сумма в режиме "
              "суммы будет округляться до десятых процента")


def главная():
    исходники()
    с, порт = сервер()
    ошибки = []
    with sync_playwright() as pw:
        бр = pw.chromium.launch(executable_path=ХРОМ, args=["--no-sandbox"])
        стр = бр.new_page()
        стр.add_init_script(ЗАГЛУШКА)
        стр.on("pageerror", lambda e: ошибки.append(str(e)))
        стр.goto(f"http://127.0.0.1:{порт}/index.html", wait_until="load")
        стр.wait_for_timeout(1500)
        for окно, ш, в in (("телефон", 390, 844), ("стол", 1440, 900)):
            проверить(стр, окно, ш, в)
        бр.close()
    с.shutdown()

    if ошибки:
        плохо("ошибки страницы: " + "; ".join(о[:120] for о in ошибки[:3]))
    if НАХОДКИ:
        print("НАХОДКИ:")
        for н in НАХОДКИ:
            print("  ✗", н)
        sys.exit(1)
    print("Чисто: главное поле скидки переключается подписью, переживает пересчёт "
          "и считается от заданного числа.")


if __name__ == "__main__":
    главная()
