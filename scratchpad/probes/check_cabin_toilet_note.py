#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Бытовка и биотуалет: примечание подстраивается, формулировки «не входят в расчёт».

Константин 30.09.2026, снимком примечаний раздела «Доп. опции и логистика»:
  1. примечание «Бытовка и биотуалет не входят в расчёт»; выбрана бытовка —
     остаётся про биотуалет, выбраны оба — гаснет глазом;
  2. «в базовую комплектацию не входят» — везде «не входят в расчёт»;
  3. «Аренда биотуалета с обслуживанием на время строительства».

Проба нажимает на строки, как менеджер, на 1440 и 390, и держит:
  • ни в одном примечании каркаса и бруса нет «в базовую комплектацию»;
  • по умолчанию примечание про оба и видно;
  • бытовка — «Биотуалет не входит в расчёт»; бытовка и биотуалет — примечание
    скрыто глазом; только биотуалет — «Бытовка не входит в расчёт»; ничего —
    снова про оба;
  • у биотуалета новое название.

    python3 check_cabin_toilet_note.py
"""
import pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).parent))
import check_preset_chip as м
from playwright.sync_api import sync_playwright

НАХОДКИ = []
СОСТ = """() => { const с = SECTION_NOTES.extra, виды = ['Бытовка и биотуалет не входят в расчёт', 'Биотуалет не входит в расчёт', 'Бытовка не входит в расчёт'];
  const место = с.findIndex(т => виды.indexOf(т) !== -1), ключ = ключПримечания('extra', место);
  const узел = document.getElementById('fixedNote_' + ключ);
  return { место, текст: с[место], скрыто: hiddenNotes.has(ключ), наЭкране: узел ? узел.textContent.trim() : null }; }"""


def нажать(стр, ид):
    стр.evaluate(f"() => document.getElementById('lbl_{ид}').scrollIntoView({{ block: 'center' }})"); стр.wait_for_timeout(150)
    стр.locator(f"#lbl_{ид} .opt-check").click(); стр.wait_for_timeout(500)


def прогон(бр, порт, шир, выс):
    н = f"[{шир}]"
    стр = бр.new_page(viewport={"width": шир, "height": выс})
    ошибки = []
    стр.on("pageerror", lambda e: ошибки.append(str(e)))
    стр.add_init_script(м.ЗАГЛУШКА); стр.add_init_script(м.ТАБЛИЦЫ_JS)
    стр.goto(f"http://127.0.0.1:{порт}/index.html", wait_until="load"); стр.wait_for_timeout(2500)
    стр.evaluate("""async () => { const б = document.getElementById('pricingErrorScreen'); if (б) б.style.display = 'none';
      applyUiStyle('blank', false);
      // В учебном каталоге у бытовки и биотуалета нет цен, а без цены строка не отмечается.
      ['e5', 'e6', 'e7'].forEach((ид, i) => { const о = getOpt(ид); if (о && !о.price) о.price = [72000, 91000, 34000][i]; });
      selectProjectOption(0); await new Promise(r => setTimeout(r, 900)); }""")
    старые = стр.evaluate("""() => { const все = [].concat(...Object.values(FRAME_NOTES), ...Object.values(KB_SECTION_NOTES), ...Object.values(SECTION_NOTES));
      return все.filter(т => /базовую комплектацию/.test(т)); }""")
    if старые:
        НАХОДКИ.append(f"{н} в примечаниях осталось «в базовую комплектацию»: {старые[:4]}")
    имя = стр.evaluate("() => (getOpt('e7') || {}).name")
    if имя != "Аренда биотуалета с обслуживанием на время строительства":
        НАХОДКИ.append(f"{н} биотуалет называется «{имя}»")

    def ждать(что, текст, скрыто):
        с = стр.evaluate(СОСТ)
        if с["место"] == -1 or с["текст"] != текст or с["скрыто"] != скрыто or (с["наЭкране"] or "").find(текст) == -1:
            НАХОДКИ.append(f"{н} {что}: ждали «{текст}», скрыто={скрыто}; есть {с}")

    ждать("по умолчанию", "Бытовка и биотуалет не входят в расчёт", False)
    нажать(стр, "e6"); ждать("выбрана бытовка", "Биотуалет не входит в расчёт", False)
    нажать(стр, "e7"); ждать("выбраны бытовка и биотуалет", "Бытовка и биотуалет не входят в расчёт", True)
    нажать(стр, "e6"); ждать("остался биотуалет", "Бытовка не входит в расчёт", False)
    нажать(стр, "e7"); ждать("ничего не выбрано", "Бытовка и биотуалет не входят в расчёт", False)
    for о in [о for о in ошибки if "supabase.co" not in о][:3]:
        НАХОДКИ.append(f"{н} ошибка страницы: {о[:160]}")
    стр.close()


def главная():
    с, порт = м.сервер()
    try:
        with sync_playwright() as pw:
            бр = pw.chromium.launch(executable_path=м.хром(), args=["--no-sandbox"])
            прогон(бр, порт, 1440, 900)
            прогон(бр, порт, 390, 844)
            бр.close()
    finally:
        с.shutdown()
    if НАХОДКИ:
        print("НАХОДКИ:")
        for н in НАХОДКИ:
            print("  ✗", н)
        raise SystemExit(1)
    print("Чисто: примечания — «не входят в расчёт»; «Бытовка и биотуалет не входят в расчёт» подстраивается: бытовка — "
          "про биотуалет, биотуалет — про бытовку, оба — гаснет глазом, ничего — про оба; биотуалет с новым названием — "
          "на 1440 и 390.")


if __name__ == "__main__":
    главная()
