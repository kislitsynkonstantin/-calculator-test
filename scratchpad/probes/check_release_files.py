#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Проба выкладки: всё, на что страницы ссылаются файлами, лежит рядом с ними.

Выпуск v2.5.7 перенёс в боевой репозиторий `index.html` и `404.html` — и только
их. Логотип клиентская страница берёт файлом `/assets/logo-bmsk-*.png`, а не
встроенной строкой, как калькулятор, и в бою на его месте встал битый значок
(Константин, 18.09.2026). Ошибка не в коде, а в переносе: глазами её видно
только на живом домене, а это уже клиент.

Проба сверяет обещание с наличием: собирает из страниц все ссылки на местные
файлы и проверяет, что каждый файл есть в той папке, куда выложено.

Запуск: python3 check_release_files.py [путь к папке]
Без пути проверяется тестовый репозиторий.
"""
import pathlib
import re
import sys

СТРАНИЦЫ = ("index.html", "404.html")


def местные_ссылки(текст):
    """Ссылки на файлы рядом: не http, не data:, не подстановка ${…}."""
    итог = set()
    for м in re.finditer(r'''(?:src|href)=["']([^"'#]+)["']''', текст):
        а = м.group(1).strip()
        if not а or а.startswith(("http", "//", "data:", "mailto:", "javascript:", "?", "${")):
            continue
        if "${" in а:          # адрес собирается в коде — файла может и не быть
            continue
        итог.add(а.lstrip("/"))
    # Лист клиента собирает адрес логотипа в коде — логотип(вид, тон): под
    # правило «${…} не проверяем» он не попадает, и без этого проба перестала
    # бы видеть и основной логотип, и логотипы тонов (24.09.2026, выбор цвета).
    if "function логотип(" in текст:
        тоны = [""] + ["-" + т for т in re.findall(r"с\.тон === '(\w+)'", текст)]
        for вид in ("dark", "light"):
            for т in тоны:
                итог.add(f"assets/logo-bmsk-{вид}{т}.png")
    return итог


def главная():
    корень = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else
                          pathlib.Path(__file__).resolve().parent.parent.parent)
    находки = []
    проверено = 0
    for имя in СТРАНИЦЫ:
        файл = корень / имя
        if not файл.exists():
            находки.append(f"в {корень} нет {имя}")
            continue
        for ссылка in sorted(местные_ссылки(файл.read_text(encoding="utf-8"))):
            проверено += 1
            if not (корень / ссылка).exists():
                находки.append(f"{имя} ссылается на «{ссылка}», а файла в {корень} нет")

    if находки:
        print("НАХОДКИ:")
        for н in находки:
            print("  ✗", н)
        sys.exit(1)
    print(f"Чисто: {проверено} ссылок на местные файлы, все файлы на месте ({корень}).")


if __name__ == "__main__":
    главная()
