"""Журнал и сводка чужого пресета: следы открытия до исправления не видны.

Константин 30.09.2026, снимком журнала мини-окна у пресета Максима: «открываю
пресет менеджера, пишет „Вы“. Должен писать „Максим Г.“… „Вы“ — только на мои
действия». Подпись была верной: все строки там записаны его аккаунтом. Это
следы открытия до 29.09 (a74ec4b) — раскладка чужого пресета писала толщину,
«Реквизиты заполнены» и смену технологии правками открывшего, а записи
«Открыт» тогда не было. Плюс публикация другого пресета, ушедшая с кодом
открытого.

Проба на 390 и 1440 держит, у чужого общего пресета:
  • толщина, реквизиты и технология от не-автора до исправления — не в
    журнале и не в счёте правок сводки;
  • печать того же человека до исправления — в журнале, с «Вы»;
  • правка автора — «Максим Г.»;
  • правка коллеги-не-автора после исправления — видна, с его именем;
  • публикация другого пресета с кодом этого — не видна;
и у своего пресета: своя толщина до исправления видна.

    python3 check_preset_journal_traces.py
"""
import pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).parent))
import check_preset_chip as м
import check_preset_card as к
from playwright.sync_api import sync_playwright

НАХОДКИ = []

ПОСЕВ = """([код, автор]) => {
  const т = window.__ТАБЛИЦЫ, я = _sbUser.id;
  const с = (ид, кто, вид, когда, строки, сумма) => т.events.push({ id: ид, user_id: кто, event_type: вид, created_at: когда,
    total_price: сумма || 3000000, details: { presetCode: код, preset: 'Проба', obj: 'Проба', rows: строки || [] } });
  т.events = [];
  с('ев-сохр', автор, 'preset_saved', '2026-09-02T10:05:00Z', []);
  с('ев-автор', автор, 'options_batch', '2026-09-20T09:00:00Z', [{ k: 'Добавлены', a: '', b: 'Метка-автор' }], 3100000);
  с('ев-толщ', я, 'thickness_changed', '2026-09-28T16:20:07Z', [{ k: 'Толщина', a: '150 мм', b: 'Метка-след-толщина' }], 3200000);
  с('ев-рекв', я, 'requisites_filled', '2026-09-28T14:52:50Z', [{ k: 'Заполнены', a: '', b: 'Метка-след-реквизиты' }]);
  с('ев-тех', я, 'tech_changed', '2026-09-28T14:52:50Z', [{ k: 'Технология', a: 'Клеёный брус', b: 'Метка-след-технология' }], 0);
  с('ев-печать', я, 'print', '2026-09-27T16:25:20Z', [{ k: 'Шаблон', a: '', b: 'blank' }]);
  с('ев-чужая-публ', я, 'share_created', '2026-09-27T07:44:24Z', [{ k: 'Код', a: '', b: '321910' }]);
  с('ев-коллега', 'u-коллега', 'thickness_changed', '2026-09-30T08:00:00Z', [{ k: 'Стены, пол и потолок', a: '150 мм', b: 'Метка-коллега' }], 3300000);
  т.profiles = (т.profiles || []).concat([{ id: автор, first_name: 'Максим', last_name: 'Григорьев', email: 'm@x' },
    { id: 'u-коллега', first_name: 'Ирина', last_name: 'Васильева', email: 'i@x' }]);
  _сводкаПресета = { код: '', данные: null, ошибка: '', грузится: false, когда: 0 };
  _журналПресета = { код: '', события: null, ошибка: '', грузится: false, когда: 0 };
}"""

ЖУРНАЛ = """() => [...document.querySelectorAll('#pcPane-l li')].map(л => л.innerText.replace(/\\s+/g, ' ').trim()).filter(Boolean)"""


def вкладка(стр, в):
    if not стр.evaluate("() => document.getElementById('presetChipCard').classList.contains('show')"):
        стр.locator("#presetChip .pc-body").click(); стр.wait_for_timeout(350)
    стр.locator(f"#pcTab-{в}").click(); стр.wait_for_timeout(1500)


def прогон(бр, порт, ш, в):
    н = f"[{ш}]"
    стр, ошибки = к.начать(бр, порт, ш, в, False)
    # ── чужой общий пресет ──
    стр.evaluate("""() => { закрытьКарточкуЗначка(); _sharedPresets.push({ short_code: '775165', id: '775165', name: 'Баня 9×5 · 01.09.26', author_name: 'Максим Григорьев',
      author_id: 'u-максим', is_public: true, visibility: 'public', locked: true, created_at: '2026-09-01T16:58:00Z', updated_at: '2026-09-02T10:05:00Z', state: {} });
      openSharedPreset('775165'); }""")
    стр.wait_for_timeout(1500)
    стр.evaluate(ПОСЕВ, ["775165", "u-максим"])
    вкладка(стр, "l")
    строки = стр.evaluate(ЖУРНАЛ)
    текст = " | ".join(строки)
    for метка in ("Метка-след-толщина", "Метка-след-реквизиты", "Метка-след-технология", "Код: 321910", "321910"):
        if метка in текст:
            НАХОДКИ.append(f"{н} чужой пресет: в журнале след открытия или чужая публикация «{метка}»: {текст[:300]}")
    if not any("Вы" in с and "печать" in с for с in строки):
        НАХОДКИ.append(f"{н} чужой пресет: своей печати с «Вы» нет: {текст[:300]}")
    if not any("Максим Г." in с and "Метка-автор" in с for с in строки):
        НАХОДКИ.append(f"{н} чужой пресет: правка автора не подписана «Максим Г.»: {текст[:300]}")
    if not any("Ирина В." in с and "Метка-коллега" in с for с in строки):
        НАХОДКИ.append(f"{н} чужой пресет: правка коллеги после исправления не видна или без имени: {текст[:300]}")
    вкладка(стр, "s")
    правок = стр.evaluate("() => { const р = [...document.querySelectorAll('#pcPane-s *')].find(э => э.children.length === 0 && /^Правок$/.test(э.textContent.trim())); if (!р) return null; const ряд = р.parentElement; return ряд.innerText.replace(/\\s+/g, ' '); }")
    # правки: автор и коллега; следы и печать — нет
    if not правок or not правок.strip().endswith("2"):
        НАХОДКИ.append(f"{н} чужой пресет: «Правок» в сводке не 2 (автор и коллега): {правок}")
    стр.screenshot(path=str(м.СНИМКИ / f"journal-traces-{ш}.png"))
    стр.close()
    # ── свой пресет: своя толщина до исправления — правка, видна ──
    стр, _ = к.начать(бр, порт, ш, в, False)
    код = стр.evaluate("() => { const p = loadAllPresets()[activePresetId]; return p && (p.shortCode || p.sharedId); }")
    стр.evaluate("""(код) => { const т = window.__ТАБЛИЦЫ, я = _sbUser.id; т.events = [
      { id: 'ев-с', user_id: я, event_type: 'preset_saved', created_at: '2026-09-20T09:00:00Z', total_price: 3000000, details: { presetCode: код, rows: [] } },
      { id: 'ев-т', user_id: я, event_type: 'thickness_changed', created_at: '2026-09-28T16:20:07Z', total_price: 3200000, details: { presetCode: код, rows: [{ k: 'Толщина', a: '150 мм', b: 'Метка-своя-толщина' }] } } ];
      _журналПресета = { код: '', события: null, ошибка: '', грузится: false, когда: 0 }; }""", код)
    вкладка(стр, "l")
    if "Метка-своя-толщина" not in " | ".join(стр.evaluate(ЖУРНАЛ)):
        НАХОДКИ.append(f"{н} свой пресет: своя смена толщины до исправления скрыта, а это правка")
    # ── правки коллеги видны через функцию базы, а не через таблицу ──
    # Таблица отдаёт менеджеру только свои строки; функция preset_events — все
    # строки пресета с именем автора (30.09.2026). Здесь строка коллеги есть
    # только в ответе функции, а его профиля в таблице профилей нет вовсе.
    стр.evaluate("""(код) => { const я = _sbUser.id;
      window.__RPC.preset_events = (а) => String(а.p_code) !== String(код) ? [] : [
        { id: 'ф1', user_id: 'u-олег', user_name: 'Олег Смирнов', event_type: 'options_batch', created_at: '2026-09-30T09:00:00Z', total_price: 3100000,
          details: { presetCode: код, rows: [{ k: 'Добавлены', a: '', b: 'Метка-коллега-функция' }] } },
        { id: 'ф2', user_id: я, event_type: 'print', created_at: '2026-09-30T08:00:00Z', total_price: 3100000, details: { presetCode: код, rows: [] } } ];
      _журналПресета = { код: '', события: null, ошибка: '', грузится: false, когда: 0 };
      _сводкаПресета = { код: '', данные: null, ошибка: '', грузится: false, когда: 0 }; }""", код)
    вкладка(стр, "l")
    т = " | ".join(стр.evaluate(ЖУРНАЛ))
    if "Олег С." not in т or "Метка-коллега-функция" not in т:
        НАХОДКИ.append(f"{н} правка коллеги из функции базы не видна или без имени: {т[:300]}")
    for о in [о for о in ошибки if "supabase.co" not in о][:3]:
        НАХОДКИ.append(f"{н} ошибка страницы: {о[:160]}")
    стр.close()


def главная():
    с, порт = м.сервер()
    try:
        with sync_playwright() as pw:
            бр = pw.chromium.launch(executable_path=м.хром(), args=["--no-sandbox"])
            прогон(бр, порт, 390, 900)
            прогон(бр, порт, 1440, 900)
            бр.close()
    finally:
        с.shutdown()
    if НАХОДКИ:
        print("НАХОДКИ:")
        for н in НАХОДКИ:
            print("  ✗", н)
        raise SystemExit(1)
    print("Чисто: у чужого пресета следы открытия до исправления и публикация другого пресета не видны ни в "
          "журнале, ни в счёте правок; своя печать — «Вы», правка автора — «Максим Г.», правка коллеги после "
          "исправления — с его именем; у своего пресета своя толщина до исправления видна; правка коллеги приходит функцией базы с его именем — на 390 и 1440.")


if __name__ == "__main__":
    главная()
