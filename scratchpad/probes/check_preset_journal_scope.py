#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Журнал пресета — только события этого пресета.

Константин 29.09.2026, двумя снимками: в журнал мини-окна «залетает от
других» — «Ручной проект сохранён» чужого сотрудника и «Изображения
изменены» от того, кто пресет только открыл; а «Открыть в журнале действий»
сначала показывает другие пресеты и лишь потом нужный, и в полном журнале у
пресета осталось одно событие вместо трёх.

Проба держит:
  • правки справочника — ручные проекты, цены проекта и опций — пишутся без
    пресета (проверяется по коду: `безРасчёта` у всех четырёх вызовов);
  • старые такие записи с кодом пресета в журнал мини-окна не попадают, в
    полный журнал с отбором по пресету — тоже;
  • полный журнал с отбором по пресету отдаёт все его события, даже когда
    поверх них 600 чужих — отбор идёт в базе, а не по последним 500;
  • «Открыть в журнале действий» не показывает прежнюю ленту: пока идёт
    запрос — полоска загрузки, потом только этот пресет;
  • раскладка снимков при открытии пресета не пишет «Изображения изменены»,
    а настоящее добавление снимка — пишет.

    python3 check_preset_journal_scope.py
"""
import os, pathlib, re, sys
sys.path.insert(0, str(pathlib.Path(__file__).parent))
import check_preset_chip as м
import check_preset_card as к
from playwright.sync_api import sync_playwright

НАХОДКИ = []


def плохо(т):
    НАХОДКИ.append(т)


def по_коду():
    исх = (м.КОРЕНЬ / "index.html").read_text(encoding="utf-8")
    for вид in ("custom_project_saved", "custom_project_deleted", "base_price_changed", "option_price_changed"):
        i = исх.find("logEvent('" + вид + "'")
        if i < 0:
            плохо(f"[код] нет записи «{вид}»"); continue
        # вызов — до закрывающей скобки с точкой с запятой
        хвост = исх[i:i + 900]
        конец = хвост.find(");\n")
        if "безРасчёта" not in хвост[:конец if конец > 0 else 900]:
            плохо(f"[код] «{вид}» пишется с кодом открытого пресета — правка справочника попадёт в журнал пресета")


СЕВ = """(код) => { const т = window.__ТАБЛИЦЫ; т.events = []; const д = Date.now(), ч = 3600 * 1000;
  const e = (ид, тип, часов, код_, кто, rows) => т.events.push({ id: ид, user_id: кто || 'u-проба', event_type: тип,
    created_at: new Date(д - часов * ч).toISOString(), project_name: 'Проба дом 8×8', details: { presetCode: код_, rows: rows || [] } });
  e('p1', 'discount_changed', 30, код, 'u-проба', [{ k: 'Скидка', a: '0 %', b: '3 %' }]);
  e('p2', 'options_batch', 31, код, 'u-проба', [{ k: 'Добавлены', b: 'Метка-пресета' }]);
  e('p3', 'print', 32, код, 'u-проба', [{ k: 'Шаблон', b: 'blank' }]);
  // старые правки справочника с кодом пресета
  e('c1', 'custom_project_saved', 29, код, 'u-другой', [{ k: 'Цена 100 мм', b: 'Метка-справочника' }]);
  e('c2', 'base_price_changed', 29.5, код, 'u-другой', [{ k: 'Цена 150 мм', a: '1', b: '2' }]);
  e('c3', 'option_price_changed', 29.7, код, 'u-другой', [{ k: 'Цена опции', a: '1', b: '2' }]);
  // 600 чужих событий новее — поверх потолка выборки
  for (let i = 0; i < 600; i++) e('x' + i, 'options_batch', i / 100, '999999', 'u-проба', [{ k: 'Добавлены', b: 'Чужая-метка' }]);
  _журналПресета = { код: '', события: null, ошибка: '', грузится: false, когда: 0 }; }"""


def прогон(бр, порт, ш, в):
    н = f"[{ш}]"
    стр, ошибки = к.начать(бр, порт, ш, в, False)
    код = стр.evaluate("() => { const p = loadAllPresets()[activePresetId]; return p && (p.shortCode || p.sharedId); }")
    if not код:
        плохо(f"{н} пресету не выдан код"); стр.close(); return
    стр.evaluate(СЕВ, код)
    # мини-окно: только события пресета, без справочника и чужих
    к.открыть(стр); к.вкладка(стр, "l"); стр.wait_for_timeout(500)
    т = стр.evaluate("() => document.querySelector('#presetChipCard .pc-lg-sc').innerText")
    if "Метка-пресета" not in т or "Ручной проект" in т or "Цены проекта" in т or "Цена опции" in т or "Чужая-метка" in т:
        плохо(f"{н} журнал мини-окна подмешивает не свои события: {т[:240]!r}")
    # полный журнал уже показывал чужую ленту — открываем его с отбором
    стр.evaluate("() => { closeActionLog && 0; }")
    стр.evaluate("() => { _alПериод = 'всё'; _alПресет = null; openActionLog(); }"); стр.wait_for_timeout(900)
    стр.evaluate("() => { closeActionLog(); window.__ЗАДЕРЖКА = 700; }")
    к.открыть(стр); к.вкладка(стр, "l"); стр.wait_for_timeout(200)
    стр.locator("#presetChipCard [data-act='to-log']").click(); стр.wait_for_timeout(120)
    сразу = стр.evaluate("() => document.getElementById('alFeed').innerText")
    # Чужие строки узнаём по коду в строке: подробности свёрнуты, их текста в
    # кадре нет.
    if "999 999" in сразу or "Чужая-метка" in сразу:
        плохо(f"{н} «Открыть в журнале действий» сначала показывает прежнюю ленту других пресетов")
    стр.wait_for_timeout(1300)
    стр.evaluate("() => { window.__ЗАДЕРЖКА = 0; }")
    пж = стр.evaluate("""() => { const л = document.getElementById('alFeed'); return { текст: л.innerText, строк: л.querySelectorAll('.al-row').length, пресет: _alПресет }; }""")
    if пж["пресет"] != код or "999 999" in пж["текст"] or "Чужая-метка" in пж["текст"] or "Ручной проект" in пж["текст"] or пж["строк"] < 2:
        плохо(f"{н} полный журнал с отбором по пресету неполон или подмешивает: строк {пж['строк']}, {пж['текст'][:200]!r}")
    стр.evaluate("() => { closeActionLog(); _alПресет = null; _alПериод = '7'; }")
    # раскладка снимков при открытии — не правка; настоящее добавление — правка
    стр.evaluate("() => { window.__ТАБЛИЦЫ.events = []; }")
    стр.evaluate("""async () => { await restoreCanvasFromUrls([{ url: '/assets/logo-bmsk-dark.png', left: 10, top: 10, width: 120, height: 60 },
      { url: '/assets/logo-bmsk-dark.png', left: 150, top: 10, width: 120, height: 60 }]); }""")
    стр.wait_for_timeout(2000)
    если = стр.evaluate("() => (window.__ТАБЛИЦЫ.events || []).filter(e => e.event_type === 'images_changed').length")
    if если:
        плохо(f"{н} открытие пресета со снимками записало «Изображения изменены»")
    стр.evaluate("() => { canvasAddImageAt('/assets/logo-bmsk-dark.png', 300, 10, 120, 60); }")
    стр.wait_for_timeout(2000)
    есть = стр.evaluate("() => (window.__ТАБЛИЦЫ.events || []).filter(e => e.event_type === 'images_changed').map(e => (e.details.rows || [])[0])")
    if not есть or есть[0].get("a") != "2" or есть[0].get("b") != "3":
        плохо(f"{н} добавленный снимок не записан как правка 2 → 3: {есть}")
    for о in [о for о in ошибки if "supabase.co" not in о][:3]:
        плохо(f"{н} ошибка страницы: {о[:160]}")
    стр.close()


def главная():
    по_коду()
    с, порт = м.сервер()
    try:
        with sync_playwright() as pw:
            бр = pw.chromium.launch(executable_path=м.хром(), args=["--no-sandbox"])
            for ш, в in ((390, 844), (1440, 900)):
                прогон(бр, порт, ш, в)
            бр.close()
    finally:
        с.shutdown()
    if НАХОДКИ:
        print("НАХОДКИ:")
        for н in НАХОДКИ:
            print("  ✗", н)
        raise SystemExit(1)
    print("Чисто: в журнале пресета только его события — без правок справочника и чужих пресетов, полный журнал "
          "с отбором берёт их из базы целиком и не показывает прежнюю ленту, раскладка снимков при открытии не пишется "
          "как правка — на 390 и 1440.")


if __name__ == "__main__":
    главная()
