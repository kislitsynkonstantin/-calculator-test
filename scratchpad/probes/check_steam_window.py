#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Окно в парное отделение 500×500 — галочка по парной, у каркаса и бруса одинаково.

Константин 14.10.2026, снимком разбора проверки: «Окно в парную в брусе также
добавь 500х500 в раздел Окна и двери, если есть парная». 17.10.2026, снимком
строки каркаса: «Окно в парное в каркасе и брусе напиши так: Окно в парном
отделении — деревянное из липы 500х500 мм. Также правило, если есть парное
отделение в расчёте, тогда его ставим. Если нет парного отделения, тогда
снимаем галочку. Если есть парное, а менеджер случайно тут снял галочку,
пишем в проверке, чтобы добавил».

До 17.10.2026 у бруса строка без парной пряталась и нажатия не принимала, у
каркаса правила не было вовсе. Держит, у бруса и у каркаса:
  • строка окна стоит в «Окнах и дверях» и видна всегда, названа
    «Окно в парном отделении — деревянное из липы 500×500 мм»;
  • появилась парная — окно отмечено; пропала — галочка снята;
  • своей цены у окна нет: итог от него не меняется;
  • снятое руками при парной окно остаётся снятым, а «Проверка» просит
    «Добавить окно в парное отделение 500×500» и ведёт к его строке;
    вернули галочку — пункт ушёл;
  • сохранённый расчёт открывается с той галочкой, с какой его сохранили;
    у старого расчёта бруса, где строки окна ещё не было, окно встаёт по парной.

    python3 check_steam_window.py
"""
import functools, http.server, json, os, pathlib, socketserver, threading
from playwright.sync_api import sync_playwright

КОРЕНЬ = pathlib.Path(os.environ.get("BM_ROOT") or pathlib.Path(__file__).resolve().parent.parent.parent)
ЗДЕСЬ = pathlib.Path(__file__).parent
ЗАГЛУШКА = (ЗДЕСЬ / "stub_sb.js").read_text(encoding="utf-8")
ФИКСТУРА = json.loads((ЗДЕСЬ / "kit_fixture.json").read_text(encoding="utf-8"))
ФИКСТУРА["pricing_options"].append({"product": "glulam", "option_id": "kb_s1", "name": "Сборка парного отделения на плавающем каркасе (учебная)",
                                    "section": "steam", "included": False, "price": 250000, "formula": None, "status": None, "sort": 950})
ЦЕНЫ = ("window.__ТАБЛИЦЫ = Object.assign(window.__ТАБЛИЦЫ || {}, " + json.dumps(ФИКСТУРА, ensure_ascii=False) + ");"
        "window.addEventListener('DOMContentLoaded', () => { window._sbProfile = Object.assign(window._sbProfile || {}, { role: 'manager' }); });")
ИМЯ = "Окно в парном отделении — деревянное из липы 500×500 мм"
НАХОДКИ, ОТЧЁТ = [], []


def факт(ок, т):
    (ОТЧЁТ if ок else НАХОДКИ).append(т)


class Тихий(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *а):
        pass


# Парная меряется сама, а не функцией страницы: на прежней сборке её нет, и
# проба должна падать на поведении, а не на имени.
ПАРНАЯ = """const парнаяЕсть = () => OPTIONS.some(o => o.section === 'steam' && checkedOptions[o.id] && (currentTech !== 'glulam' || !o.included))
  || getCustomOpts('steam').some(co => co.checked);"""
СОСТ = """() => { """ + ПАРНАЯ + """ const ид = idВРасчёте('w7'); const л = ид && document.getElementById('lbl_' + ид); const список = л && л.closest('[id^="list_"]');
  const пр = проверкаПоЧекЛисту().замечания.find(з => /окно в парн/i.test(з.т));
  return { ид, есть: !!л, видна: !!л && л.getClientRects().length > 0, отмечена: !!(ид && checkedOptions[ид]), раздел: список ? список.id : '',
    имя: ((ид && getOpt(ид)) || {}).name || '', парная: парнаяЕсть(), итог: al2ИтогДо(),
    просит: пр ? { т: пр.т, эл: пр.эл } : null }; }"""
НАЖАТЬ = "(ид) => { const л = document.getElementById('lbl_' + ид); if (л) л.click(); calc(); }"
# Снять или вернуть парную целиком: у каркаса это строки базы раздела.
ПАРНАЯ_КАРКАСА = """(надо) => { if (!надо) { window.__снятые = OPTIONS.filter(o => o.section === 'steam' && checkedOptions[o.id]).map(o => o.id);
    window.__снятые.forEach(ид => toggleOpt(ид)); } else { (window.__снятые || []).forEach(ид => toggleOpt(ид)); } calc(); """ + ПАРНАЯ + """ return парнаяЕсть(); }"""

socketserver.TCPServer.allow_reuse_address = True
с = socketserver.TCPServer(("127.0.0.1", 0), functools.partial(Тихий, directory=str(КОРЕНЬ)))
threading.Thread(target=с.serve_forever, daemon=True).start()
хром = os.environ.get("BM_CHROMIUM") or str(sorted(pathlib.Path("/opt/pw-browsers").glob("chromium-*/chrome-linux/chrome"))[-1])


def ждать(стр, мс=350):
    стр.wait_for_timeout(мс)


with sync_playwright() as pw:
    бр = pw.chromium.launch(executable_path=хром, args=["--no-sandbox"])
    стр = бр.new_page(viewport={"width": 1440, "height": 1000})
    ошибки = []
    стр.on("pageerror", lambda e: ошибки.append(str(e)))
    стр.route("**/fonts.googleapis.com/**", lambda r: r.abort())
    стр.add_init_script(ЗАГЛУШКА)
    стр.add_init_script(ЦЕНЫ)
    стр.goto(f"http://127.0.0.1:{с.server_address[1]}/index.html", wait_until="load")
    стр.wait_for_timeout(2500)
    стр.evaluate("() => { const б = document.getElementById('pricingErrorScreen'); if (б) б.style.display = 'none'; selectProjectOption(0); calc(); }")
    ждать(стр, 500)
    # Список опций каркаса с 17.10.2026 — из базы (в пробе — из заглушки), в
    # файле его больше нет: название сверяется у загруженной строки.
    факт(стр.evaluate("() => (getOpt('w7') || {}).name") == "Окно в парном отделении — деревянное из липы 500×500 мм",
         "строка окна в парную названа по-новому")

    # ── Каркас: парная входит в базу ──
    д = стр.evaluate(СОСТ)
    факт(д["ид"] == "w7" and д["раздел"] == "list_windows" and д["видна"], f"каркас: строка окна в «Окнах и дверях»: {д['раздел']}")
    факт(д["парная"] and д["отмечена"] and not д["просит"], f"каркас: парная в базе — окно отмечено, «Проверка» молчит: {д}")
    стр.evaluate(НАЖАТЬ, "w7"); ждать(стр)
    д = стр.evaluate(СОСТ)
    факт(not д["отмечена"], "каркас: снятое руками окно остаётся снятым — правило не перебивает")
    факт(bool(д["просит"]) and д["просит"]["т"] == "Добавить окно в парное отделение 500×500" and д["просит"]["эл"] == "lbl_w7",
         f"каркас: «Проверка» просит добавить окно и ведёт к строке: {д['просит']}")
    стр.evaluate(НАЖАТЬ, "w7"); ждать(стр)
    д = стр.evaluate(СОСТ)
    факт(д["отмечена"] and not д["просит"], "каркас: галочку вернули — пункт ушёл")
    итог_с = д["итог"]
    парная = стр.evaluate(ПАРНАЯ_КАРКАСА, False); ждать(стр)
    д = стр.evaluate(СОСТ)
    факт(not парная and not д["отмечена"] and д["видна"] and not д["просит"], f"каркас: парную сняли — галочка снята, строка видна: {д}")
    парная = стр.evaluate(ПАРНАЯ_КАРКАСА, True); ждать(стр)
    д = стр.evaluate(СОСТ)
    факт(парная and д["отмечена"] and д["итог"] == итог_с, f"каркас: парную вернули — окно снова отмечено, итог прежний: {д['итог']} / {итог_с}")
    # Сохранили со снятым окном — открывается снятым и с пунктом «Проверки».
    стр.evaluate(НАЖАТЬ, "w7"); ждать(стр)
    сост = стр.evaluate("() => collectState()")
    стр.evaluate(НАЖАТЬ, "w7"); ждать(стр)
    стр.evaluate("(с) => { restoreState(с); calc(); }", сост); ждать(стр, 700)
    д = стр.evaluate(СОСТ)
    факт(not д["отмечена"] and bool(д["просит"]), f"каркас: расчёт со снятым окном открывается снятым и с пунктом: {д['отмечена']}, {д['просит']}")

    # ── Брус: парную собирают опциями ──
    стр.evaluate("async () => { await switchTech('glulam'); await new Promise(r => setTimeout(r, 600)); selectProjectOption(0); calc(); }")
    ждать(стр, 600)
    факт(стр.evaluate("() => currentTech") == "glulam", "расчёт бруса открыт")
    д = стр.evaluate(СОСТ)
    факт(д["ид"] == "kb_steam_window" and д["раздел"] == "list_windows", f"брус: строка окна в «Окнах и дверях»: {д['раздел'] or 'строки нет'}")
    факт(д["имя"] == ИМЯ, f"брус: строка названа «{ИМЯ}»: «{д['имя']}»")
    факт(д["видна"] and not д["отмечена"] and not д["просит"], f"брус: без парной строка видна и не отмечена: видна {д['видна']}, отмечена {д['отмечена']}")
    без = д["итог"]
    стр.evaluate(НАЖАТЬ, "kb_s1"); ждать(стр)
    д = стр.evaluate(СОСТ)
    факт(д["отмечена"] and not д["просит"], f"брус: с парной окно отмечено: {д['отмечена']}")
    парная = стр.evaluate("() => { const ф = плавающийКаркасСостав(true); return (getOpt('kb_s1').price || 0) + (ф.steam ? (Number(((_ставкиРучного.glulam || {}).floating_frame || {}).steam) || 0) : 0); }")
    факт(д["итог"] - без == парная, f"брус: своей цены у окна нет: итог вырос на {д['итог'] - без}, парная с каркасом — {парная}")
    стр.evaluate(НАЖАТЬ, "kb_steam_window"); ждать(стр)
    д = стр.evaluate(СОСТ)
    факт(not д["отмечена"] and bool(д["просит"]) and д["просит"]["эл"] == "lbl_kb_steam_window",
         f"брус: снятое руками окно — «Проверка» просит добавить и ведёт к строке: {д['просит']}")
    стр.evaluate(НАЖАТЬ, "kb_steam_window"); ждать(стр)
    факт(стр.evaluate(СОСТ)["отмечена"], "брус: галочку вернули нажатием")
    # Старый расчёт бруса: парная отмечена, строки окна в нём нет.
    старый = стр.evaluate("() => { const с = collectState(); delete с.checkedOptions.kb_steam_window; return с; }")
    стр.evaluate(НАЖАТЬ, "kb_s1"); ждать(стр)
    д = стр.evaluate(СОСТ)
    факт(not д["отмечена"] and д["видна"] and д["итог"] == без, f"брус: парную сняли — окно снято, итог прежний: отмечена {д['отмечена']}, итог {д['итог']}")
    стр.evaluate("(с) => { restoreState(с); calc(); }", старый); ждать(стр, 700)
    д = стр.evaluate(СОСТ)
    факт(д["отмечена"] and not д["просит"], f"брус: старый расчёт с парной открывается с окном: {д['отмечена']}")
    факт(not ошибки, f"ошибок страницы нет: {ошибки[:2]}")
    бр.close()
с.shutdown()

for т in ОТЧЁТ:
    print("    ок  " + т)
if НАХОДКИ:
    print("НАХОДКИ:")
    for т in НАХОДКИ:
        print("  ✗ " + т)
    raise SystemExit(1)
print("Чисто: окно в парное отделение ставится и снимается по парной у каркаса и бруса; снятое руками при парной — пункт «Проверки».")
