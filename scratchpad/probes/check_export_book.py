#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Выгрузка базы в Excel: всё живое доходит, технологии не смешиваются.

Константин 13.10.2026: «проверь таблицу экспорта — чтобы все значения туда
попадали, то что меняли. Не должны пересекаться они». Сверка на живой базе
нашла три расхождения: у каркаса лист «Базовые комплектации» был списком в
коде и терял пять примечаний (среди них «Фундамент не входит в расчёт», а
раздел «Печь», где базовых позиций нет, — целиком); у бруса не выводились
ставки ручного проекта, по которым он считается; лист «Информация» называл
брус «планируется».

Книга снимается подменой XLSX: сборщик кладёт массивы листов в окно. Проба
держит, для каркаса и для бруса:
  • в «Базе» — ровно проекты открытой технологии, своих префиксов;
  • в «Матрице» — каждая небазовая опция, без повторов;
  • в «Базовых комплектациях» — каждая базовая позиция и каждое примечание
    каждого раздела, подписи толщины своей технологии;
  • у бруса — лист ставок со ставками, поправками и плавающим каркасом из базы;
  • в «Информации» брус — действующий продукт.

    python3 check_export_book.py
"""
import json, pathlib, sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
import check_preset_chip as м
from playwright.sync_api import sync_playwright

НАХОДКИ = []
# Ставки бруса — выдуманные: репозиторий открыт, настоящие лежат только в базе.
СТАВКИ = [
    {"product": "glulam", "key": "cp_rates", "value": {"1": [{"max": 30, "rate": 111}, {"max": None, "rate": 99}]}},
    {"product": "glulam", "key": "cp_coef", "value": {"base": 1, "glazing": 0.05, "sections": [0.8, 1, 1.2],
                                                      "no_finish": 0.1, "terrace_open": 1000, "terrace_closed": 2000}},
    {"product": "glulam", "key": "floating_frame", "value": {"steam": 777, "shower": 333}},
]
ПОДМЕНА = """window.__ТАБЛИЦЫ.pricing_rates = %s;
window.XLSX = { utils: {
  book_new: () => ({ листы: [] }),
  aoa_to_sheet: d => ({ d: JSON.parse(JSON.stringify(d)) }),
  book_append_sheet: (wb, ws, n) => wb.листы.push([n, ws.d]) },
  writeFile: (wb, имя) => { window.__КНИГА = { имя, листы: wb.листы }; } };""" % json.dumps(СТАВКИ)

ЖИВОЕ = """() => ({ тех: currentTech, проекты: [...PROJECTS, ...customProjects].map(p => p[0]),
  небазовые: OPTIONS.filter(o => !o.included && SECTIONS.some(с => с.key === o.section)).map(o => o.id),
  базовые: OPTIONS.filter(o => o.included && SECTIONS.some(с => с.key === o.section)).map(o => o.id),
  примечания: SECTIONS.flatMap(с => (SECTION_NOTES[с.key] || []).map(т => [с.name, т])),
  толщ: TECH_THICK[currentTech] })"""


def лист(книга, начало):
    for имя, д in книга["листы"]:
        if имя.startswith(начало):
            return имя, д
    return None, None


def сверить(стр, тех, чужие_проекты):
    стр.evaluate("async (т) => { await switchTech(т); }", тех)
    стр.wait_for_timeout(800)
    # Примечание, дописанное в каталог сейчас, обязано попасть в выгрузку: так
    # проверяется, что лист собран из живого каталога, а не из списка в коде.
    стр.evaluate("() => { (SECTION_NOTES.stove = SECTION_NOTES.stove || []).push('Проба: примечание печи'); }")
    стр.evaluate("() => { window.__КНИГА = null; _doExcelExport(); }")
    к = стр.evaluate("() => window.__КНИГА")
    ж = стр.evaluate(ЖИВОЕ)
    н = f"[{тех}]"
    if not к:
        НАХОДКИ.append(f"{н} книга не собралась"); return None
    _, база = лист(к, "База")
    имена = [р[2] for р in (база or [])[1:]]
    if sorted(имена) != sorted(ж["проекты"]):
        НАХОДКИ.append(f"{н} в «Базе» {имена}, а проекты технологии {ж['проекты']}")
    if set(имена) & set(чужие_проекты):
        НАХОДКИ.append(f"{н} в «Базе» проекты другой технологии: {sorted(set(имена) & set(чужие_проекты))}")
    пре = "kb_proj_" if тех == "glulam" else "proj_"
    if any(not str(р[0]).startswith(пре) for р in (база or [])[1:]):
        НАХОДКИ.append(f"{н} в «Базе» ID не с префиксом {пре}")
    _, мат = лист(к, "Матрица")
    ид = [р[0] for р in (мат or [])[4:] if р[0] and р[1]]
    if len(ид) != len(set(ид)):
        НАХОДКИ.append(f"{н} в «Матрице» повторы ID")
    нет = [и for и in ж["небазовые"] if и not in ид]
    if нет:
        НАХОДКИ.append(f"{н} в «Матрице» нет опций: {нет[:8]}")
    имя3, бк = лист(к, "Базовые комплектации")
    бк = бк or []
    if бк and бк[0][3:] != ["Базовая комплектация " + т for т in ж["толщ"]]:
        НАХОДКИ.append(f"{н} шапка базовых комплектаций {бк[0][3:]}, ждали толщины {ж['толщ']}")
    есть_ид = {р[0] for р in бк if р and р[1] == "Опция"}
    нет = [и for и in ж["базовые"] if и not in есть_ид]
    if нет:
        НАХОДКИ.append(f"{н} в «{имя3}» нет базовых позиций: {нет[:8]}")
    есть_прим = [р[3] for р in бк if р and р[1] == "Примечание"]
    нет = [т for _, т in ж["примечания"] if т not in есть_прим]
    if нет:
        НАХОДКИ.append(f"{н} в «{имя3}» нет примечаний: {нет}")
    _, инф = лист(к, "Информация")
    брус = [р for р in (инф or []) if р and р[0] == "Клеёный брус"]
    if not брус or брус[0][2] != "Активен":
        НАХОДКИ.append(f"{н} в «Информации» клеёный брус: {брус[:1]}, ждали «Активен»")
    имяС, ст = лист(к, "Ставки ручных проектов")
    if тех == "glulam":
        if not ст:
            НАХОДКИ.append(f"{н} листа ставок ручного проекта нет")
        else:
            плоско = [ч for р in ст for ч in р]
            for ждём, что in ((111, "ставка до 30 м²"), (99, "ставка более 30 м²"), (2000, "крытая терраса"),
                              (1000, "открытая терраса"), (1.2, "доля толщины"), (777, "плавающий каркас парной"),
                              (333, "плавающий каркас душа")):
                if ждём not in плоско:
                    НАХОДКИ.append(f"{н} в «{имяС}» нет: {что} ({ждём})")
            if "5%" not in плоско or "−10%" not in плоско:
                НАХОДКИ.append(f"{н} в «{имяС}» нет поправок остекления и «без отделки»")
    elif тех == "frame" and not ст:
        НАХОДКИ.append(f"{н} листа ставок ручного проекта каркаса нет")
    return ж


def main():
    проекты = {т: [р["name"] for р in м.ДАННЫЕ["pricing_projects"] if р.get("product") == т] for т in ("frame", "glulam")}
    с, порт = м.сервер()
    try:
        with sync_playwright() as п:
            бр = п.chromium.launch(executable_path=м.хром())
            стр = бр.new_page(viewport={"width": 1440, "height": 1000})
            ош = []
            стр.on("pageerror", lambda e: ош.append(str(e)))
            стр.add_init_script(м.ЗАГЛУШКА); стр.add_init_script(м.ТАБЛИЦЫ_JS); стр.add_init_script(ПОДМЕНА)
            стр.goto(f"http://127.0.0.1:{порт}/index.html", wait_until="load"); стр.wait_for_timeout(2500)
            стр.evaluate("() => { const б = document.getElementById('pricingErrorScreen'); if (б) б.style.display = 'none'; }")
            сверить(стр, "frame", проекты["glulam"])
            сверить(стр, "glulam", проекты["frame"])
            if ош:
                НАХОДКИ.append(f"ошибки страницы: {ош[:3]}")
            бр.close()
    finally:
        с.shutdown()
    if НАХОДКИ:
        print("НАХОДКИ:")
        for н in НАХОДКИ:
            print("  ✗", н)
        sys.exit(1)
    print("Чисто: выгрузка каркаса и бруса — проекты только своей технологии, все небазовые опции в матрице, "
          "все базовые позиции и примечания (с дописанным сейчас) в базовых комплектациях, толщины своей "
          "технологии; у бруса — лист ставок ручного проекта из базы; брус в «Информации» действующий.")


if __name__ == "__main__":
    main()
