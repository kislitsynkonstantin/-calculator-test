#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Скидка у каждого вида расчёта своя — до «Сбросить всё».

Константин 27.10.2026, снимком блока скидки: «Вот эти параметры, когда
переключаешь технологию и не выбран проект, сделай, чтобы гуляли за типом
расчёта. Если в парной стоит скидка 50 000р, то когда переключаешь на каркас,
а там стояла базовая скидка 200 тыс., то так она должна и остаться. Это до
момента, как нажмём „Сбросить всё“».

Проба держит:
  • каркас со скидкой 200 000 ₽ и сроком «действительна до» → парная: у парной
    скидки нет, поля пустые;
  • у парной 50 000 ₽ за наличные → каркас: снова 200 000 ₽ суммой, без
    «за наличные», с прежним сроком, и спец. цена каркаса — итог минус 200 000;
  • обратно на парную — 50 000 ₽ за наличные, спец. цена — итог минус 50 000;
  • брус, где скидку не ставили, начинается без скидки;
  • «Сбросить всё» забывает скидки у всех: после него каркас без скидки.

    python3 check_discount_per_tech.py
"""
import pathlib, sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
import check_preset_chip as м
import check_steam_tab as п
from playwright.sync_api import sync_playwright

НАХОДКИ = []

СКИДКА = """() => ({ режим: _режимСкидки, сумма: _скидкаСуммой,
  процент: document.getElementById('discountPctInput').value,
  наличные: document.getElementById('cashDiscountCheck').checked,
  до: document.getElementById('discountUntilDate').value,
  итог: Math.round(window._итогДоСкидки || 0), спец: Math.round(window._итогСоСкидкой || 0) })"""


def плохо(т):
    НАХОДКИ.append(т)


def скидка_суммой(стр, рубли):
    # Главное поле — сумма: так скидку дают суммой, и пересчёт её не трогает.
    стр.click('#discSumLab')
    стр.fill('#discountSavedInput', str(рубли))
    стр.evaluate("() => document.getElementById('discountSavedInput').blur()")
    стр.wait_for_timeout(200)


def на(стр, тех):
    стр.evaluate("async т => { selectTech(т); await new Promise(r => setTimeout(r, 900)); }", тех)


def main():
    с, порт = м.сервер()
    try:
        with sync_playwright() as pw:
            бр = pw.chromium.launch(executable_path=м.хром())
            стр, ош = п.открыть(бр, порт, 1440)
            стр.evaluate("ц => FRAME_OPTIONS.forEach(о => { if (о.id in ц) о.price = ц[о.id]; })", п.ЦЕНЫ_ПЕЧЕЙ)
            стр.evaluate("() => { window.IS_TEST_DOMAIN = true; applySteamGate(); }")

            # Каркас: 200 000 ₽ суммой, срок до 30.11.2026.
            стр.evaluate("() => selectProjectOption(0)")
            стр.wait_for_timeout(500)
            скидка_суммой(стр, 200000)
            стр.evaluate("() => { const д = document.getElementById('discountUntilDate'); д.value = '2026-11-30'; д.dispatchEvent(new Event('input')); }")
            к = стр.evaluate(СКИДКА)
            if (к["режим"], к["сумма"], к["до"]) != ("сумма", 200000, "2026-11-30") or к["итог"] - к["спец"] != 200000:
                плохо(f"каркас: скидка не встала — {к}")

            # Парная — своей скидки нет.
            на(стр, 'Парная')
            в = стр.evaluate(СКИДКА)
            if (в["режим"], в["сумма"], в["наличные"], в["до"], float(в["процент"] or 0)) != ("процент", 0, False, "", 0.0) or в["итог"] != в["спец"]:
                плохо(f"парная после каркаса со скидкой 200 000: {в} — ждали без скидки")
            скидка_суммой(стр, 50000)
            стр.evaluate("() => document.getElementById('cashDiscountCheck').click()")
            в = стр.evaluate(СКИДКА)
            if (в["сумма"], в["наличные"]) != (50000, True) or в["итог"] - в["спец"] != 50000:
                плохо(f"парная: скидка 50 000 за наличные не встала — {в}")

            # Обратно на каркас — его 200 000 и срок на месте.
            на(стр, 'Каркас')
            стр.evaluate("() => selectProjectOption(0)")
            стр.wait_for_timeout(500)
            к = стр.evaluate(СКИДКА)
            if (к["режим"], к["сумма"], к["наличные"], к["до"]) != ("сумма", 200000, False, "2026-11-30") or к["итог"] - к["спец"] != 200000:
                плохо(f"каркас после парной со скидкой 50 000: {к} — ждали прежние 200 000 ₽ без «за наличные»")

            # Брус — скидки не ставили.
            на(стр, 'Клеёный брус')
            б = стр.evaluate(СКИДКА)
            if (б["сумма"], б["наличные"], б["до"]) != (0, False, ""):
                плохо(f"брус: чужая скидка — {б}")

            # Снова парная — её 50 000 за наличные.
            на(стр, 'Парная')
            в = стр.evaluate(СКИДКА)
            if (в["режим"], в["сумма"], в["наличные"]) != ("сумма", 50000, True) or в["итог"] - в["спец"] != 50000:
                плохо(f"парная после каркаса и бруса: {в} — ждали её 50 000 ₽ за наличные")

            # «Сбросить всё» — забыты все.
            стр.evaluate("() => resetEverything()")
            на(стр, 'Каркас')
            к = стр.evaluate(СКИДКА)
            if (к["сумма"], к["наличные"], к["до"], float(к["процент"] or 0)) != (0, False, "", 0.0):
                плохо(f"каркас после «Сбросить всё» в парной: {к} — ждали без скидки")
            if ош:
                плохо(f"ошибки страницы: {ош[:3]}")
            бр.close()
    finally:
        с.shutdown()
    if НАХОДКИ:
        print("НАХОДКИ:")
        for н in НАХОДКИ:
            print("  ✗", н)
        sys.exit(1)
    print("Чисто: скидка у каждого вида расчёта своя — каркас 200 000 ₽ со сроком, парная 50 000 ₽ за наличные, "
          "брус без скидки; при переключении туда и обратно каждая возвращается своей, «Сбросить всё» забывает все.")


if __name__ == "__main__":
    main()
