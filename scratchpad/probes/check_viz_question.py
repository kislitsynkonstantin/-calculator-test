"""Вопрос проверки о визуализации знает, что уже добавлено.

Константин 30.09.2026, снимком вкладки «Проверка» с одним видом в блоке:
«когда 1 вид визуализации добавлен, написать „Добавить ещё один вид
визуализации и планировку“. Аналогично, если добавили планировку — распознать
и про неё не писать». Раньше: «минимум 2 изображения достаточно: 1
визуализация, 1 планировка».

Проба на 390 и 1440 добавляет настоящие снимки (визуализацию и планировку из
образцы_приложения2) и держит вопрос для каждого набора:
  ничего                    — «Добавить два вида визуализации и планировку»;
  один вид                  — «Добавить ещё один вид визуализации и планировку»;
  два вида                  — «Добавить планировку»;
  только планировка         — «Добавить два вида визуализации»;
  вид и планировка          — вопроса нет (минимум соблюдён);
  планировка добавлена первой и вид — тоже вопроса нет.
И отдельно: карточка открыта на «Проверке», снимок добавлен — вопрос меняется
сам, когда код узнал снимок, без повторного открытия.

    python3 check_viz_question.py
"""
import pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).parent))
import check_preset_chip as м
import check_preset_card as к
from playwright.sync_api import sync_playwright

НАХОДКИ = []
ВИЗ = "/scratchpad/probes/образцы_приложения2/визуализация.jpg"
ПЛАН = "/scratchpad/probes/образцы_приложения2/планировка.png"
НАБОРЫ = [
    ([], "Добавить два вида визуализации и планировку"),
    ([ВИЗ], "Добавить ещё один вид визуализации и планировку"),
    ([ВИЗ, ВИЗ + "?2"], "Добавить планировку"),
    ([ПЛАН], "Добавить два вида визуализации"),
    ([ВИЗ, ПЛАН], None),
    ([ПЛАН, ВИЗ], None),
]
ВОПРОС = """async (снимки) => { canvasClearAll && (() => { canvasItems.length = 0; document.querySelectorAll('#imageCanvas .canvas-img-item').forEach(э => э.remove()); })();
  снимки.forEach(s => canvasAddImage(s)); await Promise.all(снимкиХолста().map(видКартинки));
  return проверкаПоЧекЛисту().вопросы.filter(в => /визуализац|планировк/i.test(в)); }"""


def прогон(бр, порт, ш, в):
    н = f"[{ш}]"
    стр, ошибки = к.начать(бр, порт, ш, в, False)
    for снимки, ждём in НАБОРЫ:
        есть = стр.evaluate(ВОПРОС, снимки)
        имя = " + ".join("вид" if s.startswith(ВИЗ) else "планировка" for s in снимки) or "ничего"
        if (ждём and есть != [ждём]) or (not ждём and есть):
            НАХОДКИ.append(f"{н} {имя}: ждали {ждём!r}, есть {есть}")
    # Карточка открыта на «Проверке» — вопрос меняется сам.
    стр.evaluate("() => { canvasItems.length = 0; document.querySelectorAll('#imageCanvas .canvas-img-item').forEach(э => э.remove()); _видыКартинок.clear(); calc(); }")
    к.открыть(стр); к.вкладка(стр, "c"); стр.wait_for_timeout(400)
    стр.evaluate("(s) => { canvasAddImage(s); calc(); }", ВИЗ)
    стр.wait_for_timeout(1500)
    текст = стр.evaluate("() => [...document.querySelectorAll('#pcPane-c .pc-q')].map(э => э.textContent.trim()).join(' | ')")
    if "ещё один вид" not in текст:
        НАХОДКИ.append(f"{н} открытая карточка не обновилась после распознавания: {текст}")
    for о in [о for о in ошибки if "supabase.co" not in о][:3]:
        НАХОДКИ.append(f"{н} ошибка страницы: {о[:160]}")
    стр.close()


def главная():
    с, порт = м.сервер()
    try:
        with sync_playwright() as pw:
            бр = pw.chromium.launch(executable_path=м.хром(), args=["--no-sandbox"])
            прогон(бр, порт, 390, 844)
            прогон(бр, порт, 1440, 900)
            бр.close()
    finally:
        с.shutdown()
    if НАХОДКИ:
        print("НАХОДКИ:")
        for н in НАХОДКИ:
            print("  ✗", н)
        raise SystemExit(1)
    print("Чисто: вопрос о визуализации по набору снимков — ничего, один вид, два вида, только планировка, вид и "
          "планировка в любом порядке; открытая «Проверка» меняет вопрос сама после распознавания — на 390 и 1440.")


if __name__ == "__main__":
    главная()
