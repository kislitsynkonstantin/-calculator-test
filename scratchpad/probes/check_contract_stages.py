#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Этапы приёмки п. 5.1 — по спецификации договора и в лад с графиком платежей.

Константин 03.10.2026: «этапы приёмки подстраивай по спецификации к каждому
договору. Акты также сделай, чтобы совпадали с событиями оплаты». До этого
п. 5.1 был неизменным списком: основной договор всегда перечислял фундамент,
окна и коммуникации, а договор на отделку — малярные и плиточные работы,
даже когда их не заказывали.

Проба держит:
  • первый этап — передача площадки (основной) или Объекта (отделка),
    последний — окончательная приемка;
  • раздел спецификации, где ничего не отмечено, этапа не даёт, а отмеченный —
    даёт; парная или печь — один этап парного отделения;
  • каждый платёж «в день окончания …» имеет этап, названный теми же словами,
    а финальный платёж по отделке привязан к акту окончательной приемки;
  • у договора на отделку платёж «после уведомления о готовности начать
    отделку парной» стоит между двумя этапами — внутренней отделкой и парной;
    акта у него нет, и это верно: «не обязательно ко всем платежам должны
    быть акты» (03.10.2026).

    python3 check_contract_stages.py
"""
import pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).parent))
import check_contract_otd as о
import check_preset_chip as м
from playwright.sync_api import sync_playwright

НАХОДКИ = []

ДОГОВОР = """(ид) => { const д = new DOMParser().parseFromString(buildContractHtmlKar(getContractVarsKar(ид)), 'text/html');
  const т = э => э.textContent.replace(/\\s+/g, ' ').trim();
  const п51 = [...д.querySelectorAll('p.clause')].find(п => т(п).startsWith('5.1.'));
  let э = п51.nextElementSibling; while (э && э.tagName !== 'UL') э = э.nextElementSibling;
  return { этапы: [...э.querySelectorAll('li')].map(т), сроки: [...д.querySelectorAll('.g1 .tm')].map(т),
    разделы: getPPContracts().find(c => c.id === ид).sections.filter(к => !isPrintSectionEmpty(к)) }; }"""

СНЯТЬ = """(разделы) => { OPTIONS.filter(o => разделы.includes(o.section)).forEach(o => { checkedOptions[o.id] = false; });
  разделы.forEach(к => { try { (getCustomOpts(к) || []).forEach(co => { co.checked = false; }); } catch (e) {} }); calc(); }"""

ЭТАП_РАЗДЕЛА = {
    "foundation": "работы по монтажу фундамента", "frame": "каркасные работы",
    "roof": "кровельные работы (без водосточной системы)", "insulation": "работы по утеплению и монтажу пленок",
    "windows": "работы по монтажу окон и дверей", "exterior": "фасадные работы", "paint": "покрасочные работы",
    "engineering": "работы по монтажу инженерных коммуникаций", "interior": "работы по внутренней отделке",
    "steam": "работы по монтажу парного отделения", "stove": "работы по монтажу парного отделения",
}
# Платёж — и этап, акт которого он означает.
ПЛАТЁЖ_ЭТАП = {
    "задаток в день заезда бригады и начала строительных работ": "приемка-передача строительной площадки",
    "задаток в день окончания каркасных работ": "каркасные работы",
    "задаток в день окончания кровельных работ (без водосточной системы)": "кровельные работы (без водосточной системы)",
    "задаток в день окончания работ по утеплению и монтажу пленок": "работы по утеплению и монтажу пленок",
    "оплата в день подписания Акта окончательной приемки выполненных работ": "окончательная приемка выполненных работ.",
}


def проверить(н, д, ид):
    имя = "основной" if ид == 1 else "на отделку"
    э = д["этапы"]
    первый = "приемка-передача строительной площадки" if ид == 1 else "передача Объекта для отделки"
    if not э or э[0] != первый or э[-1] != "окончательная приемка выполненных работ.":
        НАХОДКИ.append(f"{н} {имя}: края списка этапов {э[:1]} … {э[-1:]}")
    ждём = []
    for к in д["разделы"]:
        if к in ЭТАП_РАЗДЕЛА and ЭТАП_РАЗДЕЛА[к] not in ждём:
            ждём.append(ЭТАП_РАЗДЕЛА[к])
    for этап in ждём:
        if этап not in э:
            НАХОДКИ.append(f"{н} {имя}: раздел в спецификации есть, а этапа «{этап}» нет")
    лишние = [x for x in э[1:-1] if x not in ждём and x not in [ПЛАТЁЖ_ЭТАП.get(с) for с in д["сроки"]]]
    if лишние:
        НАХОДКИ.append(f"{н} {имя}: этапы без раздела в спецификации и без платежа: {лишние}")
    if len(э) != len(set(э)):
        НАХОДКИ.append(f"{н} {имя}: этап повторяется: {э}")
    for срок in д["сроки"]:
        if срок in ПЛАТЁЖ_ЭТАП and ПЛАТЁЖ_ЭТАП[срок] not in э:
            НАХОДКИ.append(f"{н} {имя}: платёж «{срок}» есть, а этапа «{ПЛАТЁЖ_ЭТАП[срок]}» нет")
        elif "окончания" in срок and срок not in ПЛАТЁЖ_ЭТАП:
            НАХОДКИ.append(f"{н} {имя}: платёж «{срок}» не привязан к этапу")
        if срок.startswith("задаток после уведомления о готовности начать отделку парной"):
            if "работы по внутренней отделке" not in э or "работы по монтажу парного отделения" not in э or \
               э.index("работы по внутренней отделке") > э.index("работы по монтажу парного отделения"):
                НАХОДКИ.append(f"{н} {имя}: платёж перед парной не стоит между отделкой и парной: {э}")


def прогон(бр, порт, ш):
    к, стр, ош = о.начать(бр, порт, ш, "admin")
    for ид in (1, 2):
        проверить(f"[{ш} весь расчёт]", стр.evaluate(ДОГОВОР, ид), ид)
    до = стр.evaluate(ДОГОВОР, 1)["этапы"]
    стр.evaluate(СНЯТЬ, ["paint", "windows", "foundation"])
    после = стр.evaluate(ДОГОВОР, 1)
    for этап in ("покрасочные работы", "работы по монтажу окон и дверей", "работы по монтажу фундамента"):
        if этап not in до:
            НАХОДКИ.append(f"{ш} в исходном расчёте нет этапа «{этап}» — проба ничего не сняла бы")
        if этап in после["этапы"]:
            НАХОДКИ.append(f"[{ш}] раздел снят, а этап «{этап}» остался")
    проверить(f"[{ш} без покраски, окон и фундамента]", после, 1)
    стр.evaluate(СНЯТЬ, ["steam", "stove"])
    отд = стр.evaluate(ДОГОВОР, 2)
    if "работы по монтажу парного отделения" in отд["этапы"]:
        НАХОДКИ.append(f"[{ш}] парной и печи нет, а этап парного отделения остался")
    проверить(f"[{ш} без парной]", отд, 2)
    for е in [е for е in ош if "supabase.co" not in е][:3]:
        НАХОДКИ.append(f"[{ш}] ошибка страницы: {е[:160]}")
    к.close()


def главная():
    с, порт = м.сервер()
    try:
        with sync_playwright() as pw:
            бр = pw.chromium.launch(executable_path=м.хром(), args=["--no-sandbox"])
            for ш in (390, 1440):
                прогон(бр, порт, ш)
            бр.close()
    finally:
        с.shutdown()
    if НАХОДКИ:
        print("НАХОДКИ:")
        for н in НАХОДКИ:
            print("  ✗", н)
        raise SystemExit(1)
    print("Чисто: этапы приёмки п. 5.1 у обоих договоров идут по спецификации (снятый раздел этапа не даёт), каждый "
          "платёж «в день окончания …» и финальный по отделке имеют свой этап, платёж перед парной — между отделкой "
          "и парной; на 390 и 1440.")


if __name__ == "__main__":
    главная()
