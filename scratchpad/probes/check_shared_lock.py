"""Проба: общий расчёт держит замок, а не роль.

Константин 19.09.2026: «если автор открыл замок, его может править любой.
В этом была идея. Замок открывать и закрывать никто не может кроме автора».

Отсюда пять случаев, и проба проходит каждый:

  • чужой опубликованный расчёт с открытым замком правится, и правка
    доходит до базы. Роль ни при чём: прежде его правили только
    администратор, редактор и специалист, а менеджер не мог вовсе —
    поэтому проба входит именно менеджером;
  • закрытый замок останавливает всех, включая автора, пока автор сам
    его не снимет;
  • кнопка замка есть только у автора. Прежде её видел и администратор,
    то есть мог открыть чужой расчёт всем желающим помимо воли того, кто
    его считал;
  • чужой приватный расчёт, открытый по коду, не правится: общим его
    никто не делал, и база чужую правку всё равно отклонит;
  • свой общий с открытым замком правится, и замок у автора на месте.

Мерка не во флагах, а в поведении: нажимается кнопка толщины и сверяется
строка в базе до и после. Флаг, по которому нельзя нажать, проверять
бессмысленно — он бывает верным при работающей правке.

Правка пробуется на толщине утепления, а не на галочке позиции, и это
отдельный урок. Позиция без цены не отмечается и на здоровом расчёте
(«сначала сумма, потом галочка»), поэтому на галочке «до» и «после»
выходили одинаковыми всегда — мерило вхолостую. Толщина — три кнопки
внутри запертой зоны, переключаются без всяких условий.

    python3 check_shared_lock.py
"""
