def проверить(вид, р):
    имя = "основной" if вид == "kar" else "на отделку"
    if р["версия"] != "2.2":
        НАХОДКИ.append(f"[{имя}] версия {р['версия']}, ждали 2.2")
    ряды = р["ряды"]
    весь = " ".join(т for _, т in ряды)
    for что, шаблон in СНЯТО:
        if re.search(шаблон, весь):
            НАХОДКИ.append(f"[{имя}] осталось снятое: {что}")
    пункты = {н.rstrip("."): т for н, т in ряды if re.match(r"^\d+(\.\d+)+\.$", н)}
    for н, т in НОВОЕ.items():
        if пункты.get(н) != т:
            НАХОДКИ.append(f"[{имя}] {н} не в редакции разбора: «{(пункты.get(н) or 'нет пункта')[:120]}»")
    if not re.search(r"пени в размере 0,1 % от стоимости просроченных работ", пункты.get("8.1", "")):
        НАХОДКИ.append(f"[{имя}] пеня Подрядчика 0,1 % не в 8.1: «{пункты.get('8.1', 'нет пункта')[:100]}»")
    # Номера подряд с единицы в каждом разделе, без подпунктов.
    раздел, ждём = None, 1
    for н, т in ряды:
        if н == "§":
            раздел, ждём = int(re.match(r"\d+", т).group()), 1
            continue
        if not re.match(r"^\d+(\.\d+)+\.$", н):
            continue
        части = н.rstrip(".").split(".")
        if len(части) != 2:
            НАХОДКИ.append(f"[{имя}] подпункт {н} — с версии 2.2 раздел 8 без подпунктов")
            continue
        if int(части[0]) != раздел or int(части[1]) != ждём:
            НАХОДКИ.append(f"[{имя}] номер {н} не по порядку: ждали {раздел}.{ждём}")
        ждём = int(части[1]) + 1
    # Ссылки ведут на пункты своего содержания.
    def тема(н, ключ=None):
        # Ссылка на пункт без записанной темы — тоже находка: иначе ссылка,
        # съехавшая на соседний номер, проходила молча (проверено подменой
        # «п. 5.6» на «п. 5.4» в 5.7).
        ш = ТЕМЫ.get(ключ or н)
        if ш is None:
            НАХОДКИ.append(f"[{имя}] ссылка на п. {н} — пункт, на который договор ссылаться не должен")
            return
        if н not in пункты:
            НАХОДКИ.append(f"[{имя}] ссылка на п. {н} — такого пункта нет")
        elif not re.search(ш, пункты[н]):
            НАХОДКИ.append(f"[{имя}] ссылка на п. {н} ведёт не туда: «{пункты[н][:90]}»")
    обяз = next((т for н, т in ряды if н == "—" and т.startswith("Заказчик не выполнил")), "")
    номера = re.findall(r"\d+\.\d+", обяз)
    ждали = ["2.2", "4.2", "4.3", "6.1"] + (["6.3"] if вид == "kar" else [])
    if номера != ждали:
        НАХОДКИ.append(f"[{имя}] обязанности Заказчика в 5.5: п. {', '.join(номера)}, ждали {', '.join(ждали)}")
    for н in номера:
        тема(н, "6.3_kar" if н == "6.3" else None)
    кроме = re.search(r"кроме случаев п\. (\d+\.\d+)", пункты.get("6.2", ""))
    if not кроме:
        НАХОДКИ.append(f"[{имя}] в 6.2 нет ссылки на ручную разгрузку")
    else:
        тема(кроме.group(1), "разгрузка")
    for н, т in пункты.items():
        for ссылка in re.findall(r"п\. (\d+\.\d+)", т):
            if ссылка not in пункты:
                НАХОДКИ.append(f"[{имя}] в {н} ссылка на п. {ссылка} — такого пункта нет")
            elif н not in ("6.2",):
                тема(ссылка)


