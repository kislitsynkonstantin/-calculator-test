#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""«Проверка»: размер парного и печь — по планировке, а не по опциям.

Константин 17.10.2026, снимком строки «Печь по объёму парной (8-1, 8-3)» из
разбора проверок: «Этот пункт в проверке сделай смотреть по планировке только.
Менеджер может не правильно выбрать в опциях размер парного отделения (это
тоже смотри в проверке)».

Площадь парной читается из экспликации PDF архитектора, когда планировка
добавляется файлом, и хранится на снимке. Проба прикрепляет учебные листы
(образцы_приложения2/план_учебный.pdf — «4 Парная 6,9»; план_таблица.pdf —
«7 Парная 6,2») через поле «Добавить изображение», как менеджер, и держит:
  • площадь легла на снимок планировки и пережила сохранение, выгрузку в
    хранилище и открытие расчёта;
  • печь мала — замечание с нужным объёмом (площадь × 2,2 м + 5 м³, при
    панорамном окне + 10 м³) и выбранным, ведёт к строке печи; печь впору —
    молчит;
  • размер парного в опциях не тот, что по планировке, — замечание называет
    оба и ведёт к строке опции; у каркаса без увеличения парное базовое
    2500×2000, и при большей парной пункт просит увеличение; у бруса без
    размера — просит выбрать; размер впору — молчит;
  • планировка картинкой, площади нет — вопрос сверить вручную;
  • чтение экспликации не путает предпарную с парной и размеры с площадью.
Цены и названия опций в пробе выдуманы: репозиторий публичный.

    python3 check_steam_by_plan.py
"""
import functools, http.server, json, os, pathlib, socketserver, threading
from playwright.sync_api import sync_playwright

КОРЕНЬ = pathlib.Path(os.environ.get("BM_ROOT") or pathlib.Path(__file__).resolve().parent.parent.parent)
ЗДЕСЬ = pathlib.Path(__file__).parent
PDFJS = ЗДЕСЬ / "pdfjs"
УЧЕБНЫЙ = ЗДЕСЬ / "образцы_приложения2" / "план_учебный.pdf"
ТАБЛИЦА = ЗДЕСЬ / "образцы_приложения2" / "план_таблица.pdf"
КАРТИНКА = ЗДЕСЬ / "образцы_приложения2" / "планировка.png"
ЗАГЛУШКА = (ЗДЕСЬ / "stub_sb.js").read_text(encoding="utf-8")
ФИКСТУРА = json.loads((ЗДЕСЬ / "kit_fixture.json").read_text(encoding="utf-8"))


def опция(продукт, ид, раздел, имя, цена, порядок):
    ФИКСТУРА["pricing_options"].append({"product": продукт, "option_id": ид, "name": имя, "section": раздел, "included": False,
                                        "price": цена, "formula": None, "status": None, "sort": порядок})


for ид, имя, п in [("s9", "Увеличение парного до 2500×2500 мм (учебное)", 901), ("s10", "Увеличение парного до 2500×3000 мм (учебное)", 902),
                   ("s11", "Увеличение парного до 3000×3000 (учебное)", 903), ("s13", "Отделка парного учебная 2500×2500 мм", 904),
                   ("s24", "Учебное панно 1000×1000 мм", 905)]:
    опция("frame", ид, "steam", имя, 10000, п)
for ид, имя, п in [("st16", "Учебная печь Малая до 18 м³", 911), ("st17", "Учебная печь Средняя до 25 м³", 912),
                   ("st18", "Учебная печь Большая до 28 м³", 913)]:
    опция("frame", ид, "stove", имя, 20000, п)
for ид, имя, п in [("kb_s1", "Учебная сборка парного отделения, 2500×2500 мм", 921), ("kb_s2", "Учебная сборка парного отделения, 2500×3000 мм", 922),
                   ("kb_s22", "Учебная подсветка потолка", 923)]:
    опция("glulam", ид, "steam", имя, 10000, п)
опция("glulam", "kb_st21", "stove", "Учебная печь Малая до 18 м³", 20000, 931)
опция("glulam", "kb_st42", "stove", "Учебная печь Длинная (до 24 кубов)", 20000, 932)

ЦЕНЫ = ("window.__ТАБЛИЦЫ = Object.assign(window.__ТАБЛИЦЫ || {}, " + json.dumps(ФИКСТУРА, ensure_ascii=False) + ");"
        "window.addEventListener('DOMContentLoaded', () => { window._sbProfile = Object.assign(window._sbProfile || {}, { role: 'manager' }); });")
НАХОДКИ, ОТЧЁТ = [], []


def факт(ок, т):
    (ОТЧЁТ if ок else НАХОДКИ).append(т)


class Тихий(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *а):
        pass


def отдать(r):
    путь = PDFJS / r.request.url.rsplit("/", 1)[-1]
    if путь.exists():
        r.fulfill(status=200, content_type="application/javascript", body=путь.read_bytes())
    else:
        r.abort()


# Пункты «Проверки» о парной и печи — текст и куда ведут.
ПУНКТЫ = """() => { const п = проверкаПоЧекЛисту();
  const з = п.замечания.filter(х => /печь мала|размер парного/i.test(х.т)).map(х => ({ т: х.т, эл: х.эл, р: х.раздел }));
  const в = п.вопросы.filter(т => /парн/i.test(т));
  return { з, в }; }"""
ОТМЕТИТЬ_JS = "([ид, надо]) => { if (!!checkedOptions[ид] !== надо) toggleOpt(ид); calc(); }"
ПЛОЩАДЬ = """() => [...document.querySelectorAll('#imageCanvas .canvas-img-item')].map(э => ({ вид: э.dataset.kind || '', парная: э.dataset.steam || '' }))"""
ОЧИСТИТЬ = "() => { canvasClearAll(); }"

socketserver.TCPServer.allow_reuse_address = True
с = socketserver.TCPServer(("127.0.0.1", 0), functools.partial(Тихий, directory=str(КОРЕНЬ)))
threading.Thread(target=с.serve_forever, daemon=True).start()
хром = os.environ.get("BM_CHROMIUM") or str(sorted(pathlib.Path("/opt/pw-browsers").glob("chromium-*/chrome-linux/chrome"))[-1])


def ждать(стр, мс=350):
    стр.wait_for_timeout(мс)


def прикрепить(стр, файл):
    стр.evaluate(ОЧИСТИТЬ)
    стр.set_input_files("#canvasFileInput", str(файл))
    for _ in range(60):
        стр.wait_for_timeout(250)
        if стр.evaluate("() => canvasItems.length"):
            break
    стр.wait_for_timeout(1200)
    стр.evaluate("() => calc()")
    ждать(стр)


def отметить(стр, ид, надо):
    стр.evaluate(ОТМЕТИТЬ_JS, [ид, надо])


def пункт(д, рв):
    import re
    return next((х for х in д["з"] if re.search(рв, х["т"], re.I)), None)


with sync_playwright() as pw:
    бр = pw.chromium.launch(executable_path=хром, args=["--no-sandbox"])
    стр = бр.new_page(viewport={"width": 1440, "height": 1000})
    ошибки = []
    стр.on("pageerror", lambda e: ошибки.append(str(e)))
    стр.route("**/fonts.googleapis.com/**", lambda r: r.abort())
    стр.route("**/cdnjs.cloudflare.com/ajax/libs/pdf.js/**", отдать)
    стр.add_init_script(ЗАГЛУШКА)
    стр.add_init_script(ЦЕНЫ)
    стр.goto(f"http://127.0.0.1:{с.server_address[1]}/index.html", wait_until="load")
    стр.wait_for_timeout(2500)
    стр.evaluate("() => { const б = document.getElementById('pricingErrorScreen'); if (б) б.style.display = 'none'; selectProjectOption(0); calc(); }")
    ждать(стр, 500)
    # Выгрузка в хранилище у заглушки подменяет снимки — на время пробы снимки
    # остаются теми, что легли на холст.
    стр.evaluate("() => { window.__выгрузка = uploadCanvasToStorage; }")

    # ── Чтение экспликации ──
    чтение = стр.evaluate("""() => { if (typeof площадьПарнойИзЛистов !== 'function') return null;
      const лист = строки => ({ текст: { items: строки.flatMap(([y, куски]) => куски.map(([x, т]) => ({ str: т, transform: [1, 0, 0, 1, x, y] }))) } });
      return {
        предпарная: площадьПарнойИзЛистов([лист([[500, [[10, '2'], [20, 'Предпарная'], [200, '4,2']]]])]),
        отделение: площадьПарнойИзЛистов([лист([[500, [[10, 'Парное отделение'], [200, '7,1 м²']]]])]),
        размер: площадьПарнойИзЛистов([лист([[500, [[10, 'Парная'], [80, '2500×2500']]]])]),
        подпись: площадьПарнойИзЛистов([лист([[300, [[10, 'Парная 5,6 м²'], [400, '1 Спальня 12,8']]]])]),
        вразбивку: площадьПарнойИзЛистов([лист([[466, [[10, '4'], [20, 'Парная']]], [467.4, [[200, '6,9']]]])]),
      }; }""")
    факт(чтение is not None and чтение["предпарная"] is None, f"предпарная не принята за парную: {чтение and чтение['предпарная']}")
    факт(чтение is not None and чтение["отделение"] == 7.1, f"«Парное отделение 7,1 м²» прочитано: {чтение and чтение['отделение']}")
    факт(чтение is not None and чтение["размер"] is None, f"размер «2500×2500» не принят за площадь: {чтение and чтение['размер']}")
    факт(чтение is not None and чтение["подпись"] == 5.6, f"подпись помещения на чертеже рядом с экспликацией прочитана: {чтение and чтение['подпись']}")
    факт(чтение is not None and чтение["вразбивку"] == 6.9, f"строка, куски которой разошлись по высоте на 1,4 пт, собрана: {чтение and чтение['вразбивку']}")

    # ── Каркас: планировка PDF, парная 6,9 м² ──
    прикрепить(стр, УЧЕБНЫЙ)
    снимки = стр.evaluate(ПЛОЩАДЬ)
    план = [х for х in снимки if х["вид"] == "план"]
    факт(len(план) == 1 and план[0]["парная"] == "6.9", f"каркас: на снимке планировки площадь парной 6,9: {снимки}")
    факт(all(not х["парная"] for х in снимки if х["вид"] != "план"), "у визуализации площади парной нет")
    д = стр.evaluate(ПУНКТЫ)
    р = пункт(д, "размер парного")
    факт(bool(р) and р["т"] == "Размер парного по планировке — 2500×3000 (6,9 м²), добавить увеличение парного" and р["эл"] == "lbl_s10" and р["р"] == "steam",
         f"каркас: базовое 2500×2000 при парной 6,9 м² — просит увеличение до 2500×3000 и ведёт к нему: {р}")
    факт(not пункт(д, "печь мала") and not д["в"], f"каркас: печи нет — про печь молчит, вопросов нет: {д}")
    отметить(стр, "s9", True); ждать(стр)
    д = стр.evaluate(ПУНКТЫ); р = пункт(д, "размер парного")
    факт(bool(р) and р["т"] == "Размер парного по планировке — 2500×3000 (6,9 м²), в опциях 2500×2500" and р["эл"] == "lbl_s9",
         f"каркас: увеличение до 2500×2500 при парной 6,9 м² — пункт называет оба размера и ведёт к опции: {р}")
    отметить(стр, "s13", True); ждать(стр)
    д = стр.evaluate(ПУНКТЫ); р = пункт(д, "размер парного")
    факт(bool(р) and р["эл"] == "lbl_s9 lbl_s13" and р["т"].endswith("в опциях 2500×2500"), f"каркас: две опции не того размера — один пункт к обеим строкам: {р}")
    отметить(стр, "s9", False); отметить(стр, "s13", False); отметить(стр, "s10", True); отметить(стр, "s24", True); ждать(стр)
    д = стр.evaluate(ПУНКТЫ)
    факт(not пункт(д, "размер парного"), f"каркас: увеличение до 2500×3000 — пункта нет, панно 1000×1000 размером парной не считается: {д['з']}")
    отметить(стр, "st16", True); ждать(стр)
    д = стр.evaluate(ПУНКТЫ); р = пункт(д, "печь мала")
    факт(bool(р) and р["т"] == "Печь мала для парной по планировке: нужна от 20,2 м³, выбрана до 18 м³" and р["эл"] == "lbl_st16" and р["р"] == "stove",
         f"каркас: печь до 18 м³ при парной 6,9 м² — мала, пункт ведёт к печи: {р}")
    отметить(стр, "st16", False); отметить(стр, "st17", True); ждать(стр)
    факт(not пункт(стр.evaluate(ПУНКТЫ), "печь мала"), "каркас: печь до 25 м³ — впору, пункта нет")
    стр.evaluate("() => { customOptions.windows = (customOptions.windows || []).concat([{ id: 'pan1', name: 'Учебное панорамное окно в парной', price: 0, checked: true }]); calc(); }"); ждать(стр)
    д = стр.evaluate(ПУНКТЫ); р = пункт(д, "печь мала")
    факт(bool(р) and "нужна от 25,2 м³, выбрана до 25 м³" in р["т"], f"каркас: с панорамным окном запас 10 м³ — печь до 25 м³ мала: {р}")
    стр.evaluate("() => { customOptions.windows = (customOptions.windows || []).filter(co => co.id !== 'pan1'); calc(); }"); ждать(стр)

    # Площадь живёт в пресете: сохранение, выгрузка, открытие.
    сост = стр.evaluate("() => collectState()")
    сохр = [х.get("steam") for х in сост.get("canvasImages", []) if х.get("kind") == "план"]
    факт(сохр == [6.9], f"площадь парной в снимке расчёта: {сохр}")
    выгр = стр.evaluate("""async (снимки) => { const б = _sbUser; _sbUser = б || { id: 'проба' };
      try { return await window.__выгрузка('проба', снимки.map(с => ({ ...с, src: 'https://example.invalid/' + (с.kind || 'x') + '.png' }))); }
      finally { _sbUser = б; } }""", сост.get("canvasImages", []))
    факт([х.get("steam") for х in выгр if х.get("kind") == "план"] == [6.9], f"выгрузка в хранилище несёт площадь: {выгр}")
    стр.evaluate(ОЧИСТИТЬ)
    стр.evaluate("async (с) => { await restoreCanvasFromUrls(с); calc(); }", [{**х, "url": х["src"]} for х in сост["canvasImages"]]); ждать(стр, 600)
    снимки = стр.evaluate(ПЛОЩАДЬ)
    факт([х["парная"] for х in снимки if х["вид"] == "план"] == ["6.9"], f"открытый расчёт: площадь снова на снимке: {снимки}")
    отметить(стр, "st17", False); отметить(стр, "st16", True); ждать(стр)
    факт(bool(пункт(стр.evaluate(ПУНКТЫ), "печь мала")), "открытый расчёт: печь до 18 м³ снова мала")

    # Вторая экспликация — таблицей: парная 6,2 м², впору 2500×2500.
    прикрепить(стр, ТАБЛИЦА)
    снимки = стр.evaluate(ПЛОЩАДЬ)
    факт([х["парная"] for х in снимки if х["вид"] == "план"] == ["6.2"], f"экспликация таблицей: парная 6,2: {снимки}")
    отметить(стр, "s10", False); отметить(стр, "s9", True); ждать(стр)
    д = стр.evaluate(ПУНКТЫ)
    факт(not пункт(д, "размер парного"), f"парная 6,2 м² и увеличение до 2500×2500 — пункта нет: {д['з']}")
    р = пункт(д, "печь мала")
    факт(bool(р) and "нужна от 18,6 м³, выбрана до 18 м³" in р["т"], f"парная 6,2 м²: печь до 18 м³ мала (13,6 + 5): {р}")

    # Планировка картинкой — площади нет, вопрос.
    прикрепить(стр, КАРТИНКА)
    стр.evaluate("() => { document.querySelectorAll('#imageCanvas .canvas-img-item').forEach(э => { э.dataset.kind = 'план'; }); calc(); }"); ждать(стр, 600)
    д = стр.evaluate(ПУНКТЫ)
    # У картинки нет и других сведений планировки — парная входит в общий
    # вопрос сверить проект с планировкой (check_plan_by_pdf.py).
    вопрос = "Сверить с планировкой габариты, этажность, террасу, размер парного отделения и печь"
    факт(д["в"] == [вопрос] and not д["з"], f"планировка картинкой: вопрос сверить вручную, замечаний нет: {д}")
    адрес = стр.evaluate("(в) => (проверкаПоЧекЛисту().адреса || {})[в]", вопрос)
    факт(bool(адрес) and адрес.get("эл") == "imageCanvasCard", f"вопрос ведёт к блоку изображений: {адрес}")
    стр.evaluate(ОЧИСТИТЬ); стр.evaluate("() => calc()"); ждать(стр)
    д = стр.evaluate(ПУНКТЫ)
    факт(not д["в"] and not д["з"], f"планировки нет — этих пунктов нет (просит добавить планировку другой пункт): {д}")

    # ── Брус ──
    стр.evaluate("async () => { await switchTech('glulam'); await new Promise(r => setTimeout(r, 600)); selectProjectOption(0); calc(); }")
    ждать(стр, 600)
    факт(стр.evaluate("() => currentTech") == "glulam", "расчёт бруса открыт")
    прикрепить(стр, УЧЕБНЫЙ)
    д = стр.evaluate(ПУНКТЫ)
    факт(not д["з"] and not д["в"], f"брус: парной нет — пунктов о ней нет: {д}")
    отметить(стр, "kb_s22", True); ждать(стр)
    д = стр.evaluate(ПУНКТЫ); р = пункт(д, "размер парного")
    факт(bool(р) and р["т"] == "Выбрать размер парного по планировке — 2500×3000 (6,9 м²)" and р["эл"] == "lbl_kb_s2",
         f"брус: парная без размера — просит выбрать 2500×3000 и ведёт к опции этого размера: {р}")
    отметить(стр, "kb_s1", True); ждать(стр)
    д = стр.evaluate(ПУНКТЫ); р = пункт(д, "размер парного")
    факт(bool(р) and р["т"] == "Размер парного по планировке — 2500×3000 (6,9 м²), в опциях 2500×2500" and р["эл"] == "lbl_kb_s1",
         f"брус: сборка 2500×2500 при парной 6,9 м² — пункт к опции: {р}")
    отметить(стр, "kb_s1", False); отметить(стр, "kb_s2", True); ждать(стр)
    факт(not пункт(стр.evaluate(ПУНКТЫ), "размер парного"), "брус: сборка 2500×3000 — пункта нет")
    отметить(стр, "kb_st21", True); ждать(стр)
    р = пункт(стр.evaluate(ПУНКТЫ), "печь мала")
    факт(bool(р) and р["эл"] == "lbl_kb_st21" and "выбрана до 18 м³" in р["т"], f"брус: печь до 18 м³ мала: {р}")
    отметить(стр, "kb_st21", False); отметить(стр, "kb_st42", True); ждать(стр)
    факт(not пункт(стр.evaluate(ПУНКТЫ), "печь мала"), "брус: печь «до 24 кубов» прочитана и впору")
    факт(not ошибки, f"ошибок страницы нет: {ошибки[:2]}")
    бр.close()
с.shutdown()

for т in ОТЧЁТ:
    print("    ок  " + т)
if НАХОДКИ:
    print("НАХОДКИ:")
    for т in НАХОДКИ:
        print("  ✗ " + т)
    raise SystemExit(1)
print("Чисто: размер парного и печь сверяются с площадью парной по планировке, у каркаса и бруса; площадь живёт в пресете.")
