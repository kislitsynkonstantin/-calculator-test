#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ТЗ на строительство: PDF в чат после «Подписан» и кнопкой администратора.

Константин 18.10.2026: «Вот ТЗ проекта, которое делаем по спецификации.
После того, как написали, что договор подписан, формировать сразу в PDF и
скидывать ТЗ… Состав помещений заполняй из планировки. Все делаем в коде»;
по макету tz-template-v1: «ТЗ супер… Визуально сделай выделение подраздела.
Подписи убери… в конце [«Сводки»] добавь кнопку «Загрузить ТЗ в чат», только
для администратора… И внедряй в код».

Проба держит, на заглушке базы и с библиотеками PDF из пакетов npm:
  • экспликация планировки читается в помещения: номер, название, площадь;
    терраса в отделку не идёт;
  • в ТЗ — шапка (заказчик, договор, строение, проект), разделы расчёта с
    договором, строки «Не входит», внутренняя отделка по помещениям
    планировки: у парной — строки парного и печи, у санузла — свои; подраздел
    помещения залит цветом; подписей сторон нет;
  • без экспликации — помещения расчёта и оговорка об этом;
  • «Загрузить ТЗ в чат» в конце «Сводки» — только у администратора; нажатие
    кладёт в чат PDF «ТЗ_код_дата.pdf», A4, страницы не пустые;
  • «Подписан» кладёт в чат и заключение, и ТЗ.

    python3 check_tz_chat.py
"""
import base64, os, pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).parent))
import check_preset_chip as м
import check_preset_approval as па
import check_approval_report as з
from playwright.sync_api import sync_playwright

СНИМКИ = pathlib.Path(os.environ.get("BM_SHOTS") or "/tmp")
НАХОДКИ = []


def плохо(т):
    НАХОДКИ.append(т)


ЛИСТ = """(строки) => ({ текст: { items: строки.flatMap(([y, куски]) => куски.map(([x, т]) => ({ str: т, transform: [1, 0, 0, 1, x, y] }))) } })"""
ЭКСПЛИКАЦИЯ = [[800, [[10, "План 1-го этажа"]]], [700, [[10, "Экспликация помещений"]]],
               [690, [[10, "1"], [30, "Тамбур"], [200, "3,2"]]], [680, [[10, "3"], [30, "С/У"], [200, "3,0"]]],
               [670, [[10, "7"], [30, "Парная"], [200, "6,2"]]], [660, [[10, "8"], [30, "Комната отдыха"], [200, "9,9"]]],
               [650, [[10, "5"], [30, "Терраса"], [200, "14,0"]]]]


def ждатьPdf(стр, имя, сколько=60):
    for _ in range(сколько):
        стр.wait_for_timeout(500)
        if стр.evaluate("(и) => window.__PDF.some(п => п.имя.startsWith(и))", имя):
            return True
    return False


def прогон(бр, порт, ш, в, полный):
    н = f"[{ш}]"
    стр, ошибки = з.начать(бр, порт, ш, в)
    стр.on("console", lambda с: ошибки.append(с.text) if "[ТЗ]" in с.text else None)
    код = стр.evaluate("() => { const p = loadAllPresets()[activePresetId]; return p && (p.shortCode || p.sharedId); }")
    if not код:
        плохо(f"{н} пресету не выдан код"); стр.close(); return
    стр.evaluate(па.ДАННЫЕ, код)
    стр.evaluate(з.ХРАНИЛИЩЕ)

    # ── экспликация → помещения ──
    св = стр.evaluate("(с) => { const лист = (" + ЛИСТ + "); return сведенияПланировки([лист(с)]); }", ЭКСПЛИКАЦИЯ)
    пом = [(п["н"], п["имя"], п["пл"]) for п in (св or {}).get("помещения", [])]
    if ("7", "Парная", "6,2") not in пом or ("3", "С/У", "3,0") not in пом or len(пом) != 5:
        плохо(f"{н} экспликация прочитана не так: {пом}")

    if not стр.evaluate("() => typeof данныеТЗ === 'function' && typeof htmlТЗ === 'function'"):
        плохо(f"{н} в калькуляторе нет сборки ТЗ"); стр.close(); return
    if полный:
        # ── без экспликации ──
        д0 = стр.evaluate("() => { const д = данныеТЗ(null); return { изПлана: д.отделка.изПлана, комнаты: д.отделка.комнаты.map(к => к.имя), html: htmlТЗ(д) }; }")
        if д0["изПлана"] or "Жилая зона" not in д0["комнаты"] or "в планировке не нашлось экспликации" not in д0["html"]:
            плохо(f"{н} без экспликации: {д0['комнаты']}, изПлана {д0['изПлана']}")
        # ── с экспликацией на снимке планировки ──
        стр.evaluate("""async (п) => { canvasAddImage(п); await new Promise(r => setTimeout(r, 400));
          const э = document.getElementById(canvasItems[canvasItems.length - 1]); э.dataset.kind = 'план'; }""", з.ПЛАН if hasattr(з, "ПЛАН") else "/scratchpad/probes/образцы_приложения2/планировка.png")
        стр.evaluate("(св) => { const э = document.getElementById(canvasItems[canvasItems.length - 1]); э.dataset.plan = JSON.stringify(св); }", св)
        д = стр.evaluate("""() => { const д = данныеТЗ(null), h = htmlТЗ(д);
          return { изПлана: д.отделка.изПлана, комнаты: д.отделка.комнаты.map(к => ({ имя: к.имя, н: к.н, строк: к.строки.length, п: к.строки.map(с => с.п) })),
            разделы: д.разделы.map(р => ({ имя: р.имя, договор: р.договор, нет: р.строки.filter(с => с.вид === 'нет').length, строк: р.строки.length })),
            шапка: д.шапка.map(с => с.к), html: h,
            текст: h.replace(/<style>[\\s\\S]*?<\\/style>/, '').replace(/<[^>]+>/g, ' ').replace(/\\s+/g, ' ') }; }""")
        имена = [к["имя"] for к in д["комнаты"]]
        if not д["изПлана"] or имена != ["Тамбур", "С/У", "Парная", "Комната отдыха"]:
            плохо(f"{н} помещения ТЗ не из экспликации или с террасой: {имена}")
        парная = next((к for к in д["комнаты"] if к["имя"] == "Парная"), None)
        if not парная or парная["строк"] < 3:
            плохо(f"{н} у парной нет строк парного и печи: {парная}")
        for что in ["Заказчик", "Договор", "Строение", "Проект"]:
            if что not in д["шапка"]:
                плохо(f"{н} в шапке ТЗ нет «{что}»")
        разделы = {р["имя"]: р for р in д["разделы"]}
        for что in ["Фундамент", "Конструктив", "Кровля", "Окна и двери"]:
            if что not in разделы or not разделы[что]["договор"]:
                плохо(f"{н} раздела «{что}» нет или у него не указан договор: {разделы.get(что)}")
        if not any(р["нет"] for р in д["разделы"]):
            плохо(f"{н} ни одной строки «Не входит»")
        if "ПОДРЯДЧИК" in д["текст"].upper().replace("ПРИЛОЖЕНИЕ К ДОГОВОРУ ПОДРЯДА", "") or "sign" in д["html"]:
            плохо(f"{н} в ТЗ остались подписи сторон")
        if 'class="zk-b tz-room"' not in д["html"] or "background:var(--tint)" not in д["html"]:
            плохо(f"{н} подраздел помещения не выделен заливкой")
        if "Техническое задание на строительство" not in д["текст"]:
            плохо(f"{н} в ТЗ нет заголовка")

    # ── кнопка «Загрузить ТЗ в чат» ──
    стр.locator("#presetChip .pc-body").click(); стр.wait_for_timeout(300)
    for р, ждём in [("manager", False), ("editor", False), ("admin", True)]:
        па.роль(стр, р)
        стр.evaluate("() => { _пкВкладка = 's'; заполнитьКарточкуЗначка(); }"); стр.wait_for_timeout(500)
        есть = стр.locator('#presetChipCard [data-act="tz-chat"]').count() > 0
        if есть != ждём:
            плохо(f"{н} {р}: кнопка «Загрузить ТЗ в чат» {'есть' if есть else 'нет'}")
    кн = стр.locator('#presetChipCard [data-act="tz-chat"]')
    if кн.count():
        кн.scroll_into_view_if_needed()
        стр.screenshot(path=str(СНИМКИ / f"tz-button-{ш}.png"))
        кн.click()
        if not ждатьPdf(стр, f"ТЗ_{код}_"):
            плохо(f"{н} «Загрузить ТЗ в чат» не положила PDF в чат: {ошибки[:3]}")
        elif полный:
            данные = base64.b64decode(стр.evaluate("(и) => window.__PDF.find(п => п.имя.startsWith(и)).данные", f"ТЗ_{код}_"))
            картинки, инфо = з.страницыPdf(данные, н)
            if "595.28 x 841.89" not in инфо and "595 x 842" not in инфо:
                плохо(f"{н} ТЗ не A4: {инфо!r}")
            if not картинки:
                плохо(f"{н} в PDF ТЗ нет страниц")
            import subprocess, tempfile
            ф = pathlib.Path(tempfile.mkdtemp(prefix="tz-")) / "t.pdf"; ф.write_bytes(данные)
            subprocess.run(["pdftoppm", "-r", "80", "-png", str(ф), str(СНИМКИ / "tz-pdf")], check=True)

    # ── «Подписан» шлёт и заключение, и ТЗ ──
    стр.evaluate("() => { window.__PDF.length = 0; }")
    стр.evaluate("""() => { window.__проверкаБыла = проверкаПоЧекЛисту;
      window.проверкаПоЧекЛисту = function () { const п = window.__проверкаБыла.apply(this, arguments); п.замечания = п.замечания.filter(з => !з.стоп); return п; }; }""")
    па.роль(стр, "manager")
    па.открытьПроверку(стр)
    па.нажать(стр, "ap-send"); стр.wait_for_timeout(600)
    стр.evaluate("() => { window.__ТАБЛИЦЫ.preset_approvals.forEach(с => { с.price_by = 'u-ред'; с.price_name = 'Ольга Проверкина'; с.price_at = new Date().toISOString(); с.price_print = с.sent_print; }); _согласование.когда = 0; }")
    па.роль(стр, "specialist")
    стр.evaluate("() => решитьСогласование('approved', 'check')"); стр.wait_for_timeout(1500)
    па.роль(стр, "manager")
    па.открытьПроверку(стр)
    па.нажать(стр, "ap-sign")
    if not ждатьPdf(стр, f"ТЗ_{код}_", 90):
        плохо(f"{н} после «Подписан» ТЗ не пришло в чат: {стр.evaluate('() => window.__PDF.map(п => п.имя)')}")
    if not стр.evaluate("(и) => window.__PDF.some(п => п.имя.startsWith(и))", f"Заключение_{код}_"):
        плохо(f"{н} после «Подписан» нет заключения")
    if ошибки:
        плохо(f"{н} ошибки страницы: {ошибки[:3]}")
    стр.close()


def главная():
    if not з.JSPDF.exists() or not з.H2C.exists():
        print("нет библиотек PDF"); sys.exit(2)
    с, порт = м.сервер()
    try:
        with sync_playwright() as п:
            бр = п.chromium.launch(executable_path=м.хром())
            try:
                прогон(бр, порт, 1440, 900, True)
                прогон(бр, порт, 390, 844, False)
            finally:
                бр.close()
    finally:
        с.shutdown()
    if НАХОДКИ:
        print("НАХОДКИ:")
        for т in НАХОДКИ:
            print(" —", т)
        sys.exit(1)
    print("Чисто: экспликация читается в помещения, ТЗ — шапка, разделы с договором, «Не входит», отделка по помещениям с выделенным "
          "подразделом, без подписей; без экспликации — помещения расчёта; кнопка «Загрузить ТЗ в чат» только у администратора, "
          "PDF A4 в чате; «Подписан» шлёт заключение и ТЗ.")


if __name__ == "__main__":
    главная()
