#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Выгрузка парной в Excel: живые формулы считают так же, как калькулятор.

Константин 27.10.2026: «По двойному нажатию на версию также должна выходить
таблица с расчётами по парной. Сам разложи по вкладкам, как в каркасе и брусе.
Чтобы были понятны формулы и можно было если что поменять».

Проба держит:
  • двойной щелчок по версии у парной выгружает книгу из шести листов —
    «Параметры», три раздела, «Печи», «Итог» — с именованными ячейками;
    менеджеру выгрузка не отдаётся;
  • в книге формулы, а не числа: таблица, пересчитанная заново (LibreOffice,
    без сохранённых значений), даёт те же суммы разделов и итог, что экран
    калькулятора, — на расчёте книги (2 313 757 ₽) и на расчёте со всем сразу:
    подарок, своя позиция, другая печь, сруб, бригада руками, доставка 80 км,
    снятая база логистики;
  • правка в таблице пересчитывает её так же, как калькулятор: длина 3,6 м,
    каркасный дом и другая модель печи, вписанные в «Параметры», дают тот же
    итог, что калькулятор с теми же значениями;
  • строка «Расхождение с калькулятором» на «Итоге» — ноль.

Библиотеку выгрузки (SheetJS 0.18.5) калькулятор берёт с cdnjs, которого из
контейнера не видно: проба отдаёт её сама, скачав пакет из реестра npm.

    python3 check_steam_excel.py
"""
import io, os, pathlib, shutil, subprocess, sys, tarfile, tempfile, urllib.request

sys.path.insert(0, str(pathlib.Path(__file__).parent))
import check_preset_chip as м
import check_steam_tab as п
import openpyxl
from playwright.sync_api import sync_playwright

НАХОДКИ = []
КЭШ = pathlib.Path.home() / '.cache' / 'bm_probes' / 'xlsx-0.18.5.full.min.js'
ЛИСТЫ = ['Параметры', 'Парное отделение', 'Печь и комплектующие', 'Дополнительные опции', 'Печи', 'Итог']


def плохо(т):
    НАХОДКИ.append(т)


def библиотека():
    if not КЭШ.exists():
        КЭШ.parent.mkdir(parents=True, exist_ok=True)
        данные = urllib.request.urlopen('https://registry.npmjs.org/xlsx/-/xlsx-0.18.5.tgz', timeout=60).read()
        with tarfile.open(fileobj=io.BytesIO(данные)) as тар:
            КЭШ.write_bytes(тар.extractfile('package/dist/xlsx.full.min.js').read())
    return КЭШ.read_text(encoding='utf-8')


def выгрузить(стр, куда):
    with стр.expect_download(timeout=20000) as з:
        стр.evaluate("() => { window._sbProfile = Object.assign({}, window._sbProfile, { role: 'admin' }); downloadDbExcel(); }")
    з.value.save_as(куда)
    return куда


def пересчитать(файл, правки=None):
    """Книга без сохранённых значений, пересчитанная LibreOffice заново."""
    книга = openpyxl.load_workbook(файл)
    for (лист, адрес), значение in (правки or {}).items():
        книга[лист][адрес] = значение
    папка = pathlib.Path(tempfile.mkdtemp(prefix='steam_xlsx_'))
    голый = папка / 'голый.xlsx'
    книга.save(голый)
    профиль = папка / 'профиль'
    subprocess.run(['soffice', f'-env:UserInstallation=file://{профиль}', '--headless', '--calc',
                    '--convert-to', 'xlsx', '--outdir', str(папка / 'вых'), str(голый)],
                   check=True, capture_output=True, timeout=180)
    итог = openpyxl.load_workbook(папка / 'вых' / 'голый.xlsx', data_only=True)
    shutil.rmtree(папка, ignore_errors=True)
    return итог


def строка(книга, лист, подпись, столбец_подписи='A', столбец='B'):
    л = книга[лист]
    for r in range(1, л.max_row + 1):
        if л[f'{столбец_подписи}{r}'].value == подпись:
            return л[f'{столбец}{r}'].value
    return None


def итоги_таблицы(книга):
    return {
        'разделы': [round(строка(книга, л, 'Итого по разделу', 'B', 'J') or 0) for л in ЛИСТЫ[1:4]],
        'итог': round(строка(книга, 'Итог', 'Общая стоимость') or 0),
        'расхождение': строка(книга, 'Итог', 'Расхождение с калькулятором'),
    }


def адрес_параметра(книга, имя):
    л = книга['Параметры']
    for r in range(1, л.max_row + 1):
        if л[f'D{r}'].value == имя:
            return f'B{r}'
    raise KeyError(имя)


# Суммы разделов — из расчёта, а не с экрана: снятая база видна на экране
# бледной для сверки, а в сумму идёт нулём.
СУММЫ = "() => ({ разделы: ['par_st', 'par_pech', 'par_log'].map(к => Math.round(_secTotalsCache[к])), итог: Math.round(_currentTotal) })"


def сверить(стр, файл, что):
    ч = стр.evaluate(СУММЫ)
    т = итоги_таблицы(пересчитать(файл))
    if т['разделы'] != ч['разделы'] or т['итог'] != ч['итог']:
        плохо(f"{что}: таблица после пересчёта — разделы {т['разделы']}, итог {т['итог']}; "
              f"калькулятор — {ч['разделы']}, {ч['итог']}")
    if т['расхождение'] != 0:
        плохо(f"{что}: «Расхождение с калькулятором» после пересчёта — {т['расхождение']}")
    return ч


def main():
    lib = библиотека()
    с, порт = м.сервер()
    папка = pathlib.Path(tempfile.mkdtemp(prefix='steam_excel_'))
    try:
        with sync_playwright() as pw:
            бр = pw.chromium.launch(executable_path=м.хром())
            стр, ош = п.открыть(бр, порт, 1440)
            стр.route("**/cdnjs.cloudflare.com/ajax/libs/xlsx/**",
                      lambda r: r.fulfill(status=200, content_type="application/javascript", body=lib))
            п.в_парную(стр)

            # Менеджеру выгрузка не отдаётся.
            тосты = стр.evaluate("""async () => { const т = []; const было = window.showToast; window.showToast = с => т.push(String(с));
              window._sbProfile = { role: 'manager' }; downloadDbExcel(); await new Promise(r => setTimeout(r, 300));
              window.showToast = было; return т; }""")
            if not any('администратор' in т for т in тосты):
                плохо(f"выгрузка у менеджера: сообщения {тосты} — ждали отказ словами")

            # 1. Расчёт книги: двенадцать опций макета.
            стр.evaluate("ид => ид.forEach(к => document.getElementById('lbl_par_' + к).click())", п.МАКЕТ)
            ф1 = выгрузить(стр, папка / 'книга.xlsx')
            книга = openpyxl.load_workbook(ф1)
            if книга.sheetnames != ЛИСТЫ:
                плохо(f"листы выгрузки: {книга.sheetnames}")
            имена = set(книга.defined_names.keys()) if hasattr(книга.defined_names, 'keys') else {д.name for д in книга.defined_names.definedName}
            for нужно in ('Длина', 'Площадь_отделки', 'Дни_бригады', 'Модель_печи', 'Каркас_нужен', 'Итог_par_st'):
                if нужно not in имена:
                    плохо(f"нет именованной ячейки «{нужно}»")
            формул = {л: sum(1 for ряд in книга[л].iter_rows() for я in ряд if isinstance(я.value, str) and я.value.startswith('='))
                      for л in ЛИСТЫ}
            if формул['Парное отделение'] < 40 or формул['Печи'] < 90 or формул['Параметры'] < 7:
                плохо(f"формул в листах мало — выгружены числа, а не расчёт: {формул}")
            ч1 = сверить(стр, ф1, 'расчёт книги')
            if ч1['итог'] != 2313757:
                плохо(f"расчёт книги в калькуляторе: {ч1['итог']} — ждали 2 313 757 ₽")
            сохр = итоги_таблицы(openpyxl.load_workbook(ф1, data_only=True))
            if сохр['итог'] != ч1['итог'] or сохр['расхождение'] != 0:
                плохо(f"сохранённые значения в файле: итог {сохр['итог']}, расхождение {сохр['расхождение']}")

            # Объём для печи (Анатолий, 27.10.2026: парная + 20 %, окно — 3 м³
            # за каждый начатый м²) и столбец «Подходит» листа «Печи» — формулами,
            # как в калькуляторе; снятое в таблице окно объём не прибавляет.
            def подходят(кн):
                л = кн['Печи']
                return [л[f'A{r}'].value for r in range(5, л.max_row + 1) if л[f'I{r}'].value == 'да']
            ждём = стр.evaluate("() => ({ объём: парГеом().печь, да: ПАР_ПЕЧИ.filter(м => парПечьПодходит(м, парГеом())).map(м => м.имя) })")
            пк = пересчитать(ф1)
            if строка(пк, 'Параметры', 'Объём для печи') != ждём['объём'] or подходят(пк) != ждём['да'] or ждём['объём'] != 36.1:
                плохо(f"объём для печи в таблице {строка(пк, 'Параметры', 'Объём для печи')}, подходят {подходят(пк)[:4]}…; "
                      f"калькулятор — {ждём['объём']}, {ждём['да'][:4]}… (ждали 36,1 м³: 27,6 × 1,2 + 3 за окно 1 м²)")
            лист_окна, ряд_окна = next((л, r) for л in ЛИСТЫ[1:4] for r in range(1, книга[л].max_row + 1) if книга[л][f'A{r}'].value == 'okno')
            без_окна = пересчитать(ф1, {(лист_окна, f'D{ряд_окна}'): 0})
            if строка(без_окна, 'Параметры', 'Объём для печи') != 33.1:
                плохо(f"окно снято в таблице: объём для печи {строка(без_окна, 'Параметры', 'Объём для печи')} — ждали 33,1 м³")

            # 2. Правка в таблице считает как калькулятор.
            правки = {('Параметры', адрес_параметра(книга, 'Длина')): 3.6,
                      ('Параметры', адрес_параметра(книга, 'Тип_помещения')): 'Каркасный дом',
                      ('Параметры', адрес_параметра(книга, 'Модель_печи')): 'ГРОМ 30 (П2), печь-комплект'}
            т = итоги_таблицы(пересчитать(ф1, правки))
            стр.evaluate("() => { ПАР.L = 3.6; ПАР.комн = 'frame'; ПАР.печь = 'grom-30-p2-pech-komplekt'; calc(); }")
            ч = стр.evaluate(СУММЫ)
            if т['итог'] != ч['итог'] or т['разделы'] != ч['разделы']:
                плохо(f"правка в таблице (3,6 м, каркасный дом, ГРОМ 30): таблица {т['разделы']} / {т['итог']}, "
                      f"калькулятор {ч['разделы']} / {ч['итог']}")
            if т['расхождение'] == 0:
                плохо("после правки в таблице «Расхождение с калькулятором» осталось нулём — сверка ничего не сверяет")

            # 3. Всё сразу: подарок, своя позиция, другая печь, сруб, бригада руками,
            # доставка, снятая база логистики.
            стр.evaluate("""() => { ПАР.L = 3; ПАР.комн = 'log'; парнаяПечь('grom-40-p2-pech-komplekt');
              ПАР.brig = 25; ПАР.dost = 80; ПАР.podsv = 3; ПАР.panno = 1.4; calc(); }""")
            стр.click('#gift_par_spinki', force=True)
            стр.click('#addBtn_par_st')
            стр.fill('#addName_par_st', 'Полка-лежак из кедра')
            стр.fill('#addPrice_par_st', '45000')
            стр.click('#addForm_par_st .btn-confirm-add')
            стр.evaluate("() => парнаяБаза('par_log')")
            ф3 = выгрузить(стр, папка / 'всё.xlsx')
            сверить(стр, ф3, 'расчёт со всем сразу')
            if ош:
                плохо(f"ошибки страницы: {ош[:3]}")
            стр.close()
            бр.close()
    finally:
        с.shutdown()
        shutil.rmtree(папка, ignore_errors=True)
    if НАХОДКИ:
        print("НАХОДКИ:")
        for н in НАХОДКИ:
            print("  ✗", н)
        sys.exit(1)
    print("Чисто: выгрузка парной — шесть листов с именованными ячейками и формулами; пересчитанная заново, "
          "таблица даёт те же разделы и итог, что калькулятор (2 313 757 ₽ и расчёт со всем сразу), правка "
          "длины, типа помещения и печи в таблице считает так же, сверка с калькулятором — ноль; менеджеру отказ.")


if __name__ == "__main__":
    main()
