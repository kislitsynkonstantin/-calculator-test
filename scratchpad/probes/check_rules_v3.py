НАХОДКИ = []

ИЗВЛЕЧЬ = r"""([парная, печь]) => { const д = new DOMParser().parseFromString(buildContractHtmlKar({ kind: 'rules', rulesSteam: парная, rulesStove: печь, rulesNums: ['11112222-КАР', '11112222-ОТД'], contractDate: '17.10.2026' }), 'text/html');
  const т = э => э.textContent.replace(/\s+/g, ' ').trim(); const out = [];
  for (const э of д.querySelectorAll('h2.section, p.clause')) {
    if (э.closest('.keep') && !э.matches('h2')) continue;
    if (э.matches('h2')) out.push(['§', т(э), false]);
    else { const н = э.querySelector('.clause-num'); out.push([н ? т(н) : '…', н ? т(э).slice(т(н).length).trim() : т(э), !!э.querySelector('b')]); }
  }
  return { ряды: out, версия: ВЕРСИИ_ДОКУМЕНТОВ.rules }; }"""

РАЗДЕЛЫ = {
    True: ["1.Общие положения", "2.Ввод в эксплуатацию", "3.Эксплуатация бани", "4.Парное отделение и печь",
           "5.Гарантийный случай", "6.Подписание", "7.Адреса и реквизиты"],
    False: ["1.Общие положения", "2.Ввод в эксплуатацию", "3.Эксплуатация Строения", "4.Гарантийный случай",
            "5.Подписание", "6.Адреса и реквизиты"],
}
НЕДОПУСТИМОЕ = [
    ("суд по месту нахождения Подрядчика", r"по месту нахождения Подрядчика"),
    ("«нарушение хотя бы одного пункта»", r"хотя бы одного"),
    ("«полного или частичного отказа» от гарантии", r"полного или частичного"),
    ("благодарность за покупку", r"Благодарим"),
    ("«неукоснительно»", r"неукоснительно"),
]
ЧИСЛА_ВСЕМ = [("проветривание 2 часа", r"не меньше 2 часов"), ("зимой +12 °C", r"\+12 °C"), ("снег 50 см", r"50 см"), ("зазор 30 см", r"30 см")]


def проверить(имя, парная, печь, р):
    ряды = р["ряды"]
    if р["версия"] != "3.0":
        НАХОДКИ.append(f"версия правил {р['версия']}, ждали 3.0")
    разделы = [т for н, т, _ in ряды if н == "§"]
    if разделы != РАЗДЕЛЫ[парная]:
        НАХОДКИ.append(f"[{имя}] разделы: {разделы}")
    пункты = {н.rstrip("."): (т, ж) for н, т, ж in ряды if re.match(r"^\d+\.\d+\.$", н)}
    весь = " ".join(т for н, т, _ in ряды if н != "§")
    # Номера подряд.
    раздел, ждём = None, 1
    for н, т, _ in ряды:
        if н == "§":
            раздел, ждём = int(re.match(r"\d+", т).group()), 1
        elif re.match(r"^\d+\.\d+\.$", н):
            а, б = map(int, н.rstrip(".").split("."))
            if а != раздел or б != ждём:
                НАХОДКИ.append(f"[{имя}] номер {н} не по порядку: ждали {раздел}.{ждём}")
            ждём = б + 1
    for что, ш in НЕДОПУСТИМОЕ:
        if re.search(ш, весь):
            НАХОДКИ.append(f"[{имя}] осталось недопустимое или вода: {что}")
    т14 = пункты.get("1.4", ("", False))[0]
    if "п. 4 ст. 29" not in т14 or "ст. 755 ГК РФ" not in т14:
        НАХОДКИ.append(f"[{имя}] в 1.4 нет опоры на закон: «{т14[:120]}»")
    if not re.search(r"в порядке, установленном Договором", весь):
        НАХОДКИ.append(f"[{имя}] споры не отданы договору")
    т31, ж31 = пункты.get("3.1", ("", False))
    if not ж31 or "гарантией не покрываются" not in т31:
        НАХОДКИ.append(f"[{имя}] раздел 3 не открывается последствием жирным: «{т31[:100]}», жирный {ж31}")
    if парная:
        т41, ж41 = пункты.get("4.1", ("", False))
        if not ж41 or not re.search(r"гарантия Подрядчика на установку печи[^.]*не действует", т41):
            НАХОДКИ.append(f"[{имя}] раздел 4 не открывается последствием для печи жирным: «{т41[:120]}», жирный {ж41}")
    for что, ш in ЧИСЛА_ВСЕМ + ([("90 °C у верхнего полка", r"90 °C по термометру на уровне верхнего полка")] if парная else []) \
            + ([("чистка дымохода раз в 2 месяца", r"Дымоход чистится от сажи не реже раза в 2 месяца"), ("следы перекала", r"Следы перекала")] if печь in ("wood", "both") else []):
        if not re.search(ш, весь):
            НАХОДКИ.append(f"[{имя}] нет проверяемого требования: {что}")
    if парная:
        дров, элек = "Дровяная печь" in весь, "Электрическая печь" in весь
        if (печь == "wood" and (not дров or элек)) or (печь == "electric" and (дров or not элек)) or (печь == "both" and not (дров and элек)):
            НАХОДКИ.append(f"[{имя}] печь не по виду: дровяная {дров}, электрическая {элек}")
        # Дрова у стен (3.5) — о строении, а не о печи: смотрим всё, кроме раздела 3.
        безр3 = " ".join(т for н, (т, _) in пункты.items() if not н.startswith("3."))
        if печь == "electric" and re.search(r"дымоход|дров|(?<![а-яё])бак", безр3, re.I):
            НАХОДКИ.append(f"[{имя}] у электрической печи — дымоход, дрова или бак: {re.findall(r'дымоход|дров|бак[а-я]*', безр3, re.I)[:4]}")
        if печь == "electric" and re.search(r"(?<![а-яё])бака", пункты.get("3.3", ("", 0))[0]):
            НАХОДКИ.append(f"[{имя}] зимой у электрической печи сливают воду из бака: «{пункты['3.3'][0][:90]}»")
    else:
        лишнее = re.findall(r"печ[ьиеюя]|дымоход\S*|парн\S*|(?<![а-яё])[Бб]ан(?:я|и|е|ю|ей)(?![а-яё])|(?<![а-яё])бак[а-я]*", весь)
        if лишнее:
            НАХОДКИ.append(f"[{имя}] без парной — о печи, парной или бане: {лишнее[:5]}")
    длинные = [(н, len(т)) for н, (т, _) in пункты.items() if len(т) > 400]
    if длинные:
        НАХОДКИ.append(f"[{имя}] пункты длиннее 400 знаков: {длинные}")
    всего = sum(len(т) for т, _ in пункты.values())
    if всего > 7500:
        НАХОДКИ.append(f"[{имя}] текст {всего} знаков — длиннее 7 500")
    return len(пункты), всего


РАСЧЁТ = r"""async (печь) => { const ДР = ДРОВЯНЫЕ_ПЕЧИ, ЭЛ = ['st3', 'st4', 'st5', 'st35'];
  OPTIONS.filter(o => o.section === 'stove').forEach(o => { checkedOptions[o.id] = false; });
  try { (getCustomOpts('stove') || []).forEach(co => { co.checked = false; }); } catch (e) {}
  const ид = и => idВРасчёте(и);
  if (печь === 'wood') checkedOptions[ид(ДР[0])] = true;
  if (печь === 'electric') checkedOptions[ид(ЭЛ[0])] = true;
  if (печь === 'нет') OPTIONS.filter(o => o.section === 'steam').forEach(o => { checkedOptions[o.id] = false; });
  calc();
  const т = new DOMParser().parseFromString(buildRulesHtml(getContractVarsKar(2)), 'text/html').body.textContent;
  return { дров: т.includes('Дровяная печь'), элек: т.includes('Электрическая печь'), раздел4: т.includes('Парное отделение и печь'), заголовок: т.includes('с парным отделением (бани)') }; }"""


def главная():
    с, порт = м.сервер()
    итог = {}
    try:
        with sync_playwright() as п:
            бр = п.chromium.launch(executable_path=м.хром(), args=["--no-sandbox"])
            к, стр, ош = о.начать(бр, порт, 1440, "admin")
            for имя, парная, печь in (("дровяная", True, "wood"), ("электрическая", True, "electric"), ("обе", True, "both"), ("без парной", False, "")):
                итог[имя] = проверить(имя, парная, печь, стр.evaluate(ИЗВЛЕЧЬ, [парная, печь]))
            ждём = {"wood": (True, False, True), "electric": (False, True, True), "": (True, True, True), "нет": (False, False, False)}
            for печь, (дров, элек, р4) in ждём.items():
                в = стр.evaluate(РАСЧЁТ, печь)
                if (в["дров"], в["элек"], в["раздел4"]) != (дров, элек, р4) or в["заголовок"] != р4:
                    НАХОДКИ.append(f"[расчёт: {печь or 'парная без печи'}] правила: дровяная {в['дров']}, электрическая {в['элек']}, "
                                   f"раздел печи {в['раздел4']}, заголовок с парной {в['заголовок']}; ждали {дров}, {элек}, {р4}")
            for е in [е for е in ош if "supabase.co" not in е][:3]:
                НАХОДКИ.append(f"ошибка страницы: {е[:160]}")
            к.close(); бр.close()
    finally:
        с.shutdown()
    if НАХОДКИ:
        print("НАХОДКИ:")
        for н in НАХОДКИ:
            print("  ✗", н)
        sys.exit(1)
    print("Чисто: правила 3.0 — " + "; ".join(f"{и}: {н} пунктов, {з} знаков" for и, (н, з) in итог.items())
          + ". Разделы и номера по виду, последствия для гарантии жирным во главе разделов, опора на закон, недопустимого и воды нет, "
          "требования с числами, печь по виду и по расчёту.")


if __name__ == "__main__":
    главная()
