"""Правила эксплуатации версии 3.0 — текст, который защищает компанию.

Константин 17.10.2026: «перепиши правила эксплуатации, чтобы максимально
защитить компанию. Если есть парная — добавляем про печь. Если нет парной, то
просто для каркасного строения правила пропиши. К этой задаче подойди
основательно. Но воды быть много не должно, самую суть. Особенно пункты по
эксплуатации, в случае нарушения которых снимаем с гарантии печь и баню в
целом».

Проба собирает правила в четырёх видах — с дровяной печью, с электрической,
с обеими (печь по расчёту не понять) и без парной — и держит:
  • версия 3.0;
  • разделы по виду: с парной — шесть и реквизиты седьмым, без — пять и
    реквизиты шестым; номера в каждом разделе подряд с единицы;
  • раздел «Эксплуатация …» и раздел «Парное отделение и печь» открываются
    последствием для гарантии, выделенным жирным; у печи — гарантия
    Подрядчика на установку не действует;
  • опора на закон: п. 4 ст. 29 Закона о защите прав потребителей и п. 2
    ст. 755 ГК РФ; споры — по договору;
  • нет недопустимого и воды прежних правил: суда по месту Подрядчика,
    «нарушение хотя бы одного пункта», «полного или частичного отказа»,
    благодарностей и «неукоснительно»;
  • требования проверяемы — с числами: проветривание 2 часа, +12 °C зимой,
    снег 50 см, зазор 30 см; с парной — 90 °C у верхнего полка, с дровяной —
    чистка дымохода раз в 2 месяца и следы перекала;
  • печь по виду: у дровяной нет электрической и наоборот, у электрической
    нет дымохода, дров и бака; без парной нет ни печи, ни бани, ни парной;
  • коротко: пункт не длиннее 400 знаков, весь текст не длиннее 7 500
    (прежние правила — 16 087);
  • вид печи берётся из расчёта: дровяная отмечена — дровяная, электрическая
    или её монтаж — электрическая, печи нет при парной — обе; парной и печи
    нет — раздела нет.

    python3 check_rules_v3.py
"""
