#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Фирменный цвет берётся из палитры, а не вписывается руками.

24.09.2026 все бирюзовые оттенки калькулятора, листа клиента и оболочек
справки переведены на переменные `--br-NN` из одного блока — чтобы цвет можно
было сменить одним действием (`scratchpad/палитра.py собрать <тон>`). Такая
структура держится ровно до первой правки, где кто-нибудь впишет `#1e6c72`
прямо в правило: на экране это неотличимо, а при смене цвета эта строка
останется бирюзовой посреди синего.

Проба отвечает на два вопроса:

  • нет ли фирменного цвета, вписанного руками, — тот же разбор, которым
    файл переводился (`палитра.py остаток`), по всем четырём файлам;
  • совпадает ли блок палитры в `index.html` и `404.html` — лист клиента
    живёт отдельной страницей, и разошедшиеся блоки дали бы клиенту другой
    цвет, чем менеджеру.

И третий, про само «одно действие»: палитра, собранная на другой тон и
собранная обратно, возвращает файлы байт в байт.

    python3 check_palette_raw.py
"""
import importlib.util
import pathlib
import sys

ЗДЕСЬ = pathlib.Path(__file__).resolve().parent
спец = importlib.util.spec_from_file_location("палитра", ЗДЕСЬ.parent / "палитра.py")
П = importlib.util.module_from_spec(спец)
спец.loader.exec_module(П)

НАХОДКИ = []

ост = П.остаток(печать=False)
for м in ост[:20]:
    НАХОДКИ.append(f"{м['файл']}: #{м['ш6']} вписан руками — возьми переменную палитры")
if len(ост) > 20:
    НАХОДКИ.append(f"… и ещё {len(ост) - 20}")


def блок(путь):
    т = путь.read_text(encoding="utf-8")
    н, к = т.find(П.НАЧАЛО), т.find(П.КОНЕЦ)
    return т[н:к] if н >= 0 and к >= 0 else None


блоки = {путь.name: блок(путь) for путь, вид in П.ФАЙЛЫ if вид == "блок"}
for имя, б in блоки.items():
    if б is None:
        НАХОДКИ.append(f"{имя}: блока палитры нет")
if len({б for б in блоки.values() if б}) > 1:
    НАХОДКИ.append("блоки палитры в index.html и 404.html разошлись — клиент увидит другой цвет")

# «Одно действие» туда и обратно — без следа.
было = {путь: путь.read_bytes() for путь, вид in П.ФАЙЛЫ if вид == "блок"}
try:
    П.собрать("215")
    сменилось = [путь.name for путь in было if путь.read_bytes() != было[путь]]
    if len(сменилось) != len(было):
        НАХОДКИ.append("сборка на тон 215° тронула не все файлы с блоком: " + ", ".join(сменилось))
    П.собрать("эталон")
    for путь, байты in было.items():
        if путь.read_bytes() != байты:
            НАХОДКИ.append(f"{путь.name}: после сборки туда и обратно файл не вернулся байт в байт")
finally:
    for путь, байты in было.items():
        путь.write_bytes(байты)

if НАХОДКИ:
    print("НАХОДКИ:")
    for н in НАХОДКИ:
        print("  ✗", н)
    sys.exit(1)
print(f"Чисто: вписанных руками фирменных цветов нет ни в одном из {len(П.ФАЙЛЫ)} файлов, "
      "блоки палитры у калькулятора и листа клиента одинаковые, а смена тона и "
      "возврат к бирюзе проходят без следа.")
