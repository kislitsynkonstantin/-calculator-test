#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Фирменный цвет берётся из палитры, а не вписывается руками.

24.09.2026 все бирюзовые оттенки калькулятора, листа клиента и оболочек
справки переведены на переменные `--br-NN` из одного блока — чтобы цвет можно
было сменить одним действием (`scratchpad/палитра.py собрать <тон>`). Такая
структура держится ровно до первой правки, где кто-нибудь впишет `#1e6c72`
прямо в правило: на экране это неотличимо, а при смене цвета эта строка
останется бирюзовой посреди синего.

Проба отвечает на два вопроса:

  • нет ли фирменного цвета, вписанного руками, — тот же разбор, которым
    файл переводился (`палитра.py остаток`), по всем четырём файлам;
  • совпадает ли блок палитры в `index.html` и `404.html` — лист клиента
    живёт отдельной страницей, и разошедшиеся блоки дали бы клиенту другой
    цвет, чем менеджеру.

И третий, про само «одно действие»: палитра, собранная на другой тон и
собранная обратно, возвращает файлы байт в байт — вместе с картинками.

Четвёртый — картинки (Константин 24.09.2026: «лого тоже под тему день/ночь
перекрась под синюю»): логотип вшит в страницу картинкой PNG, лежит файлом в
`assets/`, а значок приложения и значок вкладки несут цвет в себе. Палитра до
них не доставала, и на синей теме крыша логотипа оставалась бирюзовой. Пока
тон не эталонный, ни в одной вшитой картинке, ни в файле логотипа, ни в
значке вкладки не должно быть бирюзового пикселя.

    python3 check_palette_raw.py
"""
import importlib.util
import pathlib
import sys

ЗДЕСЬ = pathlib.Path(__file__).resolve().parent
спец = importlib.util.spec_from_file_location("палитра", ЗДЕСЬ.parent / "палитра.py")
П = importlib.util.module_from_spec(спец)
спец.loader.exec_module(П)

НАХОДКИ = []

ост = П.остаток(печать=False)
for м in ост[:20]:
    НАХОДКИ.append(f"{м['файл']}: #{м['ш6']} вписан руками — возьми переменную палитры")
if len(ост) > 20:
    НАХОДКИ.append(f"… и ещё {len(ост) - 20}")


def блок(путь):
    т = путь.read_text(encoding="utf-8")
    н, к = т.find(П.НАЧАЛО), т.find(П.КОНЕЦ)
    return т[н:к] if н >= 0 and к >= 0 else None


блоки = {путь.name: блок(путь) for путь, вид in П.ФАЙЛЫ if вид == "блок"}
for имя, б in блоки.items():
    if б is None:
        НАХОДКИ.append(f"{имя}: блока палитры нет")
if len({б for б in блоки.values() if б}) > 1:
    НАХОДКИ.append("блоки палитры в index.html и 404.html разошлись — клиент увидит другой цвет")

# Картинки идут за тоном.
import base64
import io
import re
from PIL import Image


def ночная_темнее(байты):
    """Картинка с белым рисунком стоит на тёмном фоне: её фирменный цвет
    должен остаться той же яркости для глаза, что бирюзовый в оригинале
    (#2a8f97 у крыши логотипа, #1e6c72 у значка приложения), — иначе крыша
    ночного логотипа тонет в фоне (повёрнутый синий давал 2,4:1 вместо 4,5:1)."""
    им = Image.open(io.BytesIO(байты)).convert("RGBA")
    цвета = [(н, (r, g, b)) for н, (r, g, b, a) in им.getcolors(1 << 24) if a > 200]
    нейтр = [(н, sum(ц)) for н, ц in цвета if not П.фирменный(П.rgb_шестн(*ц)) and max(ц) - min(ц) < 8]
    if not нейтр or sum(н * с for н, с in нейтр) / sum(н for н, _ in нейтр) <= 3 * 128:
        return None
    цветные = sorted([(н, ц) for н, ц in цвета if max(ц) - min(ц) > 40], reverse=True)
    if not цветные:
        return None
    главный = П.rgb_шестн(*цветные[0][1])
    я = П.яркость(главный)
    return None if any(abs(я / П.яркость(эт) - 1) < 0.03 for эт in ("2a8f97", "1e6c72")) else главный


def бирюзовых(байты):
    им = Image.open(io.BytesIO(байты)).convert("RGBA")
    return sum(н for н, (r, g, b, a) in им.getcolors(1 << 24) if a and П.фирменный(П.rgb_шестн(r, g, b)))


тон_сейчас = П.текущий_тон()
if тон_сейчас != "эталон":
    for путь, вид in П.ФАЙЛЫ:
        if вид != "блок":
            continue
        т = путь.read_text(encoding="utf-8")
        for н, к in enumerate(re.findall(r"data:image/png;base64,([A-Za-z0-9+/=]+)", т)):
            if бирюзовых(base64.b64decode(к)):
                НАХОДКИ.append(f"{путь.name}: вшитая картинка №{н + 1} осталась бирюзовой при тоне {тон_сейчас}")
            темнее = ночная_темнее(base64.b64decode(к))
            if темнее:
                НАХОДКИ.append(f"{путь.name}: картинка №{н + 1} с белым рисунком получила #{темнее} — "
                               "яркость не бирюзовая, на тёмном фоне контраст уйдёт")
        for м in П.ЗНАЧОК.finditer(т):
            if П.фирменный(м.group(2).lower()):
                НАХОДКИ.append(f"{путь.name}: значок вкладки остался бирюзовым (#{м.group(2)})")
    for путь in П.ФАЙЛЫ_КАРТИНОК:
        if бирюзовых(путь.read_bytes()):
            НАХОДКИ.append(f"assets/{путь.name}: логотип на домене остался бирюзовым")
        темнее = ночная_темнее(путь.read_bytes())
        if темнее:
            НАХОДКИ.append(f"assets/{путь.name}: белый логотип получил #{темнее} — яркость не бирюзовая")

# «Одно действие» туда и обратно — без следа, от той палитры, что стоит сейчас.
было = {путь: путь.read_bytes() for путь, вид in П.ФАЙЛЫ if вид == "блок"}
было.update({путь: путь.read_bytes() for путь in П.ФАЙЛЫ_КАРТИНОК})
текущий = П.текущий_тон()
другой = "эталон" if текущий != "эталон" else "215"
try:
    П.собрать(другой)
    сменилось = [путь.name for путь in было if путь.read_bytes() != было[путь]]
    if len(сменилось) != len(было):
        НАХОДКИ.append(f"сборка на тон {другой} тронула не все файлы с блоком: " + ", ".join(сменилось))
    П.собрать(текущий)
    for путь, байты in было.items():
        if путь.read_bytes() != байты:
            НАХОДКИ.append(f"{путь.name}: после сборки туда и обратно файл не вернулся байт в байт")
finally:
    for путь, байты in было.items():
        путь.write_bytes(байты)

if НАХОДКИ:
    print("НАХОДКИ:")
    for н in НАХОДКИ:
        print("  ✗", н)
    sys.exit(1)
print(f"Чисто: вписанных руками фирменных цветов нет ни в одном из {len(П.ФАЙЛЫ)} файлов, "
      "блоки палитры у калькулятора и листа клиента одинаковые, логотип и значки идут "
      "за тоном, белый логотип держит яркость, а смена тона и возврат к прежней "
      "палитре проходят без следа.")
